def scene(label,r,vertices=72,theorem=False):
    names=['A',*['_vertex'+str(i) for i in range(1,vertices)]]
    points={s:(round(r*cos(2*pi*i/vertices),10),round(r*sin(2*pi*i/vertices),10)) for i,s in enumerate(names)}
    points['T']=(0,0);points['U']=(-r,-r-.7);points['W']=(1-r,-r-.7)
    edges=[('T','A'),('U','W')]+list(zip(names,names[1:]+names[:1],strict=True))
    if theorem:
        points['B']=points.pop(names[1]);edges=[tuple('B' if s==names[1] else s for s in pair) for pair in edges];names[1]='B'
        points['H']=tuple((points['A'][k]+points['B'][k])/2 for k in (0,1))
        edges.extend([('T','H'),('T','B'),('H','A')])
    return graph(label,points,edges=edges,circle=('T',r)),names


def decorate(e,vs,note):
    e['source']['chapter']='XIII';e['review']['reviewer']='Атанасян 7–9, 2023: п. 120 на с. 305–306, постановка №1205 на с. 308 и все 8 столбцов таблицы с продолжением на с. 309, два подпункта №1206 на с. 309, ключ с. 401.'
    m=e['visualization']['model'];m['description']=note;e['visualization']['caption']=note
    for i,(v,src) in enumerate(zip(m['views'].values(),[vs[0],*vs,*vs],strict=True)):
        suffix='__v'+str(i);ids={name:k for k in v['points'] for name in m['labels'][k].split('=')}
        v['polygons']=[[n+suffix for n in src[1]]]
        if 'H' in ids:
            v['circles'].append({'center':ids['T'],'through':ids['H']})
            v['rightAngles']=[{'vertex':ids['H'],'a':ids['T'],'b':ids['A'],'size':1.4}]
            v['highlightSegments']=[[ids['T'],ids['A']],[ids['T'],ids['H']],[ids['A'],ids['B']]]
        else:v['highlightSegments']=[[ids['T'],ids['A']]]
    return e


