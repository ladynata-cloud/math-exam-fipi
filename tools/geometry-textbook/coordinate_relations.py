def parameters():
    # Coefficients moved to the left: (p+q*x+r*y)a + (s+t*x+u*y)b = 0.
    specs=[
        ('а','3a−xb=ya+b',(3,0,-1),(-1,-1,0),Fraction(-1),Fraction(3),
         'При a сравни 3 и y, поэтому y=3. При b слева стоит −x, справа +1, значит −x=1 и x=−1.',
         'Чему равно y из коэффициента при a?', '3','Слева 3a, справа ya, поэтому y=3.',
         'При замене правого слагаемого +b на +4b как изменится x?', '-4','Теперь −x=4.'),
        ('б','4a−xa+5b+yb=0',(4,-1,0),(5,0,1),Fraction(4),Fraction(-5),
         'У a коэффициент 4−x, у b — 5+y. Каждый равен нулю. Следовательно x=4, y=−5.',
         'Чему равен y из 5+y=0?', '-5','Вычти 5 из обеих частей.',
         'В новом равенстве (7−x)a+(5+y)b=0 какое нужно x?', '7','Коэффициент 7−x должен обнулиться.'),
        ('в','xa+3b−yb=0',(0,1,0),(3,0,-1),Fraction(0),Fraction(3),
         'Собери xa+(3−y)b=0. Отсюда x=0 и 3−y=0, то есть y=3. Коэффициенты при a и b нельзя компенсировать друг другом.',
         'Какое x необходимо в исходном равенстве?', '0','Единственный член при a — xa.',
         'В сходном примере xa−7b−yb=0 чему равно y?', '-7','Положи −7−y=0.'),
        ('г','a+b−3ya+xb=0',(1,0,-3),(1,1,0),Fraction(-1),Fraction(1,3),
         'После группировки имеем (1−3y)a+(1+x)b=0. Поэтому 3y=1 и x=−1. В ответе сначала укажи x, затем y.',
         'Найди y из 1−3y=0.', '1/3','Раздели 1 на 3.',
         'При замене a на 2a в первом слагаемом уравнение при a станет 2−3y=0. Чему равно y?', '2/3','Раздели 2 на 3.')]
    result=[]
    for part,equation,ca,cb,x,y,reason,p1,a1,h1,p2,a2,h2 in specs:
        def view(label,chosen_x,chosen_y):
            u=ca[0]+ca[1]*chosen_x+ca[2]*chosen_y
            v=cb[0]+cb[1]*chosen_x+cb[2]*chosen_y
            # Two coordinate axes for the residual; coincident tips are represented once.
            p=dict(X=(-4,3),A=(-3,3),B=(-4,4),O=(0,0));arrows=[('X','A'),('X','B')]
            for name,delta in [('H',(float(u),0)),('P',(float(u),float(v)))]:
                if delta not in p.values():p[name]=delta
            loc=lambda xy:next(k for k,z in p.items() if z==xy)
            h,p_final=loc((float(u),0)),loc((float(u),float(v)))
            for a,b in [('O',h),(h,p_final),('O',p_final)]:
                if a!=b and (a,b) not in arrows:arrows.append((a,b))
            return frame(f'{label}, x={chosen_x}, y={chosen_y}',p,arrows)
        trial=view('Пример, где равенство нарушено',x+1,y+1);one=view('Выполнено лишь одно условие',x,y+1);good=view('Оба остатка нулевые',x,y)
        e=math_card(1003,part,question=f'Векторы a и b неколлинеарны. Найди такие x и y, чтобы выполнялось {equation}.',
            answer=reason,hint='Перенеси всё в левую часть. Собери отдельно множители при a и при b. Нулевой вектор имеет только два нулевых коэффициента.',
            steps=[('Сгруппируй по стрелкам',f'Начни с {equation}. Приведи равенство к виду Ua+Vb=0. На первом рисунке показана попытка, где обе поправки ещё необходимы.','При сложении коэффициентов нельзя смешивать разные базисные векторы.'),
                   ('Приравняй каждый коэффициент к нулю',reason,'Разложение нуля по независимым a,b единственно: U=0 и V=0.'),
                   ('Подставь найденные параметры',f'Возьми x={x}, y={y}. Тогда каждый множитель при a и b равен 0. На схеме остались лишь две стрелки выбранного базиса, а конечная точка суммарного остатка совпала с O.','Одна выполненная скалярная часть ещё не подтверждает равенства векторов.')],
            frames=[trial,trial,one,good],cases=[trial,one,good],prompts=[(p1,a1,h1),(p2,a2,h2)])
        values=[f'{x};{y}',f'{x}; {y}',f'({x};{y})',f'({x}; {y})']
        if y.denominator==3:values.extend([f'{x};⅓',f'{x}; ⅓'])
        e['answer']={'mode':'exact','accepted':values,'prompt':'Введи x и y через точку с запятой в порядке x;y. Для дроби используй черту.',
                     'feedback':{'а':'У b сравни −x с +1; проверь знак и порядок x;y.','б':'У b должно обнулиться 5+y, а не 5−y.','в':'У единственного члена xa коэффициент тоже должен равняться нулю.','г':'При a число 3 умножает y. Проверь оба коэффициента и порядок x;y.'}[part]}
        result.append(e)
    return result


