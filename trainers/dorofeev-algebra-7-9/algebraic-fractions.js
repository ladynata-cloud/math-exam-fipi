    ['(4a² − 20a + 25)/(2a − 5)','2a − 5','Квадрат разности (2a − 5)² раскрывается в 4a² − 20a + 25. У дроби a ≠ 5/2.',s=>{const a=s+3;return['a = '+a,2*a-5,2*a-5,4*a*a-20*a+25];}],
    ['(3m³ − 6m² − 3m)/(m² − 2m − 1)','3m','Вынеси 3m из всех трёх слагаемых. Остаётся m² − 2m − 1, который при делении должен отличаться от нуля.',s=>{const m=s+3;return['m = '+m,m*m-2*m-1,3*m,3*m**3-6*m*m-3*m];}],
    ['(4a² − 11a − 3)/(a − 3)','4a + 1','(a − 3)(4a + 1) = 4a² + a − 12a − 3. Выражение слева определено при a ≠ 3.',s=>{const a=s+4;return['a = '+a,a-3,4*a+1,4*a*a-11*a-3];}]
