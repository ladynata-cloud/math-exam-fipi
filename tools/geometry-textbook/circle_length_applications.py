def arc(label,r,angle,teeth=0):
    theta=angle*pi/180
    p={'T':(0,0),'A':(r,0),'B':(round(r*cos(theta),10),round(r*sin(theta),10)),'U':(-r,-r-.85),'W':(1-r,-r-.85)}
    edges=[('T','A'),('T','B'),('U','W')]
    arc_ids=['A']
    for j in range(1,24):
        k='_arc'+str(j);p[k]=(r*cos(theta*j/24),r*sin(theta*j/24));arc_ids.append(k)
    arc_ids.append('B');curve=list(zip(arc_ids,arc_ids[1:]))
    edges.extend(curve)
    for j in range(teeth):
        a=2*pi*j/teeth;k1='_toothInner'+str(j);k2='_toothOuter'+str(j)
        p[k1]=(.94*r*cos(a),.94*r*sin(a));p[k2]=(1.06*r*cos(a),1.06*r*sin(a));edges.append((k1,k2))
    g=graph(label,p,edges=edges,circle=('T',r))
    return (*g[:3],curve)


def orbit(label,earth,alt,scale):
    # Literal Earth/orbit radii are in km. Normalisation changes only the drawing's unit.
    e=earth/scale;o=(earth+alt)/scale
    p={'T':(0,0),'A':(e,0),'B':(o,0),'D':(0,o),'U':(-o,-o-.7),'W':(-o+1,-o-.7)}
    return graph(label,p,edges=[('T','A'),('A','B'),('T','D'),('U','W')],circle=('T',o))


