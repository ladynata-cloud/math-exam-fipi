def river_view(label,base,alpha,beta,mark):
    ac=base*sin(radians(beta))/sin(radians(alpha+beta));x=ac*cos(radians(alpha));y=ac*sin(radians(alpha))
    pts={'A':(0,0),'B':(base/10,0),'C':(x/10,y/10)}
    edges=[('A','B'),('A','C'),('B','C')]
    if mark:pts['H']=(x/10,0);edges.extend([('C','H'),('A','H'),('B','H')])
    banks=[((0,0),(base/10,0)),((0,y/10),(base/10,y/10))]
    return graph(label,pts,edges=edges,lines=banks)


