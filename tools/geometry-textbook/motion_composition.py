def construction(title, points, edges, guides):
    xmin=min(x for x,y in points.values())
    ymin=min(y for x,y in points.values())-1.25
    return graph(title,{**points,'U':(xmin,ymin),'W':(xmin+1,ymin)},
                 edges=[*edges,('U','W')],lines=guides)


def shifted(title,width,by):
    source={'A':(0,0),'B':(width,0),'C':(1,2)}
    image={n+'′':(x+by,y) for n,(x,y) in source.items()}
    axes=[((x,-1),(x,3)) for x in (by/2,width+by/2)]
    return construction(title,{**source,**image},[*TRI,*[(a+'′',b+'′') for a,b in TRI]],axes)


