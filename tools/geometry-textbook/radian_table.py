def finish(e,hint,caption):
    e['source']['chapter']='XIII';e['review']['reviewer']='Издание Атанасяна 2023: п. 119 на с. 304–305, №1203 на с. 308. В таблице 13 столбцов данных, из них первый уже целиком заполнен; все 12 пропусков проверены по своим столбцам.'
    e['visualization']['caption']=caption;m=e['visualization']['model'];m['description']=caption
    for v in m['views'].values():
        labels={name:k for k in v['points'] for name in m['labels'][k].split('=')}
        m.setdefault('labelOffsets',{}).update({labels['A']:[3,3],labels['B']:[-2,-5]})
