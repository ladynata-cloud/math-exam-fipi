def trapezoid_view(label,base,angle,feet):
    flank=base/(1+2*cos(radians(angle)));x=flank*cos(radians(angle));y=flank*sin(radians(angle))
    pts={'A':(0,0),'B':(base,0),'C':(base-x,y),'D':(x,y)}
    edges=[('A','B'),('B','C'),('C','D'),('D','A')]
    if feet:
        pts.update({'H':(x,0),'K':(base-x,0)})
        edges.extend([('D','H'),('C','K'),('A','H'),('B','K')])
    return graph(label,pts,edges=edges)


