"""Build the browser bank from the reviewed authoring source (no network)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEST_ONLY = {'oracle', 'oracles', 'oracleValues', 'web_reference', 'reference'}


def clean(value):
    if isinstance(value, dict):
        return {key: clean(item) for key, item in value.items() if key not in TEST_ONLY}
    if isinstance(value, list):
        return [clean(item) for item in value]
    return value


def build():
    source = json.loads((ROOT / 'content/full_data.json').read_text())
    payload = json.dumps(clean(source), ensure_ascii=False, separators=(',', ':'))
    return ('/* Generated by build.py from content/full_data.json. */\n'
            '(function(root){\n\"use strict\";\nconst data=' + payload + ';\n'
            'if(typeof module!==\"undefined\"&&module.exports)module.exports=data;\n'
            'else root.VPR_DATA=data;\n'
            '})(typeof window!==\"undefined\"?window:globalThis);\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'data.js'
    expected = build()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('VPR data.js is stale: run python trainers/vpr-math/build.py')
        print('VPR_DATA_BUILD_OK')
    else:
        target.write_text(expected)
        print('Built trainers/vpr-math/data.js')
