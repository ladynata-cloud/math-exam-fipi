'use strict';

// Keep the cabinet's small static projection in sync with the canonical course map.
// The account server only serves its own reviewed assets; it loads no remote script.
const fs = require('node:fs');
const path = require('node:path');
const map = require('../ege-profil/exam-map.js');
const target = path.join(__dirname, '../learning/profile-exam-catalog.js');
const project = entry => ({ number: entry.number, title: entry.title, entry: entry.entry, href: map.href(entry) });
const projection = map.entries.filter(entry => entry.part === 1).map(project);
const secondPart = map.entries.filter(entry => entry.part === 2).map(project);
const extras = map.extras.map(project);
const source = '// Generated by tools/build-profile-exam-catalog.cjs from ege-profil/exam-map.js.\n' +
  '// Do not edit this projection by hand.\n' +
  '(function(root){\n  \'use strict\';\n  const exams=' + JSON.stringify(projection, null, 2) + ';\n' +
  '  const secondPart=' + JSON.stringify(secondPart, null, 2) + ';\n' +
  '  const extras=' + JSON.stringify(extras, null, 2) + ';\n' +
  '  const api={exams,secondPart,extras};\n  root.ProfileExamCatalog=api;\n' +
  '  if(typeof module!==\'undefined\'&&module.exports)module.exports=api;\n' +
  '})(typeof globalThis!==\'undefined\'?globalThis:window);\n';
// The board picker normalizes links synchronously. Its small generated adapter
// keeps one source of truth without a new script on the shared board shell.
const pickerTarget = path.join(__dirname, '../trainers/board-picker.js');
const pickerText = fs.readFileSync(pickerTarget, 'utf8');
const routePattern = /\/\/ BEGIN PROFILE_FIPI_ROUTES:[^\n]*\n[\s\S]*?\/\/ END PROFILE_FIPI_ROUTES/;
if (!routePattern.test(pickerText)) throw new Error('Missing generated profile board route block');
// Preserve the original board URLs for the shipped wrappers. Later wrappers
// use current FIPI numbers, including the two separate calculus units that
// originally shared the same legacy #exam/9 overview.
const legacyBoardEntries = new Set(['planimetry', 'vectors', 'stereometry', 'probability',
  'equations', 'expressions', 'random-variables']);
const mirrored = [...map.entries.filter(entry => entry.part === 1), map.topic('random-variables')];
const boardCourses = mirrored.map(entry => {
  const official = map.hash(entry);
  const legacy = entry.legacyStart === 9 ? null : String(entry.legacyStart);
  const landing = legacyBoardEntries.has(entry.id) ? '#exam/' + legacy : official;
  // Direct graph links keep the established log/trig classroom. Both number
  // overviews can still open every lesson in their own course.
  const lessons = entry.lessonIds.filter(id => id !== 'fn-explog');
  if (entry.id === 'derivative') lessons.push(...entry.preparationIds);
  return { official, legacy, landing, file: 'ege-profile-' + entry.id + '.html', lessons };
});
const rows = boardCourses.map(course => ' ' + JSON.stringify(course)).join(',\n');
const pickerSource = pickerText.replace(routePattern,
  '// BEGIN PROFILE_FIPI_ROUTES: generated by tools/build-profile-exam-catalog.cjs.\n' +
  'const PROFILE_BOARD_COURSES = [\n' + rows + '\n];\n' +
  '// END PROFILE_FIPI_ROUTES');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source || pickerText !== pickerSource) {
    console.error('Profile exam catalogue or board route projection is stale. Run node tools/build-profile-exam-catalog.cjs');
    process.exitCode = 1;
  } else console.log('PROFILE_EXAM_CATALOG_CURRENT');
} else {
  fs.writeFileSync(target, source);
  fs.writeFileSync(pickerTarget, pickerSource);
  console.log('PROFILE_EXAM_CATALOG_WRITTEN');
}
