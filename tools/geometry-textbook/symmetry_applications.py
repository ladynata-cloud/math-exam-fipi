def axes_figure(title,n,r):
    points={'T':(0,0)}
    names='ABCD'[:n]
    for i,k in enumerate(names):
        theta=pi/2+2*pi*i/n
        points[k]=(round(r*cos(theta),9),round(r*sin(theta),9))
    axes=[]
    for k in range(n):
        alpha=pi/2+k*pi/n
        x,y=(r+.35)*cos(alpha),(r+.35)*sin(alpha)
        axes.append(((-x,-y),(x,y)))
    return diagram(title,points,[(a,names[(i+1)%n]) for i,a in enumerate(names)],axes)


def strip():
    points={'A':(0,1),'B':(3,1),'A′':(3,1),'B′':(6,1),'K':(0,0),'L':(0,2)}
