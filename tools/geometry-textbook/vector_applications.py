def add(p,q):return tuple(x+y for x,y in zip(p,q))


def difference(p,q):return tuple(x-y for x,y in zip(p,q))


def application(n,**kwargs):
    card=build_card(n,pages=[242] if n<=977 else [243],**kwargs)
    card['help'][1]['theoryIds']=['atanasyan-7-9-theory-92-part-1','atanasyan-7-9-theory-89-part-1']
