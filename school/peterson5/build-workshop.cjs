'use strict';
const fs=require('node:fs'),path=require('node:path'),M=require('./math.js');
const read=name=>JSON.parse(fs.readFileSync(path.join(__dirname,name),'utf8'));
const lessons=read('theory.json'),input=[...read('workshop-part1.json'),...read('workshop-part2.json')];
const ids=new Set(),kinds=new Set(['number','choice','set']);
function task(raw,id,step=false){
 if(!raw||!kinds.has(raw.kind)||typeof raw.prompt!=='string'||raw.prompt.trim().length<8||typeof raw.answer!=='string'||!raw.explanation?.trim())throw Error('Incomplete task '+id);
 if(ids.has(id))throw Error('Duplicate id '+id);ids.add(id);
 const q={...raw,id};
 if(q.kind==='number'&&!M.check(q.answer,q.answer,q.answerFormat))throw Error('Invalid numeric answer '+id);
 if(q.kind==='choice'){
  if(!Array.isArray(q.choices)||q.choices.length<2||new Set(q.choices).size!==q.choices.length||!q.choices.includes(q.answer))throw Error('Invalid choices '+id);
  const n=[...id].reduce((a,c)=>a+c.charCodeAt(0),0)%q.choices.length;
  q.choices=[...q.choices.slice(n),...q.choices.slice(0,n)];
 }
 if(q.kind==='set'){
  const values=q.answer.trim().split(/[\s,;]+/);
  if(!values.every(v=>/^\d+$/.test(v)&&Number.isSafeInteger(Number(v)))||new Set(values.map(Number)).size!==values.length)throw Error('Invalid finite set '+id);
 }
 if(!step){
  if(!q.hint?.trim())throw Error('Missing hint '+id);
  q.steps=(q.steps||[]).map((s,i)=>task(s,id+'-step-'+(i+1),true));
 }
 return q;
}
if(input.length!==43||new Set(input.map(t=>t.id)).size!==43)throw Error('Expected exactly 43 distinct topics');
const topics=lessons.map(l=>{
 const t=input.find(t=>t.id===l.id);
 if(!t||!t.goal?.trim()||!t.why?.trim()||t.practice?.length!==2||t.check?.length!==3)throw Error('Incomplete topic '+l.id);
 return {id:l.id,title:l.title,part:l.part,page:l.page,model:l.model,goal:t.goal,why:t.why,
  discovery:task(t.discovery,l.id+'-discover'),
  practice:t.practice.map((q,i)=>task(q,l.id+'-practice-'+(i+1))),
  check:t.check.map((q,i)=>task(q,l.id+'-check-'+(i+1)))};
});
const out='/* Generated by build-workshop.cjs. Original exercises; not textbook exercise numbers. */\nwindow.PetersonWorkshopData = '+JSON.stringify({version:1,edition:'Дорофеев — Петерсон, 5 класс, две части, 2019',topics},null,2)+';\n';
const target=path.join(__dirname,'workshop-data.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('workshop-data.js is out of date');}else fs.writeFileSync(target,out);
console.log('PETERSON5_WORKSHOP_CONTENT_OK: 43 topics, 43 investigations, 86 practice tasks, 129 check tasks; '+ids.size+' validated task/step IDs.');
