export function answerCabinetOffline(input, cards) {
  if (input && Object.hasOwn(input, 'courseContext')) return answerCourseOffline(input, cards);
  const safe = checked(input), selected = selectedCards(safe, cards), card = selected[0];
  let solved = arithmetic(safe.topic, safe.question);
  if (safe.topic === 'decimal-compare') solved = compare(safe.question);
  if (safe.topic === 'decimal-rounding') solved = rounding(safe.question);
  if (safe.topic === 'decimal-place-value') solved = placeValue(safe.question);
  if (safe.topic === 'decimal-fractions') solved = conversion(safe.question);
  const sources = selected.map(row => ({ id: row.id, title: row.title, url: row.source.url }));
  const common = { topic: safe.topic, sources, sourceIds: selected.map(row => row.id) };
  if (solved) {
    const complete = safe.mode === 'explain';
    let note = feedback(safe.attempt, solved.expected);
    if (solved.comparison && safe.attempt) note = /^[<>=]$/.test(safe.attempt)
      ? safe.attempt === solved.comparison ? 'Знак сравнения подходит.' : 'Проверь знак сравнения по разрядам.'
      : 'Для проверки сравнения введи один знак: <, > или =.';
    return { ...common, title: solved.title,
      text: [safe.simpler ? 'Сделаем одно маленькое действие.' : solved.text, note].filter(Boolean).join(' '),
      steps: complete ? solved.steps : [(safe.simpler ? solved.shorts : solved.hints)[Math.min(safe.hintLevel - 1, solved.hints.length - 1)]],
      check: complete ? solved.check : 'Выполни только этот шаг. Ранее показанные подсказки можно оставить перед глазами.',
      verification: 'deterministic', complete };
  }
  const caution = geometryCaution(safe);
  const concept = conceptTerms[safe.topic].test(normalize(safe.question)) && !/[\d=]/u.test(safe.question) && /^(?:как|что|почему|зачем|когда|чем|какие|какой|какая|можно|объясни|напомни|правило|формула)(?:\s|[?!.,:]|$)/iu.test(safe.question)
    && !/рисунк|чертеж|докаж|найди|вычисли/iu.test(safe.question);
  const complete = safe.mode === 'explain' && (concept || Boolean(caution));
  const steps = caution?.steps || card.steps;
  return { ...common, title: card.title,
    text: caution?.text || (concept ? (safe.simpler ? card.explanation.split(/(?<=[.!?])\s+/u)[0] : card.explanation)
      : 'Здесь есть проверенное правило по теме, но конкретное решение этой задачи ещё не проверено. Для геометрии укажи все данные и расположение точек; для вычисления можно использовать формат примера выбранной темы.'),
    steps: complete ? steps : [(safe.simpler && !caution ? shorterGeometry[safe.topic] || steps : steps)[Math.min(safe.hintLevel - 1, steps.length - 1)]],
    check: card.check, verification: concept || caution ? 'curated-guidance' : 'needs-teacher', complete };
}

