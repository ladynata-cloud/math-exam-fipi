'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
const {steps: previousSteps, storageKey: previousKey, createStore: previousStore, grouping} = require('../trainers/like-terms-factory-polynomials.js');
const {steps, grade, createStore, cleanProgress, storageKey} = grouping;
const step = id => steps.find(s=>s.id===id);
const answer = id => step(id).fields.map(f=>f.expected);
const check = (id, vals, status, index) => { const r=grade(step(id),vals); assert.equal(r.status,status,id+': '+vals); assert.equal(r.done,status==='correct'); if(index!==undefined)assert.equal(r.index,index); };
test('all eight fixtures, two independent checkpoints, stable prior IDs and key',()=>{
  assert.deepEqual(previousSteps.map(s=>s.id),['standard','degree','distribute','factor','factor-two-letters','independent-factor','independent-area']);
  assert.equal(previousKey,'likeTermsFactory.polynomials.v1');
  assert.equal(storageKey,'likeTermsFactory.grouping.v1');
  assert.equal(steps.length,8);
  assert.equal(new Set(steps.map(s=>s.id)).size,8);
  assert.equal(steps.filter(s=>s.checkpoint).length,2);
  for(const s of steps) check(s.id,answer(s.id),'correct');
  check('multiply',['10+2x+5x+x²','10+7x+x²'],'correct');
  check('common-binomial',['3a','5','2+x','5+3a','10+5x+6a+3xa'],'correct');
  check('opposite',['-5','-5+2a','-3+x','15-5x-6a+2ax'],'correct');
  check('square-sum',['9+3x+x²+3x','9+x²+6x'],'correct');
  check('square-difference',['9-6x+4x²-6x','9-12x+4x²'],'correct');
  check('conjugates',['-9-6x+4x²+6x','-9+4x²'],'correct');
});
test('distribution must show four terms; incorrect signs and missing cross terms fail',()=>{
  check('multiply',['x²+7x+10','x²+7x+10'],'terms',0);
  check('multiply',['x²+5x+2x+10','x²+5x+2x+10'],'collect',1);
  check('square-sum',['x²+9','x²+9'],'wrong',0);
  check('square-sum',['x²+6x+9','x²+6x+9'],'terms',0);
  check('square-difference',['4x²-6x-6x-9','4x²-12x+9'],'wrong',0);
  check('square-difference',['4x²-6x-6x+9','4x²+12x+9'],'wrong',1);
  check('conjugates',['4x²+6x-6x+9','4x²+9'],'wrong',0);
  check('conjugates',['4x²+6x-6x-9','4x²+6x-6x-9'],'collect',1);
  check('opposite',['5','2a-5','x-3','2ax-6a-5x+15'],'wrong',0);
  check('opposite',['-5','2a+5','x-3','2ax-6a-5x+15'],'wrong',1);
  check('common-binomial',['3','5','x+2','3a+5','3ax+6a+5x+10'],'wrong',0);
});
test('both valid grouping paths and either factor order; no mixed or expanded impostors',()=>{
  const g=step('independent-grouping');
  assert.equal(g.variants.length,8);
  for(const v of g.variants) check(g.id,v,'correct');
  check(g.id,['15x+10y','4xy+6x²','2x+5','2y+3x'],'correct');
  check(g.id,['6x²+15x','6x²+4xy','3x+2y','2x+5'],'wrong',1);
  check(g.id,['6x²+15x','4xy+10y','6x²+15x+4xy+10y','1'],'wrong',2);
  check(g.id,['6x²+15x','4xy+10y','-3x-2y','-2x-5'],'wrong',2);
  check('independent-squares',['2x+5','2x-5','-25-10x+10x+4x²','-25+4x²'],'correct');
  check('independent-squares',['2x-5','2x-5','4x²+10x-10x-25','4x²-25'],'wrong',1);
  check('independent-squares',['2x-5','2x+5','4x²-25','4x²-25'],'terms',2);
  check('independent-squares',['2x-5','2x+5','4x²+10x-10x-25',''],'empty',3);
});
test('separate progress, completed alternatives survive reload, two stores and storage denial',()=>{
  const values=new Map([['mathExamCourseProgress.v1','original'],['likeTermsFactory.brackets.v1','brackets'],[previousKey,JSON.stringify({current:'standard',records:{}})]]);
  const storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
  const old=previousStore(storage), before=values.get(previousKey), a=createStore(storage), b=createStore(storage);
  a.update(p=>{p.current='independent-grouping';p.records['independent-grouping'].drafts[0]='15x+10y';});
  b.update(p=>{p.records['independent-grouping'].drafts[1]='6x²+4xy';});
  assert.deepEqual(a.read().records['independent-grouping'].drafts,['15x+10y','6x²+4xy','','']);
  const alternate=step('independent-grouping').variants[7];
  b.update(p=>{Object.assign(p.records['independent-grouping'],{drafts:alternate,done:true,first:'correct',attempts:1});});
  assert.equal(a.read().records['independent-grouping'].done,true);
  assert.equal(cleanProgress({records:{'independent-grouping':{done:true,drafts:['0','0','0','0'],hints:8}}}).records['independent-grouping'].done,false);
  assert.equal(cleanProgress({records:{'independent-grouping':{hints:8}}}).records['independent-grouping'].hints,0);
  assert.equal(values.get('mathExamCourseProgress.v1'),'original');
  assert.equal(values.get('likeTermsFactory.brackets.v1'),'brackets');
  assert.equal(values.get(previousKey),before);
  assert.equal(old.read().current,'standard');
  const denied=createStore({getItem(){throw Error('denied')},setItem(){throw Error('denied')}});
  denied.update(p=>{p.records.multiply.drafts[0]='x²+';});
  assert.equal(denied.read().records.multiply.drafts[0],'x²+');
});
