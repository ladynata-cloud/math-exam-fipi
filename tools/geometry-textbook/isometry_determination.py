def proof(n, task, reason, hint, theory, steps, scenes, probes, prompt, caption):
    c = area(n,None,[319],task,reason,hint,steps,scenes,probes,refs=[123,124])
    c['source']['chapter']='XIV'
    c['review']['reviewer']='Атанасян и др., Геометрия 7–9, 2023, глава XIV, §1. Исходный номер и условие проверены по печатной с. 319 (страница PDF 320).'
