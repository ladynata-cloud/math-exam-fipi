(function(){
  'use strict';
  const {register,mark,q}=window.NikolskyInequalities;
  const fmt=n=>Number(n.toFixed(5)).toLocaleString('ru-RU',{useGrouping:false,maximumFractionDigits:5});
  const fraction=n=>'1/'+n;
  const codes={'<':-1,'>':1,'≤':-2,'≥':2,'=':0};
  const flip={'<':'>','>':'<','≤':'≥','≥':'≤','=':'='};
  const directions='Какой знак переносит правило? Введи −2 для ≤, −1 для <, 0 для =, 1 для > или 2 для ≥.';
  const common=[[15,'<',20],[5,'>',4],[2.5,'<',3],[1.1,'<',1.2],[1.3,'≥',1.2],[5,'≤',6]];
  const sets={
    6:common,
    7:[...common.slice(0,2),[-2.5,'<',3],...common.slice(3,5),[-5,'≤',6]],
    8:[[14,'>',11,10,'>',9],[-2,'>',-3,3,'>',2],[-6,'<',-5,2,'<',3],[-8,'≤',0,8,'≤',9]],
    9:[[14,'>',10,2,'>',1],[5,'>',3,6,'>',5],[6,'<',7,2,'<',3],[8,'<',9,1,'<',2]],
    10:[[3,'>',0],[5,'>',-1],[-9,'<',-1],[-5,'≤',-1],[9,'≥',-2],[0,'≤',3]],
    11:[[1,'<',2],[5,'>',4.5],[6.5,'≤',6.9],[1.1,'<',1.2],[1.3,'≥',1.2],[5,'≤',6]],
    12:[[6,'>',3],[7,'≤',10],[2,'<',4],[11,'<',12],[13,'≥',12],[15,'≤',26]]
  };
  const methods={
    6:['Сдвиг обеих границ','Прибавь к обеим частям одно число.','Один и тот же сдвиг сохраняет расстояние и направление сравнения.'],
    7:['Положительный масштаб','Умножь обе стороны на одно положительное число.','Положительный множитель увеличивает или уменьшает расстояние, сохраняя порядок.'],
    8:['Сложение двух неравенств','Сложи две пары почленно.','Сначала проверь одинаковое направление. Сложи левые границы и отдельно правые.'],
    9:['Произведение двух неравенств','Перемножь положительные стороны почленно.','Здесь все четыре числа положительны. Порядок сохраняется при каждом умножении.'],
    10:['Отражение относительно нуля','Замени оба числа противоположными.','Отражение меняет направление на прямой. Вид строгого или нестрогого сравнения сохраняется.'],
    11:['Отрицательный масштаб','Умножь обе части на одно отрицательное число.','Умножение на отрицательное число одновременно растягивает и отражает прямую, поэтому порядок меняется.'],
    12:['Обратные положительные числа','Переходи к обратным числам на обеих сторонах.','У положительных чисел произведение знаменателей положительно. Величина 1/x убывает с ростом x.']
  };
  function transform(n,a,b,k,c,d){
    switch(n){
      case 6:return [a+k,b+k];
      case 7:case 11:return [a*k,b*k];
      case 8:return [a+c,b+d];
      case 9:return [a*c,b*d];
      case 10:return [-a,-b];
      case 12:return [1/a,1/b];
    }
  }
  Object.entries(sets).forEach(([idx,rows])=>{
    const n=Number(idx),[name,action,rule]=methods[n];
    rows.forEach(([a,rel,b,c,rel2,d],i)=>{
      const double=c!==undefined,sgn=n>=10?flip[rel]:rel;
      const orig=fmt(a)+' '+rel+' '+fmt(b)+(double?', '+fmt(c)+' '+rel2+' '+fmt(d):'');
      const originalFactor=n===11?-2:2,[L,R]=transform(n,a,b,originalFactor,c,d);
      const result=n===12?fraction(a)+' '+sgn+' '+fraction(b):fmt(L)+' '+sgn+' '+fmt(R);
      const guide=(n===6?'Выберем сдвиг на +2. ':n===7?'Например, возьмём множитель 2. ':n===11?'Выберем множитель −2. ':'')+
        'Получаем '+result+'. '+rule;
      register(n,i,name+' · '+orig,action+' Исходные данные: '+orig+'.',guide,rule,s=>{
        const offset=n===12||n===9?s:s-6,A=a+offset,B=b+offset,C=double?c+s:undefined,D=double?d+s:undefined;
        const factor=n===11?-(s+1):n===6?s-4:s+1;
        const [l,r]=transform(n,A,B,factor,C,D),pairs=[['a',A],['b',B],['Исходный знак',rel]];
        if(double)pairs.push(['c',C],['d',D]);
        if(n===6||n===7||n===11)pairs.push([n===6?'Сдвиг':'Множитель',factor]);
        return mark(name+' для пары '+fmt(A)+' '+rel+' '+fmt(B),pairs,[
          q('Найди новую левую часть. Можно использовать дробь.',l,action+' Начни с левой части '+fmt(A)+'.',l+1,'Проверь преобразование левой стороны: лишняя единица меняет точку на прямой.'),
          q('Найди новую правую часть.',r,action+' Теперь преобразуй '+fmt(B)+'.',r-1,'Правая сторона должна изменяться ровно по тому же правилу.'),
          q(directions,codes[sgn],rule,-codes[sgn],'Сначала выясни, сохраняется ли направление. Разрешённое равенство при преобразовании остаётся допустимым.')
        ],[l,r]);
      });
    });
  });
  const powers=[[2,9],[5,6],[4,10],[1.3,1.5],[7.28,8.37],[5.4,4.5],[-2,-3],[4,-4],[-4,1],[-1,-1.4],[-4.9,-7],[4,-5]];
  powers.forEach(([a,b],i)=>{
    const notation=v=>v<0?'('+fmt(v)+')²':fmt(v)+'²',expr=notation(a)+' и '+notation(b);
    const sign=Math.sign(a*a-b*b),sym=['<','=','>'][sign+1];
    const rule='Сначала сравни расстояния оснований до нуля. Чем больше модуль, тем больше квадрат. Равные модули дают равные квадраты.';
    register(13,i,'Квадраты · '+expr,'Сравни '+expr+'.','Модули равны '+fmt(Math.abs(a))+' и '+fmt(Math.abs(b))+'. Поэтому '+notation(a)+' '+sym+' '+notation(b)+'.',rule,s=>{
      const A=Math.sign(a)*(Math.abs(a)+s),B=Math.sign(b)*(Math.abs(b)+s);
      return mark('Сначала найди оба модуля',[['Первое основание',A],['Второе основание',B]],[
        q('Найди квадрат первого основания.',A*A,'Умножь первое основание на себя.',-A*A,'Квадрат ненулевого действительного числа положителен.'),
        q('Найди квадрат второго основания.',B*B,'Сначала можно убрать минус под квадратом.',-B*B,'Квадрат убирает знак основания.'),
        q('Каковы квадраты слева и справа? Введи −1 для <, 0 для =, 1 для >.',sign,rule,sign===0?1:-sign,'Проверь модули. Для отрицательного основания порядок его квадрата определяется расстоянием до нуля.')
      ],[A*A,B*B]);
    });
  });
})();
