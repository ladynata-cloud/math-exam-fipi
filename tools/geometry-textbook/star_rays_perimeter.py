def direction(d):
    a=radians(d)
    return cos(a),sin(a)


def polar(deg,r):
    x,y=direction(deg)
    return round(r*x,9),round(r*y,9)


def star(title,phase,mode):
    names='ABCDE'
    pts={k:polar(phase+i*72,3) for i,k in enumerate(names)}
    sides=[(names[i],names[(i+2)%5]) for i in range(5)]
    if mode=='axes':
        marks=[(polar(phase+i*36+180,3.4),polar(phase+i*36,3.4)) for i in range(5)]
    else:
        marks=turning_arrow((0,0),pts['A'],72*mode)
    return diagram(title,{**pts,'T':(0,0)},sides,marks)


