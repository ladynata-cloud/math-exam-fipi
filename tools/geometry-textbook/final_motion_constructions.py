def sub(a,b):return a[0]-b[0],a[1]-b[1]
def cross(a,b):return a[0]*b[1]-a[1]*b[0]
def dot(a,b):return a[0]*b[0]+a[1]*b[1]
def at(a,d,t):return (a[0]+t*d[0],a[1]+t*d[1])


def intersect(a,b,c,d):
    u=sub(b,a);v=sub(d,c)
    return at(a,u,cross(sub(c,a),v)/cross(u,v))


def secants(title,r,angle):
    center=(0,0);pts={'T':center}
    for i,k in enumerate('ABC'):
        pts[k]=rotated((r,0),center,15+120*i)
        pts[k+'₁']=rotated((r,0),center,15+120*i+angle)
    edges=[(s[i],s[(i+1)%3]) for s in [('A','B','C'),('A₁','B₁','C₁')] for i in range(3)]
    lines=[(pts[k],pts[k+'₁']) for k in 'ABC']
    nodes=[intersect(*lines[i],*lines[(i+1)%3]) for i in range(3)]
    if angle!=180:pts.update(dict(zip('KLN',nodes,strict=True)))
    spans=[]
    for i,(p,q) in enumerate(lines):
        d=sub(q,p);length=dist(p,q);unit=tuple(z/length for z in d)
        ts=[dot(sub(s,p),unit) for s in [p,q,nodes[i],nodes[i-1]]]
        spans.append((at(p,unit,min(ts)-.35),at(p,unit,max(ts)+.35)))
    for k,z in enumerate([(r,0),(0,r),(-r,0),(0,-r)]):pts['bound'+str(k)]=z
    return diagram(title,pts,edges,spans)


