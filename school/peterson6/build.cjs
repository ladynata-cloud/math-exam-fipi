// Build committed browser data. No dependencies or network access.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = name => JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const lessons = ['logic.json','arithmetic.json','percent.json'].flatMap(read).sort((a,b)=>a.order-b.order);
const revision = read('equation-lessons.json');
if(revision.version!==2)throw Error('Unsupported equation content revision');
const legacyTasks={},legacyTheory={};
const allowed=new Set(['methodVersion','steps','hint','explanation','finalLabel']);
const taskIds=new Set(lessons.flatMap(l=>l.tasks.map(t=>t.id)));
for(const id of Object.keys(revision.tasks))if(!taskIds.has(id))throw Error('Unknown equation task '+id);
for(const lesson of lessons){
 const update=revision.lessons[lesson.id];
 if(update){
  if(Object.keys(update).some(k=>!['theory','goals'].includes(k)))throw Error('Unapproved lesson override '+lesson.id);
  legacyTheory[lesson.id]={theory:lesson.theory,goals:lesson.goals};
  Object.assign(lesson,update);
 }
 lesson.tasks=lesson.tasks.map(task=>{
  const patch=revision.tasks[task.id];if(!patch)return task;
  if(patch.methodVersion!==2||Object.keys(patch).some(k=>!allowed.has(k)))throw Error('Unapproved task override '+task.id);
  legacyTasks[task.id]=task;
  return {...task,...patch};
 });
}
const source = read('source-map.json');
const exerciseIndex = {};
for(const r of source.exercisePageRanges){
  for(let n=r.firstExercise;n<=r.lastExercise;n++){
    const i=source.topics.findIndex(t=>n>=t.firstExercise&&n<=t.lastExercise);
    const review=source.selfChecks.find(t=>n>=t.firstExercise&&n<=t.lastExercise);
    const lesson=i>=0?'p'+String(i+1).padStart(2,'0'):(n<176?'p07':n<308?'p10':'p14');
    exerciseIndex[n]={page:r.page,lesson,review:!!review};
  }
}
const data={version:1,methodVersion:2,source:source.source,lessons,exerciseIndex,legacyTasks,legacyTheory};
const text='// Generated by build.cjs from authored content and verified source map.\nwindow.PetersonCourse = '+JSON.stringify(data,null,1).replace(/</g,'\\u003c')+';\n';
if(process.argv.includes('--check')){
  if(fs.readFileSync(path.join(root,'data.js'),'utf8')!==text)throw Error('data.js is stale; run node school/peterson6/build.cjs');
}else fs.writeFileSync(path.join(root,'data.js'),text);
console.log('Course bundle: '+lessons.length+' topics, '+lessons.reduce((n,l)=>n+l.tasks.length,0)+' tasks, '+Object.keys(exerciseIndex).length+' source numbers.');
