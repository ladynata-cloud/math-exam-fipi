(function(){
  'use strict';
  const {lessons,add,example}=window.MathExamTopicPractice,course=window.MathExamTopicEdition;
  const ids=[],letters='абвгдежз';
  function card(n,i,title,prompt,guide,rule,make){
    const key=String(n)+(i===null?'':String.fromCharCode(97+i)),printed=String(n)+(i===null?'':letters[i]);
    add(49,key,n<=9?8:9,title,prompt,rule,'numline',make);
    const l=lessons.get('49-'+key);Object.assign(l,{printedReference:'Упражнение №'+printed,printedPrompt:prompt,printedGuide:guide});ids.push(l.id);
  }
  const q=(prompt,answer,calculation,bad,error)=>({prompt,answer,calculation,error,mistakes:[[bad,error]]});
  const segment=(left,right,fn,openLeft=false,openRight=false)=>({left,right,fn,openLeft,openRight});
  function sample(caption,rows,questions,segments,points=[]){
    return Object.assign(example(caption,['Условие','Данные'],rows,questions,'advanced-function'),{graph:{segments,points}});
  }
  function compare(caption,formula,x1,x2,fn,segments){
    const y1=fn(x1),y2=fn(x2),dy=y2-y1;
    return sample(caption,[['Функция',formula],['Первый аргумент',x1],['Второй аргумент',x2]],[
      q('Чему равно первое значение f('+x1+')?',y1,'Подставь первый аргумент вместо x.',y2,'Это значение относится ко второй точке.'),
      q('Чему равно второе значение f('+x2+')?',y2,'Подставь второй аргумент и сохрани все знаки.',y1,'Это ордината первой точки.'),
      q('Чему равно приращение f('+x2+') − f('+x1+')?',dy,'Вычти значение слева из значения справа. Знак показывает направление на выбранной ветви.',-dy,'Значения вычтены в обратном порядке.')
    ],segments,[[x1,y1],[x2,y2]]);
  }
  for(const [i,formula,guide] of [
    [0,'5x − 8','Коэффициент при x равен 5. Когда аргумент увеличивается на h > 0, значение растёт на 5h. Функция возрастает на ℝ.'],
    [1,'−3x + 7','При положительном приращении h значение меняется на −3h. Прямая убывает на ℝ.'],
    [2,'6/x','Каждая ветвь убывает: отдельно при x < 0 и при x > 0. На всей проколотой прямой монотонности нет: при переходе от −1 к 1 значение растёт.'],
    [3,'−10/x','На каждой отдельной ветви функция возрастает. При переходе от −1 к 1 значение падает с 10 до −10, поэтому объединять ветви нельзя.'],
    [4,'x² при x ≥ 0','При 0 ≤ u < v оба множителя (v − u)(v + u) положительны. Квадрат возрастает на [0; +∞).'],
    [5,'x² при x ≤ 0','При u < v ≤ 0 сумма u + v отрицательна. Разность квадратов (v − u)(v + u) отрицательна, поэтому функция убывает на (−∞; 0].']
  ]){
    card(1,i,'Направление изменения · '+formula,'Исследуй на возрастание и убывание y = '+formula+'.',guide,'Две упорядоченные точки нужно брать на одном указанном промежутке.',s=>{
      const a=s+2,k=i%2?-a:a,b=s-5;
      if(i<2){const f=x=>k*x+b;return compare('Сравни точки прямой','y = '+k+'x + ('+b+')',1,3,f,[segment(-1,4,f)]);}
      if(i<4){const c=6*k,f=x=>c/x;return compare('Сравни две точки одной ветви','y = '+c+'/x',1,3,f,[segment(-4,-.7,f),segment(.7,4,f)]);}
      const f=x=>x*x,x1=i===4?s:-s-1;return compare('Сравни квадраты на одной полуоси','y = x²',x1,x1+1,f,[segment(i===4?0:-s-2,i===4?s+2:0,f)]);
    });
  }
  card(2,null,'Модуль по обе стороны вершины','Докажи, на какой полуоси |x| убывает, а на какой возрастает.','Слева от нуля |x| = −x: большему x соответствует меньшее значение. Справа |x| = x, и значения растут. Нулевую граничную точку можно включить в оба промежутка.','Раскрой модуль по разные стороны вершины.',s=>{
    const h=s-4,a=s+1,f=x=>Math.abs(x-h);
    return sample('Сдвиг вершины модуля',[['Функция','y = |x − ('+h+')|'],['Шаг от вершины',a]],[
      q('При каком x достигается минимум?',h,'Подмодульное выражение должно равняться нулю.',h+1,'В этой точке расстояние до вершины ещё равно единице.'),
      q('Чему равно f(h − '+a+')?',a,'Слева от вершины расстояние положительно.',-a,'Модуль расстояния не бывает отрицательным.'),
      q('Каково изменение значения от h − '+a+' до h?',-a,'В вершине значение нулевое, вычти длину левой стороны.',a,'Движение к вершине уменьшает высоту.')
    ],[segment(h-a-1,h,f),segment(h,h+a+1,f)],[[h,0]]);
  });
  card(3,null,'Возрастание и убывание ломаной','Построй ломаную через A(−1; −2), B(2; 5), C(6; 2) и найди промежутки монотонности.',
    'При чтении слева направо высота растёт до B, затем падает. Первый промежуток [−1; 2], второй [2; 6]. Концы и точка B принадлежат графику.','Меняй направление чтения графика только в вершине ломаной.',s=>{
      const h=s-4,y=s+1,a=h-2,b=h+3,up=x=>y+2*(x-h),down=x=>y-(x-h);
      return sample('Два звена с общей вершиной',[['A',[a,up(a)].join('; ')],['B',[h,y].join('; ')],['C',[b,down(b)].join('; ')]],[
        q('Какова абсцисса точки смены направления?',h,'Переход между звеньями происходит в B.',y,'Прочитана ордината, а требуется координата x.'),
        q('На сколько увеличилась высота от A до B?',4,'Вычти ординату A из ординаты B.',2,'Это изменение абсциссы, а нужно изменение высоты.'),
        q('Каково приращение от B до C?',-3,'На правом звене высота падает на три единицы.',3,'При падении приращение отрицательно.')
      ],[segment(a,h,up),segment(h,b,down)],[[a,up(a)],[h,y],[b,down(b)]]);
    });
  const pieceGuide='Область определения [−2; 6], область значений [−4; 4]. В x = 0 берём 1, в x = 2 берём 4. Функция убывает на [2; 6], возрастает на [−2; 0] и [1; 2], постоянна на [0; 1]. В x = 0 скачок вверх сохраняет строгое возрастание слева.';
  const piecePrompt='Построй f по четырём правилам: −x² при −2 ≤ x < 0, 1 при 0 ≤ x ≤ 1, x² при 1 < x ≤ 2, 6 − x при 2 < x ≤ 6. Найди область определения и значения.';
  ['убывает','возрастает','постоянна'].forEach((word,i)=>card(4,i,'Кусочная функция · '+word,piecePrompt+' Найди промежутки, где функция '+word+'.',pieceGuide,'В граничной точке используй включающий её кусок. Проверь, может ли промежуток продолжиться через стык.',s=>{
    const h=s-5;
    return pieceData(h,i);
  }));
  function pieceData(h,i){
    const left=x=>-((x-h)**2),right=x=>(x-h)**2,fall=x=>6-(x-h);
    const bounds=[[h+2,h+6],[h-2,h],[h,h+1]][i],qs=[
      q('Какова левая граница '+(i===1?'первого промежутка возрастания':i===0?'убывания':'участка постоянства')+'?',bounds[0],'Читай абсциссу соответствующей точки стыка.',bounds[0]+1,'Эта точка лежит правее искомой границы.'),
      q('Какова правая граница этого промежутка?',bounds[1],'Проследи выбранную ветвь до смены поведения.',bounds[1]+1,'Выход за эту точку меняет поведение или покидает область определения.'),
      q('Чему равно значение в точке x = '+h+'?',1,'В самой точке действует правило горизонтальной части.',0,'Ноль — предел слева, эту точку левый кусок не включает.')
    ];
    return sample('Исследуй сдвинутый кусочный график',[['Сдвиг вправо h',h],['Переменная u','u = x − h'],['Формулы по u','−u² [−2; 0), 1 [0; 1], u² (1; 2], 6−u (2; 6]']],qs,[segment(h-2,h,left,false,true),segment(h,h+1,()=>1),segment(h+1,h+2,right,true,false),segment(h+2,h+6,fall,true,false)]);
  }
  const prevNext=course.nextId,prevGrade=course.grade,prevSource=course.source;
  course.nextId=l=>l.book===49?ids[ids.indexOf(l.id)+1]:prevNext(l);
  course.grade=b=>b===49?'9 класс':prevGrade(b);
  course.source=(b,p)=>b===49?'https://pdf.my-uchebnik.ru/pdf/algebra/00000042.pdf#page='+(p+1):prevSource(b,p);
  window.AdvancedFunctionGraphs={card,q,sample,segment,compare};
})();
