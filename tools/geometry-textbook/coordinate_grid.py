def grid(label, movements):
    """Build axes, a unit-spaced grid, named endpoints, and the directed source movements."""
    xs=[0,1]+[p[0] for _,a,b in movements for p in (a,b)]
    ys=[0,1]+[p[1] for _,a,b in movements for p in (a,b)]
    xmin=min(-1,floor(min(xs)));xmax=max(2,ceil(max(xs)))
    ymin=min(-1,floor(min(ys)));ymax=max(2,ceil(max(ys)))
    points={'O':(0,0),'_left':(xmin-.25,0),'X':(xmax+.48,0),'_base':(0,ymin-.25),'Y':(0,ymax+.48),
            '_unitX':(1,0),'_unitY':(0,1)}
    lines=[]
    arrows=[('_left','X'),('_base','Y')]
    for x in range(xmin,xmax+1):
        if x:
            l,r=f'_gx{x}b',f'_gx{x}t';points[l]=(x,ymin);points[r]=(x,ymax);lines.append((l,r))
    for y in range(ymin,ymax+1):
        if y:
            l,r=f'_gy{y}l',f'_gy{y}r';points[l]=(xmin,y);points[r]=(xmax,y);lines.append((l,r))
    positions={(0,0):'O'}
    def named(name,p):
        if p not in positions:
            positions[p]=name;points[name]=p
        return positions[p]
    for name,a,b in movements:
        begin=named('S'+name,a);end=named(name,b)
        if begin!=end and (begin,end) not in arrows:arrows.append((begin,end))
    return label,points,arrows,lines


def cartesian(n,*,part=None,cases,initial,frames,**data):
    e=authored(n,chapter_part=part,pages=[251] if n<=1005 else [252],frames=[initial]+frames,cases=cases,**data)
    e['review']['reviewer']='Точные подпункты с. 251–252 и направления исходного рисунка 309 проверены в издании Атанасяна 2023 года. Положение начальных и конечных точек измерено; рисунки для курса построены заново.'
    e['help'][1].update(theoryIds=['atanasyan-7-9-theory-94-part-1'],text='Сравни коэффициенты при горизонтальном i и вертикальном j. Проверь знаки по стрелкам.')
    e['answer']['prompt']='Запиши координаты или разложения всех требуемых векторов и поясни одно из построений.'
    model=e['visualization']['model'];model['description']='Вправо возрастает x, вверх возрастает y. Одна клетка даёт одну единицу. Острие обозначает конец вектора.'
    for v in model['views'].values():
        grid_lines=[pair for pair in v['segments'] if pair[0].startswith(('_gx','_gy'))]
        v['dashSegments']=grid_lines
        v['segments']=[pair for pair in v['segments'] if pair not in grid_lines]
        v['points']=[key for key in v['points'] if not key.startswith('_')]
        heads=[pair for pair in v['segments'] if pair[1].startswith('head_')]
        shafts=[pair for pair in v['segments'] if not pair[1].startswith('head_')]
        v['highlightSegments']=shafts[2:]+heads[4:]
    for key,name in model['labels'].items():
        if name in ('X','Y'):model['labels'][key]=name.lower()
        elif name.startswith('S') and len(name)>1:model['labels'][key]='нач.'
        elif name in 'ABCDEFIJ' and len(name)==1:model['labels'][key]=name.lower()
    e['visualization']['caption']='Одна клетка — единица длины. Считай шаги от начала до острия. Вектор с ненулевым началом можно перенести, сохраняя оба смещения.'
    return e


def encoded_point(n,part,task,answer,hint,stages,frames,probes):
    return cartesian(n,part=part,question=task,answer=answer,hint=hint,steps=stages,initial=frames[0],frames=frames,cases=frames,prompts=probes)


