(function(){
  'use strict';
  const {add,lessons}=window.MathExamTopicPractice;
  const {q,sample,order}=window.NikolskyWorkshop;
  const letters='абвгдежзиклм';
  function register(n,i,title,prompt,guide,rule,make){
    const part=i===null?'':'-'+String.fromCharCode(97+i),key=String(n)+part;
    const printed=String(n)+(i===null?'':letters[i]),page=n<=10?9:10;
    add(75,key,page,title,prompt,rule,'signedcompare',make);
    const l=lessons.get('75-'+key);
    Object.assign(l,{printedReference:'Упражнение №'+printed,printedPrompt:prompt,printedGuide:guide});
    order.push(l.id);
  }
  const ratios=(n,d)=>d===1?String(n):n+'/'+d;
  const gap=(left,right)=>Math.abs(right-left);
  const mark=(caption,rows,qs,points)=>sample(caption,rows,qs,'orderedPoints',points);
  for(let i=0;i<2;i++){
    const mult=!!i;
    register(1,i,mult?'Когда можно перемножить неравенства':'Когда можно сложить неравенства',mult?'При каких условиях верно почленное умножение?':'При каких условиях верно почленное сложение?',
      mult?'Сначала направь знаки одинаково и проверь положительность всех частей. Если 0 < a < b и 0 < c < d, то ac < bc < bd. При произвольных отрицательных числах это рассуждение ломается.':'Запиши обе верные пары от меньшего к большему. Из a < b и c < d следует a + c < b + d, поскольку (b − a) + (d − c) положительно.',
      mult?'Умножай одноимённые неравенства с положительными частями.':'Сравни направления знаков перед сложением.',s=>{
        const a=mult?s+1:-s,b=a+2,c=s+3,d=c+1+s%3,L=mult?a*c:a+c,R=mult?b*d:b+d;
        return mark(mult?'Перемножь две положительные пары':'Сложи две однонаправленные пары',[['Первая пара',a+' < '+b],['Вторая пара',c+' < '+d]],[
          q('Чему равна левая часть результата?',L,'Объедини '+a+' и '+c+' указанным действием.',R,'Это результат для двух правых частей.'),
          q('Чему равна правая часть?',R,'Объедини '+b+' и '+d+'.',L,'Сейчас нужны обе большие границы.'),
          q('На сколько правая часть больше левой?',R-L,'Вычти левую границу из правой.',L-R,'Порядок вычитания определяет знак расстояния.')],[L,R]);
      });
  }
  for(let i=0;i<2;i++){
    register(2,i,i?'Когда запись a ≥ b ложна':'Когда запись a ≥ b верна',i?'Как опровергнуть a ≥ b?':'В каких двух случаях a ≥ b верно?',
      i?'Единственная возможность — a < b. Случай a = b входит в знак ≥ и опровержением не является.':'Подходят и a > b, и a = b. Например, 3 ≥ 3 верно, поскольку разрешено равенство.','Посмотри, включает ли знак случай равенства.',s=>{
        const a=s+4,b=i?a+1+s%4:a-(s%3),L=Math.min(a,b),R=Math.max(a,b);
        return mark('Сравни a = '+a+' и b = '+b,[['a',a],['b',b]],[
          q('Найди a − b с учётом знака.',a-b,'Вычти второе число из первого.',a+b,'Сумма не определяет порядок двух чисел.'),
          q('Каково расстояние между a и b?',R-L,'Возьми модуль разности.',R-L+1,'На прямой между соседними целыми длина 1, хотя точек две.'),
          q('Истинно ли a ≥ b? Введи 1 для «да» или 0 для «нет».',Number(a>=b),'Проверка включает совпадение границ.',Number(a<b),i?'Левая точка находится строго левее. Неравенство ≥ здесь ложно.':'При равенстве знак ≥ тоже верен. Проверь порядок данных точек.')],[a,b]);
      });
  }
  const originals=window.NikolskyCompareOriginals;
  Object.entries(originals).forEach(([kind,rows])=>{
    const n={compare:3,between:4,chain:5}[kind];
    rows.forEach(([letter,expr,...rest],i)=>{
      const guide=rest.pop(),den=rest.pop(),values=rest;
      const prefix=n===3?'Сравни ':n===4?'Подбери число строго между ':'Как связаны крайние числа: ';
      const rule=n===3?'Переведи числа в равные доли. Больше то, у которого числитель больше.':n===4?'Полусумма разных чисел лежит строго между ними, даже когда границы заданы в обратном порядке.':'Направь оба знака в одну сторону и проследи порядок трёх чисел через общее среднее.';
      register(n,i,(n===3?'Сравнение':n===4?'Середина между числами':'Транзитивность')+' · '+expr,prefix+expr+'.',guide,rule,s=>{
        const pts=values.map(v=>v+(s-6)*den),A=pts[0],B=pts.at(-1),left=Math.min(A,B),right=Math.max(A,B);
        const rows=pts.map((v,j)=>[['Первая точка','Вторая точка','Третья точка'][j],ratios(v,den)]);
        rows.push(['Общий знаменатель',den]);
        if(n===4){
          return mark('Найди середину и проверь обе строгие границы',rows,[
            q('Каков числитель меньшей границы при знаменателе '+den+'?',left,'Сравни числители после приведения к одному знаменателю.',right,'Вы выбрали точку справа. Нужна левая граница.'),
            q('Каков числитель суммы границ при том же знаменателе?',A+B,'Сложи два числителя.',A+B+den,'К сумме добавлена лишняя целая единица. Складывай только координаты двух точек.'),
            q('Чему равна середина? Можно ввести дробь.',(A+B)/(2*den),'Раздели сумму координат пополам.',right/den,'Правая граница не принадлежит строгому промежутку.')],[left/den,(left+right)/(2*den),right/den]);
        }
        if(n===5){
          return mark('Пройди через общую точку и сравни крайние',rows,[
            q('Найди расстояние от первой точки до второй.',gap(A,pts[1])/den,'Вычти меньшую координату из большей.',-gap(A,pts[1])/den,'Длина отрезка положительна.'),
            q('Найди расстояние от второй точки до третьей.',gap(pts[1],B)/den,'Снова сравни соседние координаты.',-gap(pts[1],B)/den,'Расстояние равно модулю разности.'),
            q('Каково расстояние между крайними числами?',gap(A,B)/den,'Сложи два соседних отрезка.',gap(A,pts[1])/den,'Посчитан только первый отрезок цепочки.')],pts.map(v=>v/den));
        }
        return mark('Сравни точки на общей шкале',rows,[
          q('Какой числитель у первого числа при знаменателе '+den+'?',A,'Читай числитель первой координаты.',A+den,'Прибавлена лишняя целая единица.'),
          q('Найди числитель разности «первое минус второе» при этом знаменателе.',A-B,'Сохрани порядок и вычти два числителя.',A-B+den,'Разность смещена на целую единицу.'),
          q('Введи знак сравнения числом: −1 для <, 0 для =, 1 для >.',Math.sign(A-B),'Сравни разность с нулём.',Math.sign(A-B)===0?1:-Math.sign(A-B),'Сравнивай координаты с сохранением минуса. Совпавшие точки дают равенство.')],[A/den,B/den]);
      });
    });
  });
  window.NikolskyInequalities={register,mark,q,sample,ratios};
})();
