def bisected(label,b,c,alpha):
    # D divides BC internally in the ratio BD/DC = AB/AC = c/b.
    B=(c,0);C=(b*cos(radians(alpha)),b*sin(radians(alpha)))
    D=tuple((b*x+c*y)/(b+c) for x,y in zip(B,C))
    from coordinate_curves import graph
    return graph(label,{'A':(0,0),'B':B,'C':C,'D':D},edges=[('A','B'),('B','C'),('C','A'),('A','D')])


