'use strict';
// Actual self-contained deliverable opened from file:// with browser network disabled.
// Invoke only after final HTML packaging; this script never edits runtime or content.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'../..');
const html=process.argv[2];
if(!html)throw Error('Pass the final self-contained HTML path.');
const absolute=path.resolve(html),bytes=fs.readFileSync(absolute);
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const output=path.join(path.dirname(root),'artifacts/shestakov-offline');fs.mkdirSync(output,{recursive:true});
const report={passed:false,at:new Date().toISOString(),mode:'file:// with context.setOffline(true)',htmlFile:path.basename(absolute),htmlSHA256:hash(bytes),htmlBytes:bytes.length,expectedCards:351,task:'sy-6-1-a1-a',verified:[],errors:[],networkRequests:[],screenshots:[]};
const reportPath=path.join(__dirname,'offline-smoke.json');
let browser;
(async()=>{try{
 browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH,args:['--no-sandbox']}:{} )});
 report.browser=browser.version();
 const ctx=await browser.newContext({viewport:{width:1280,height:1000}});
 await ctx.setOffline(true);
 const page=await ctx.newPage();page.on('pageerror',e=>report.errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))report.networkRequests.push(r.url());});
 await page.goto(pathToFileURL(absolute).href,{waitUntil:'load'});
 await page.waitForFunction(()=>Boolean(window.textbookApp));
 assert.equal(await page.evaluate(()=>navigator.onLine),false);
 const coverage=await page.evaluate(()=>({coverage:window.textbookApp.coverage,issues:window.textbookApp.issues}));
 assert.equal(coverage.coverage.available,351);assert.deepEqual(coverage.issues,[]);
 report.cards=coverage.coverage.available;report.verified.push('351 available catalog cards and zero bundle issues while browser is offline');
 await page.locator('#catalog-section').selectOption('6.1');
 await page.locator('#catalog-level').selectOption('A');
 await page.locator('[data-lesson="sy-6-1-a1-a"]').click();
 assert.match(await page.locator('h1').textContent(),/6\.1.*A1а/);
 assert.equal(await page.locator('[data-step]').count(),0);
 await page.locator('#final-answer').fill('15');
 await page.getByRole('button',{name:'Проверить ответ',exact:true}).click();
 assert.match(await page.locator('[data-final-feedback]').textContent(),/самостоятельно/);
 report.verified.push('6.1 A1а: answer 15 accepted as independent work before help');
 await page.reload({waitUntil:'load'});
 assert.equal(await page.locator('#final-answer').inputValue(),'15');
 assert.match(await page.locator('[data-final-feedback]').textContent(),/самостоятельно/);
 assert.equal(await page.evaluate(()=>location.hash),'#sy-6-1-a1-a');
 report.verified.push('file reload restores deep-linked task, answer 15 and independent result');
 await page.locator('#final-answer').fill('мой черновик');
 await page.locator('[data-main-help]>summary').click();
 await page.getByRole('button',{name:'Разобрать по шагам',exact:true}).click();
 await page.getByRole('button',{name:'Следующий шаг',exact:true}).click();
 assert.equal(await page.locator('[data-step]').count(),2);
 const firstStep=page.locator('[data-step]').first();
 await firstStep.locator('input').fill('8');
 await page.reload({waitUntil:'load'});
 assert.equal(await page.locator('#final-answer').inputValue(),'мой черновик');
 assert.equal(await page.locator('[data-step]').count(),2);
 assert.equal(await page.locator('[data-step]').first().locator('input').inputValue(),'8');
 report.verified.push('reload retains two revealed steps, final-answer draft and intermediate diameter draft 8');
 await page.locator('#final-answer').fill('15');
 await page.getByRole('button',{name:'Проверить ответ',exact:true}).click();
 assert.match(await page.locator('[data-final-feedback]').textContent(),/помощи/);
 await page.reload({waitUntil:'load'});
 assert.match(await page.locator('[data-final-feedback]').textContent(),/с помощью/);
 report.verified.push('help use remains recorded after reload and final answer is marked assisted');
 await page.setViewportSize({width:320,height:900});
 const taskMetrics=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,innerWidth}));
 assert(taskMetrics.scrollWidth<=taskMetrics.innerWidth+1,JSON.stringify(taskMetrics));
 await page.screenshot({path:path.join(output,'task-mobile.png'),fullPage:true});
 report.screenshots.push('artifacts/shestakov-offline/task-mobile.png');
 await page.getByRole('button',{name:'← Все материалы курса',exact:true}).click();
 const catalogMetrics=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,innerWidth}));
 assert(catalogMetrics.scrollWidth<=catalogMetrics.innerWidth+1,JSON.stringify(catalogMetrics));
 await page.screenshot({path:path.join(output,'catalog-mobile.png'),fullPage:true});
 report.screenshots.push('artifacts/shestakov-offline/catalog-mobile.png');
 report.mobile={width:320,task:taskMetrics,catalog:catalogMetrics};
 report.verified.push('task and catalog have no horizontal overflow at 320 CSS pixels');
 assert.deepEqual(report.errors,[]);assert.deepEqual(report.networkRequests,[]);
 assert.equal(hash(fs.readFileSync(absolute)),report.htmlSHA256,'Final HTML must remain unchanged during smoke test');
 report.verified.push('zero JavaScript errors, zero HTTP(S) resource requests, HTML hash unchanged');
 report.passed=true;
 console.log('SHESTAKOV_OFFLINE_SMOKE_OK '+report.htmlSHA256);
 }catch(e){report.failure=e.message;throw e;}finally{
 if(browser)await browser.close();
 fs.writeFileSync(reportPath,JSON.stringify(report,null,2)+'\n');
 }})().catch(e=>{console.error(e.message);process.exitCode=1;});
