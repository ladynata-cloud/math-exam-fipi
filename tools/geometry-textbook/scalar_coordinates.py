    points={'A':(2,8),'B':(-1,5),'C':(3,1)}; changed={**points,'B':(-1,8)}
    views=[triangle('Вычисление угла при A',points,'A'),triangle('Сравнение двух стрелок из B',points,'B','ABC'),triangle('Перемести B в (−1;8)',changed,'A')]
