"""Measure the convexity, lengths and angles of every counterexample and every regular source polygon."""
import json
from math import acos, degrees, hypot, isclose
from regular_polygon_definition import OUT


def v(a,b):
    return b[0]-a[0],b[1]-a[1]


def dot(u,w):
    return u[0]*w[0]+u[1]*w[1]


def det(u,w):
    return u[0]*w[1]-u[1]*w[0]


def near(x,y):
    return isclose(x,y,abs_tol=1e-4)


tasks=[(113,None,True),(1167,'а',True),(1167,'б',False),(1168,'а',False),(1168,'б',True),(1168,'в',True),(1168,'г',False),(1169,None,True)]
data=json.loads(OUT.read_bytes())['lessons']; measured=0
for (n,part,truth),e in zip(tasks,data,strict=True):
    theory=n==113;pg=294 if theory else 300;ix='абвг'.index(part)+1 if part else 1;s=e['source']
    assert s['chapter']=='XIII' and s['printedPages']==[pg] and s['pdfPages']==[pg+1] and s.get('subpart')==part
    assert e['id']==f'atanasyan-7-9-{"theory" if theory else "main"}-{n}-part-{ix}'
    if n in (1167,1168):
        assert e['answer']['mode']=='exact' and ('да' in e['answer']['accepted'])==truth and ('нет' in e['answer']['accepted'])!=truth
    elif not theory:assert e['answer']['mode']=='manual'
    else:assert e['kind']=='theory'
    model=e['visualization']['model']
    for key,view in model['views'].items():
        mode=2 if key in ('case-3','step-3') else 1 if key in ('case-2','step-2') else 0
        measured+=1;suf='__v'+view['points'][0].split('__v')[1];raw=model['points'];o=raw['O'+suf];scale=raw['_unitX'+suf][0]-o[0];assert scale>0
        p={n:tuple((raw[j][dim]-o[dim])/scale for dim in (0,1)) for j in view['points'] for n in model['labels'][j].split('=')}
        names=sorted(p);c=len(names);assert names==list('ABCDEFGH')[:c]
        coords=[p[k] for k in names]
        lengths=[];angles=[]
        for i in range(c):
            first,mid,last=coords[i-1],coords[i],coords[(i+1)%c]
            u,w=v(mid,first),v(mid,last)
            assert det(u,w)<0
            lengths.append(hypot(*w));angles.append(degrees(acos(max(-1,min(1,dot(u,w)/(hypot(*u)*hypot(*w)))))))
        equal_sides=all(near(x,lengths[0]) for x in lengths)
        equal_angles=all(near(x,angles[0]) for x in angles)
        regular=equal_sides and equal_angles
        assert near(sum(angles),180*(c-2))
        if n==113:
            assert c==[5,4,8][mode] and regular==(mode!=1)
            if mode==1:assert equal_sides and not equal_angles
        elif n==1167:
            if part=='а':assert c==[5,6,3][mode] and regular
            else:
                assert regular==(mode==1)
                if mode==2:assert near(lengths[0]**2,16) and near(lengths[-1]**2,13)
        elif n==1168:
            if part=='а':assert equal_sides and regular==(mode==1)
            if part=='б':assert regular==(mode!=2) and c==3
            if part=='в':assert regular==(mode!=1) and c==3
            if part=='г':
                assert equal_sides and regular==(mode==1)
                if mode==2:assert near(angles[0],120) and near(angles[1],60)
        else:
            assert (equal_sides,equal_angles)==[(False,True),(True,False),(True,True)][mode]
            if mode==2:assert all(near(x,5) for x in lengths)
        if regular:
            assert near(angles[0],180-360/c)
trials=0
for x in range(1,31):
    for y in range(1,31):
        w=hypot(x,y);assert not near(w,x) and 0<x/w<1
        # Adjacent corners of the convex rhombus generated by (w,0),(x,y) have opposite cosines.
        assert near(dot((w,0),(x,y))/(w*w),x/w) and near(dot((-w,0),(x,y))/(w*w),-x/w)
        trials+=1
print(f'REGULAR_POLYGON_DEFINITION_OK {len(data)} source entries, {measured} polygons with all angles and lengths measured, {trials} independent rhombi.')
