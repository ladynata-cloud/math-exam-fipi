def circle_view(title,kind,r):
    if kind=='right':a,b,c=(0,r),(-r,0),(r,0)
    else:
        a=(0,r if kind=='acute' else -r);b=(-.8*r,-.6*r);c=(.8*r,-.6*r)
    t=(-b[0],-b[1]);pts={'S':(0,0),'A':a,'B':b,'C':c,'T':t}
    return graph(title,pts,edges=[('A','B'),('A','C'),('B','C'),('B','T'),('C','T')],circle=('S',r))


