def two_families(title,start,delta,u,v):
    x,y=start; dx,dy=delta
    p2=(x+dx,y+dy)
    points={'P':start,'Q':p2}
    lines=[]
    for tag,(ax,ay),o in [('A',u,start),('B',v,start),('A′',u,p2),('B′',v,p2)]:
        ox,oy=o;points[tag]=(ox+ax,oy+ay)
        lines.append(((ox-1.4*ax,oy-1.4*ay),(ox+1.4*ax,oy+1.4*ay)))
    length=hypot(dx,dy)
    ux,uy=dx/length,dy/length
    qx,qy=p2
    head=[(p2,(qx-.5*ux-.22*k*uy,qy-.5*uy+.22*k*ux)) for k in (-1,1)]
    # Keep the scale away from the lower ends of both oblique lines on a phone.
    x0=min(q[0] for line in lines for q in line)
    y0=min(q[1] for line in lines for q in line)-1.65
    points.update(U=(x0,y0),W=(x0+1,y0))
    return graph(title,points,edges=[('P','Q'),('U','W')],lines=[*lines,*head])


