def picture(label,vertices,edges,marks=(),unit=1):
    return panel(label,{key:(x/unit,y/unit) for key,(x,y) in vertices.items()},edges,'',marks)


def figure_card(n,part=None,*,frames,cases,**fields):
    return lesson(n,part=part,pages=[257],frames=frames,cases=cases,**fields)


