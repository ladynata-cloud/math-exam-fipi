def trapezoid(title,a,b,x,h):
    p={'A':(0,0),'D':(a,0),'E':(a+b,0),'C':(x,h),'B':(x-b,h)}
    return diagram(title,p,[('A','B'),('B','C'),('C','D'),('D','E'),('D','A'),('D','B')],[(p['A'],p['C']),(p['C'],p['E'])])


