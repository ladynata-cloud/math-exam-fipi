def square_pair(title,base,dx,dy):
    pts={'A':(0,0),'B':(base,0),'C':(dx+base,dy),'D':(dx,dy),'K':(0,base),'L':(base,base),'P':(dx,dy+base),'Q':(dx+base,dy+base),
         'M':(base/2,base/2),'N':(dx+base/2,dy+base/2)}
    edges=[('A','B'),('B','C'),('C','D'),('D','A'),('A','K'),('K','L'),('L','B'),('D','P'),('P','Q'),('Q','C')]
    return diagram(title,pts,edges,[(pts['A'],pts['D']),(pts['M'],pts['N'])])


