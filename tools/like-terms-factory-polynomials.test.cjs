'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
const {steps, grade, createStore, cleanProgress, storageKey} = require('../trainers/like-terms-factory-polynomials.js');
const step = id => steps.find(s=>s.id===id);
const answer = id => step(id).fields.map(f=>f.expected);
const check = (id, vals, status, index) => { const r=grade(step(id), vals); assert.equal(r.status,status,id+': '+vals); if(index!==undefined)assert.equal(r.index,index); assert.equal(r.done,status==='correct'); };
test('all seven worked/independent fixtures and sign-reordered equivalents',()=>{
  assert.equal(new Set(steps.map(s=>s.id)).size,7);
  assert.equal(steps.filter(s=>s.checkpoint).length,2);
  for(const s of steps) check(s.id, answer(s.id),'correct');
  check('standard',['-1+2x+6х^2'],'correct');
  check('degree',['-3b+5ba','2'],'correct');
  check('distribute',['x²+8x-6x²','8x-5x²'],'correct');
  check('factor',['3*x','3+2x','9x+6x²'],'correct');
  check('factor-two-letters',['4ba²','-2b+3a','-8a²b²+12a³b'],'correct');
  check('independent-factor',['5y','2-3y','10y-15y²'],'correct');
  check('independent-area',['3+2x','12x+8x²'],'correct');
});
test('standard form, degree after cancellation, and separate expanded line',()=>{
  check('standard',['4x²+2x²+2x-1'],'collect',0);
  check('standard',['6xx+2x-1'],'powers',0);
  check('standard',['6x*х+2x-1'],'powers',0);
  check('standard',['6x²+2x+1'],'wrong',0);
  check('degree',['2a³-2a³+5ab-3b','3'],'collect',0);
  check('degree',['5ab-3b','3'],'degree',1);
  check('degree',['5ab-3b','1+1'],'degree',1);
  check('degree',['5ab-3b',''],'empty',1);
  check('distribute',['-5x²+8x','-5x²+8x'],'terms',0);
  check('distribute',['-6x²-8x+x²','-5x²+8x'],'wrong',0);
  check('distribute',['-6x²+8x+x²','-6x²+8x+x²'],'collect',1);
});
test('factorization checks all three lines; equal product not automatically maximal',()=>{
  check('factor',['x','6x+9','6x²+9x'],'maxfactor',0);
  check('factor',['-3x','-2x-3','6x²+9x'],'maxfactor',0);
  check('factor',['2x+3','3x','6x²+9x'],'maxfactor',0);
  check('factor',['3x','2x+3','3x(2x+3)'],'expand',2);
  check('factor',['3x','2x+9','6x²+9x'],'wrong',1);
  check('factor',['3x','2x+3','6x²-9x'],'wrong',2);
  check('factor-two-letters',['4aab','3a-2b','12a³b-8a²b²'],'powers',0);
  check('independent-factor',['5y','-3y+2',''],'empty',2);
  check('independent-area',['2x+3','8x²-12x'],'wrong',1);
});
test('isolated storage, two stores preserve independent fields, invalid completion rejected',()=>{
  const old={'mathExamCourseProgress.v1':'{"old":true}','likeTermsFactory.brackets.v1':'{"done":13}'};
  const saved=new Map(Object.entries(old));
  const storage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v)};
  const a=createStore(storage),b=createStore(storage);
  a.update(p=>{p.records.degree.drafts[0]='5ab-3b';p.current='degree';});
  b.update(p=>{p.records.degree.drafts[1]='2';});
  assert.deepEqual(a.read().records.degree.drafts,['5ab-3b','2']);
  assert.equal(a.read().current,'degree');
  assert.equal(saved.get('mathExamCourseProgress.v1'),old['mathExamCourseProgress.v1']);
  assert.equal(saved.get('likeTermsFactory.brackets.v1'),old['likeTermsFactory.brackets.v1']);
  assert.ok(saved.has(storageKey));
  assert.equal(cleanProgress({records:{standard:{done:true,drafts:['0']}}}).records.standard.done,false);
  assert.equal(cleanProgress({records:{'independent-factor':{hints:6}}}).records['independent-factor'].hints,0);
  const denied=createStore({getItem(){throw Error('denied')},setItem(){throw Error('denied')}});
  denied.update(p=>{p.records.standard.drafts[0]='6x²+'});
  assert.equal(denied.read().records.standard.drafts[0],'6x²+');
});
