def segment_family(title,original,first,second,markers=None,axes=()):
    groups=[{'A':original[0],'B':original[1]},{'A′':first[0],'B′':first[1]},
            {'A″':second[0],'B″':second[1]}]
    return schematic(title,{**groups[0],**groups[1],**groups[2],**(markers or {})},[('A','B'),('A′','B′'),('A″','B″'),*axes])


