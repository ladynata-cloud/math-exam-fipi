  function index(preset) {
    const value = Number(preset == null ? 1 : preset);
    if (!Number.isInteger(value) || value < 1 || value > 3) throw new RangeError('Доступны варианты 1, 2 и 3.');
    return value - 1;
  }
  function motion(before, after, pairs, caption, moves = []) {
    return { type: 'arrows', before, after, arrows: pairs.map(([from, to]) => ({ from, to })),
      moves: moves.map(([from, to]) => ({ from, to })), caption };
  }
  function scene(id, title, narration, math, note, extra = {}) {
    return { id, title, narration, math, note, action: 'observe', click: false,
      record: null, duration_hint_ms: Math.max(6500, Math.min(12000, narration.length * 85)), ...extra };
  }
  function step(id, title, narration, math, note, animation) {
    return scene(id, title, narration, math, note, { action: 'correct', record: math,
      ...(animation ? { motion: animation, motion_ms: 3200 } : {}) });
  }
