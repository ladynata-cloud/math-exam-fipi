def drawing(label, r, *, unroll=False, sides=0, quarter=False):
    """Coordinates use the same reference segment UV for all cases within a card."""
    pts = {'T': (0, 0), 'A': (r, 0), 'B': (-r, 0), 'U': (-r, -r-.6), 'V': (1-r, -r-.6)}
    edges = [('T', 'A'), ('B', 'T'), ('U', 'V')]
    if unroll:
        pts['P'] = (-r, -r-1.3)
        pts['E'] = (r*(2*pi-1), -r-1.3)
        edges.append(('P', 'E'))
    if sides:
        names = ['A'] + ['B' if j==sides//2 else '_polygon'+str(j) for j in range(1,sides)]
        for j, name in enumerate(names[1:], 1):
            x, y = r*cos(2*pi*j/sides), r*sin(2*pi*j/sides)
            pts[name] = (round(x, 10), round(y, 10))
        edges.extend(zip(names, names[1:]+names[:1], strict=True))
    if quarter:
        pts['D'] = (0, r)
        edges.append(('T', 'D'))
        for j in range(1,20):
            pts['_arc'+str(j)] = (r*cos(pi*j/40), r*sin(pi*j/40))
        names = ['A', *['_arc'+str(j) for j in range(1,20)], 'D']
        edges.extend(zip(names, names[1:]))
    g = graph(label, pts, edges=edges, circle=('T',r))
    if quarter:
        return (*g[:3], list(zip(names,names[1:])))
    return g


