def intersect(a,b,c,d):
    u,v=(b[0]-a[0],b[1]-a[1]),(d[0]-c[0],d[1]-c[1])
    return coordinates(a,b,((c[0]-a[0])*v[1]-(c[1]-a[1])*v[0])/(u[0]*v[1]-u[1]*v[0]))


