'use strict';
const fs=require('node:fs'),path=require('node:path');
const read=f=>JSON.parse(fs.readFileSync(path.join(__dirname,f),'utf8'));
const sourceMap=read('source-map.json');
const authored=['part1.json','part2.json','part3.json','part4.json'].flatMap(read);
const refs=sourceMap.topics;
if(authored.length!==90||new Set(authored.map(l=>l.section)).size!==90)throw Error('Expected 90 unique topic sections');
const lessons=refs.map((r,index)=>{
 const l=authored.find(x=>x.section===r.number);if(!l)throw Error('Missing topic '+r.number);
 return {...l,id:'p'+String(index+1).padStart(2,'0'),order:index+1,title:r.title,advanced:r.advanced,page:r.printedPage,chapterId:r.chapter,chapter:sourceMap.chapters.find(c=>c.number===r.chapter).title};
});
const chapters=sourceMap.chapters.map(c=>({...c,id:c.number}));
const data={edition:'nikolsky10-2022',chapters,sourceMap,lessons};
fs.writeFileSync(path.join(__dirname,'data.js'),'/* Generated by build.cjs from chapter JSON. */\nwindow.NikolskyCourse='+JSON.stringify(data)+';\n');
