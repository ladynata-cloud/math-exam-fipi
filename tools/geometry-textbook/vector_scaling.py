def scale(k, v):
    return tuple(k*t for t in v)


def scaled_path(label, factors, vectors, mode='both'):
    return route(label,[scale(k,v) for k,v in zip(factors,vectors,strict=True)],show=mode)


def build_card(n, *, title=None, part=None, question, answer, hint, steps, frames, cases, prompts, pages=None):
    theory=title is not None
    card=lesson(n,kind='theory' if theory else 'exercise',pages=pages or [241],part=part,
                question=question,answer=answer,hint=hint,steps=steps,frames=frames,cases=cases,
                checks=[None]+[check(*p) for p in prompts])
    card['review']['reviewer']='Атанасян, 2023 год, §3 главы X, печатные с. 237–241. Все коэффициенты, подпункты, направления и модели проверены по книге и координатам.'
    if theory:card['title']=title
    else:
        card['help'][1]['theoryIds']=['atanasyan-7-9-theory-91-part-1','atanasyan-7-9-theory-87-part-1']
        card['answer']['prompt']='Запиши построение. Укажи направления отдельных слагаемых и обозначь результат.'
    return card


