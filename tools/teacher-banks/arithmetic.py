def fmt(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f'{x.numerator}/{x.denominator}'


def dec(n, places=1):
    return f'{n / (10 ** places):.{places}f}'.replace('.', ',')


def ev(expr):
    ops = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul,
           ast.Div: operator.truediv, ast.Pow: operator.pow, ast.Mod: operator.mod,
           ast.FloorDiv: operator.floordiv}
    def walk(n):
        if isinstance(n, ast.Constant): return F(str(n.value))
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub): return -walk(n.operand)
        if isinstance(n, ast.BinOp) and type(n.op) in ops: return ops[type(n.op)](walk(n.left), walk(n.right))
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id in ('gcd', 'lcm'):
            return F({'gcd': gcd, 'lcm': lcm}[n.func.id](*(int(walk(a)) for a in n.args)))
        raise ValueError(expr)
    return F(walk(ast.parse(expr, mode='eval').body))


def plural(n, one, few, many):
    n=abs(int(n))
    return many if 11 <= n%100 <= 14 else one if n%10==1 else few if 2 <= n%10 <= 4 else many


def calc(q, expr, solution, unit=''):
    value=ev(expr)
    result = fmt(value)
    forms={'книг':('книга','книги','книг'),'кубиков':('кубик','кубика','кубиков'),'предметов':('предмет','предмета','предметов'),'учеников':('ученик','ученика','учеников'),'наборов':('набор','набора','наборов'),'карандашей':('карандаш','карандаша','карандашей'),'рублей':('рубль','рубля','рублей'),'задач':('задача','задачи','задач'),'страниц':('страница','страницы','страниц'),'дней':('день','дня','дней')}
    if value.denominator==1 and unit in forms: unit=plural(value,*forms[unit])
    return {'q': q, 'a': result + (f' {unit}' if unit else ''),
            'solution': solution.format(answer=result), 'points': 1,
            'check': {'kind': 'expression', 'expr': expr, 'expected': result}}


def decimalcalc(q, expr, solution, unit=''):
    task = calc(q, expr, solution, unit)
    raw = fmt(ev(expr))
    val = ev(expr)
    rendered = format(Decimal(val.numerator) / Decimal(val.denominator), 'f').rstrip('0').rstrip('.') if val.denominator != 1 else str(val.numerator)
    rendered = rendered.replace('.', ',')
    task['a'] = rendered + (f' {unit}' if unit else '')
    if '/' in raw:
        task['solution'] = task['solution'].replace(raw, rendered)
    return task


def eq(q, lhs, rhs, root):
    # The bank uses linear equations. Evaluate the two sides at 0 and 1
    # to display a concrete reduction, rather than a generic instruction.
    left0 = ev(lhs.replace('x', '(0)'))
    right0 = ev(rhs.replace('x', '(0)'))
    left1 = ev(lhs.replace('x', '(1)'))
    right1 = ev(rhs.replace('x', '(1)'))
    coefficient = (left1-left0) - (right1-right0)
    value = right0-left0
    left_at_root = fmt(ev(lhs.replace('x', f'({root})')))
    right_at_root = fmt(ev(rhs.replace('x', f'({root})')))
    reduced = f'{fmt(coefficient)}x = {fmt(value)}'
    solution = (f'Раскроем скобки, если они есть, и соберём слагаемые с x в левой части, числа — в правой: {reduced}. '
                f'Разделим обе части на {fmt(coefficient)}: x = {root}. '
                f'Проверка: левая часть равна {left_at_root}, правая — {right_at_root}.')
    return {'q': q, 'a': f'x = {root}', 'solution': solution, 'points': 1,
            'check': {'kind': 'equation', 'lhs': lhs, 'rhs': rhs, 'roots': [str(root)]}}


