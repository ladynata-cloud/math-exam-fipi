def scene(points, stages, extra_cases=()):
    """Arrowheads are segments without point labels, so reversing an arrow changes its visible end."""
    all_stages = stages + list(extra_cases)
    pictures=[]
    for label, visible, arrows, plain in all_stages:
        pictures.append(drawing({name:points[name] for name in visible},list(plain)+list(arrows)))
    result=model(pictures)
    for i,(label,visible,arrows,plain) in enumerate(all_stages):
        key='neutral' if i==0 else f'step-{i}'
        view=result['views'][key]
        view['label']=label
        for j,(start,end) in enumerate(arrows):
            a,b=(result['points'][f'{name}__v{i}'] for name in (start,end))
            dx,dy=b[0]-a[0],b[1]-a[1]
            length=hypot(dx,dy)
            if length==0:raise ValueError('A zero vector is represented by a point.')
            ux,uy=dx/length,dy/length
            depth=min(3.2,length*.27);half=depth*.47
            for side in (-1,1):
                anchor=f'head_{i}_{j}_'+('l' if side==-1 else 'r')
                result['points'][anchor]=[b[0]-depth*ux-side*half*uy,b[1]-depth*uy+side*half*ux,0]
                view['segments'].append([f'{end}__v{i}',anchor])
        if i>=len(stages):
            case_index=i-len(stages)+1
            view['availableFromStep']=1
            result['views'][f'case-{case_index}']=result['views'].pop(key)
    result['description']='Начало вектора находится у основания отрезка, конец — у острия стрелки.'
    return result


def check(prompt,answer,hint):
    return dict(prompt=prompt,accepted=[answer],feedback=hint)


def make(number, *, kind, pages, title, statement, result, hint, stages, picture, checks, part=None):
    source=dict(bookId=BOOK,collection='theory' if kind=='theory' else 'main',chapter='X',
                printedPages=pages,pdfPages=[n+1 for n in pages])
    source['point' if kind=='theory' else 'exercise']=str(number)
    part_n='абвг'.index(part)+1 if part else 1
    if part:source['subpart']=part
    prefix='theory' if kind=='theory' else 'main'
    steps=[]
    for i,((prompt,explanation,reason),sample) in enumerate(zip(stages,checks),1):
        step=dict(id=f'step-{i}',title=f'Шаг {i}',prompt=prompt,explanation=explanation,
                  view=f'step-{i}',justifications=[dict(kind='reason',text=reason)])
        if sample:step['input']=sample
        steps.append(step)
    assert len(stages)==len(checks) and set(picture['views']) >= {s['view'] for s in steps}
    help_items=[dict(id='first-hint',question='С чего начать?',text=hint),
                dict(id='compare-result',question='Сверить рассуждение',text=result)]
    if kind=='exercise':
        help_items.insert(1,dict(id='recall-theory',question='Повторить определение',text='Вернись к рисунку и проверь, где начало и конец стрелки.',
                                theoryIds=[f'atanasyan-7-9-theory-{n}-part-1' for n in ([84,85] if number in [926,927] else [85,86])]))
    card=dict(schemaVersion=1,id=f'atanasyan-7-9-{prefix}-{number}-part-{part_n}',revision=1,kind=kind,
              title=title,status='reviewed',source=source,review=REVIEW,statement=dict(text=statement,
              goal='Нарисуй или предскажи свой ответ до раскрытия разбора.'),
              visualization=dict(type='scene3d',caption='Сравни начало и конец каждой стрелки.',model=picture),
              help=help_items,steps=steps)
    if kind=='exercise':
        card['answer']=dict(mode='manual',prompt='Опиши построение или перечисли подходящие стрелки. Сверь его с рисунками по шагам.')
    return card


