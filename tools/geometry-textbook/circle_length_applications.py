def angle_lengths():
    rows=[('а',30,'1/12',['π','π см','pi'],3,120,'2'),('б',45,'1/8',['3π/2','1,5π','1.5π','3*pi/2'],4,90,'2'),
          ('в',60,'1/6',['2π','2π см','2*pi'],9,120,'6'),('г',90,'1/4',['3π','3π см','3*pi'],4,180,'4')]
    result=[]
    for part,alpha,frac,forms,r2,beta,new in rows:
        views=[arc('Данная дуга и радиусы к концам',6,alpha),arc('Сравни выделенный путь с полным оборотом',6,alpha),arc('Дуга другого радиуса и угла',r2,beta)]
