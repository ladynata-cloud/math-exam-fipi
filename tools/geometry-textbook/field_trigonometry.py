def chords_view(label,be,de,ce,bd,circum):
    ae=ce*de/be;u=(be*be+de*de-bd*bd)/(2*be*de);v=sqrt(1-u*u)
    pts={'E':(0,0),'A':(-ae,0),'B':(be,0),'D':(de*u,de*v),'C':(-ce*u,-ce*v)}
    cx=(be-ae)/2
    cy=(de*de-2*de*u*cx-ae*be)/(2*de*v)
    pts['S']=(cx,cy)
    radius=sqrt((be-cx)**2+cy*cy)
    return graph(label,pts,edges=[('A','B'),('C','D'),('B','D')],circle=('S',radius) if circum else None)


