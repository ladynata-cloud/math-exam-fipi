#!/usr/bin/env node
'use strict';
// Extract the existing, reviewed teaching content and generators. No evaluation,
// browser emulation or copied progress is used in the production server.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const base = path.join(root, 'trainers/oge-basics');
function files(dir) { return fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? files(path.join(dir,e.name)) : [path.join(dir,e.name)]); }
const out = ['/* Generated by tools/learning-remediation-bank.cjs. Edit the original trainer, then regenerate. */', '(function(root){\n\'use strict\';\nconst definitions=Object.create(null);'];
let count=0;
for (const file of files(base).filter(f=>f.endsWith('.html')).sort()) {
 const html=fs.readFileSync(file,'utf8'), id=path.relative(base,file).replaceAll(path.sep,'/').replace(/\.html$/,'');
 let body, result;
 if(html.includes('const SPEC =')) {
  const spec=html.slice(html.indexOf('const SPEC ='),html.indexOf('(function(){',html.indexOf('const SPEC =')));
  const start=html.indexOf('(function(){',html.indexOf('const SPEC ='))+'(function(){'.length;
  body=spec+html.slice(start,html.indexOf('  let state=',start)).replace(/^\s*document\.title[^\n]*\n/gm,'');
  result="{family:'basic',title:SPEC.title,topicId:SPEC.topicId,rule:SPEC.rule,lessons:SPEC.lessons,task:makePracticeTask(),answerEqual}";
 } else if(html.includes('function computeSteps')) {
  const start=html.indexOf('const CONFIG ='), end=html.indexOf('(function(){',start);
  body=html.slice(start,end)+html.slice(end+'(function(){'.length,html.indexOf('let state=',end));
  result="{family:'division',title:CONFIG.title,topicId:CONFIG.topicId,config:CONFIG,task:gen(pick(CONFIG.levels)),answerEqual:stepMatches,makeCheck:()=>{const modes=CONFIG.levels.filter(x=>x!=='quotientDigit');const out=[];for(let i=0;i<Math.min(3,CONFIG.levels.length);i++){const index=Math.floor(Math.random()*modes.length);out.push(gen(modes.splice(index,1)[0]))}return out}}";
 } else if(html.includes('const SKILLS=')) {
  const start=html.indexOf('const $=id=>document.getElementById(id);');
  body=html.slice(start,html.indexOf('const MAP_KEY=',start));
  result="{family:'percent',title:TITLE,topicId:TOPIC,rule:SUBTITLE,lessons:LESSONS,skills:SKILLS,task:(()=>{const key=pick(Object.keys(SKILLS));const t=norm(makeTask(key));t.skill=key;return t})(),makeCheck:()=>{const seen=new Set(),out=[];CHECK_PLAN.forEach(k=>{let t,g=0;do{t=norm(makeTask(k));t.skill=k;g++}while(seen.has(t.prompt)&&g<60);seen.add(t.prompt);out.push(t)});return out}}";
 } else continue;
 if (!body || /localStorage|document\.title\s*=/.test(body)) throw Error('Unsafe extraction: '+id);
 out.push('definitions['+JSON.stringify(id)+']=function(seed){\nconst Math=Object.create(globalThis.Math);let randomState=(seed>>>0)||1;Math.random=()=>{randomState=(globalThis.Math.imul(1664525,randomState)+1013904223)>>>0;return randomState/4294967296};\n'+body+'\nreturn '+result+';\n};');
 count++;
}
if(count!==35)throw Error('Expected 35 source trainers, got '+count);
out.push("if(typeof module==='object'&&module.exports)module.exports=definitions;else root.MathExamRemediationBank=definitions;\n})(typeof window==='undefined'?globalThis:window);\n");
const target=path.join(base,'learning-bank.js'), result=out.join('\n');
if(process.argv.includes('--check')) { if(fs.readFileSync(target,'utf8')!==result)throw Error('Regenerate learning-bank.js after editing trainer content.'); }
else fs.writeFileSync(target,result);
console.log('Remediation teaching bank: '+count+' source trainers, '+Buffer.byteLength(result)+' bytes.');
