def build():
    cards=[]
    for n,part,kind,values,text,forms,reason,hint,probe,other in ROWS:
        outside=n==1193
        note='T — центр, UW — одна единица. '+('Окружность проходит через вершины.' if outside else 'Окружность касается каждой стороны. Отрезок от T к точке касания перпендикулярен стороне.')
        views=scenes(kind,values,outside)
        steps=[('Определи, где искать радиус',('Соедини T с вершинами. Каждая из этих точек лежит на окружности, поэтому расстояния до них равны R.' if outside else 'Найди перпендикуляр из T на сторону. Его длина равна внутреннему радиусу r.')+' '+hint,hint),
               ('Выведи длину окружности',reason,'В конце умножь радиус на 2π или весь диаметр на π.'),
               ('Проверь на новых данных',REPEATS[n,part], 'Сравни измеряемую величину с той же меркой UW на последнем чертеже.')]
        e=area(n,part,[307],text,reason,hint,steps,views,[probe,other],refs=[115,116,118])
        e['source']['chapter']='XIII';e['help'][1]['text']=hint
        e['review']['reviewer']='Атанасян 7–9, 2023, 14-е издание: сверены все 5+4 подпункта №1193–1194 на печатной с. 307 и ответы на с. 401. Радиусы до вершин и расстояния до сторон измерены на каждой построенной фигуре.'
        e['visualization']['caption']=note;e['visualization']['model']['description']=note
        if not outside:
            for v in e['visualization']['model']['views'].values():
                ids={name:k for k in v['points'] for name in e['visualization']['model']['labels'][k].split('=')}
                marks=[('H','A'),('K','B')] if kind=='square' else [('H','A'),('K','B'),('L','C')]
                v['rightAngles']=[{'vertex':ids[foot],'a':ids['T'],'b':ids[end],'size':1.5} for foot,end in marks]
        cards.append(grade(e,forms,hint,'Введи длину окружности в точной форме. Разрешены π или pi, √ или sqrt и указанные буквы условия.'))
    return {'bookId':BOOK,'lessons':cards}


