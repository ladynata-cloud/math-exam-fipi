def distinct_vectors(label, p=(2,1), q=(-2,4)):
    a=(0,0);c=(5,0)
    return frame(label,{'A':a,'B':p,'C':c,'D':(c[0]+q[0],c[1]+q[1])},[('A','B'),('C','D')])


