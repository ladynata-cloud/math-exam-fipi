def tower_view(label,d,down,up,mark=True):
    eye=d*tan(radians(down));top=eye+d*tan(radians(up))
    pts={'M':(0,eye/10),'B':(d/10,0),'H':(d/10,eye/10),'T':(d/10,top/10)}
    edges=[('M','T'),('M','B'),('B','T')]
    if mark:edges.extend([('M','H'),('B','H'),('H','T')])
    else:del pts['H']
    return graph(label,pts,edges=edges)


