'use strict';
// Compile exact-model surface amendments into the existing self-contained viewer.
// No lesson, learner identity, source text or historical review is rewritten.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..'), directory = path.join(__dirname, 'visibility-profiles');
const signature = source => JSON.stringify([source.points, source.edges || [], source.faces || [],
  Object.entries(source.views || {}).map(([id, view]) => [id, view.segments || [], view.polygon || []]), !!source.planar]);
const lessons = new Map(['textbook', 'merzlyak-10-base', 'shestakov-yaschenko-10-11'].flatMap(course =>
  JSON.parse(fs.readFileSync(path.join(root, 'stereo-course', course, 'data/course.json'), 'utf8')).lessons.map(lesson => [lesson.id, lesson])));
const entries = new Map();
for (const name of fs.readdirSync(directory).filter(name => name.endsWith('.json')).sort()) {
  const document = JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8'));
  for (const row of Array.isArray(document) ? document : document.profiles || []) {
    const [points, , , views] = JSON.parse(row.signature), knownViews = new Set(views.map(view => view[0]));
    assert.equal(typeof row.signature, 'string');
    assert(Array.isArray(row.lessonIds) && row.lessonIds.length, name + ': explicit amended lessons');
    for (const id of row.lessonIds) {
      assert(lessons.has(id), name + ': existing amended lesson ' + id);
      assert.equal(signature(lessons.get(id).visualization.model), row.signature, name + ': exact original geometry ' + id);
    }
    const geometry = {};
    for (const key of ['faces', 'views', 'spheres', 'viewSpheres']) if (row[key] !== undefined) geometry[key] = row[key];
    for (const faces of [geometry.faces || [], ...Object.values(geometry.views || {})]) {
      for (const face of faces) assert(face.length >= 3 && face.every(name => Array.isArray(points[name])), name + ': unknown face vertex');
    }
    for (const key of [...Object.keys(geometry.views || {}), ...Object.keys(geometry.viewSpheres || {})]) assert(knownViews.has(key), name + ': unknown view');
    for (const spheres of [geometry.spheres || [], ...Object.values(geometry.viewSpheres || {})]) for (const sphere of spheres) {
      assert(sphere.center.length === 3 && sphere.center.every(Number.isFinite) && Number.isFinite(sphere.radius) && sphere.radius > 0);
      for (const edge of sphere.surfaceEdges || []) assert(edge.length === 2 && edge.every(name => Array.isArray(points[name])));
    }
    if (entries.has(row.signature)) assert.deepEqual(entries.get(row.signature), geometry, 'Conflicting profile for identical geometry');
    entries.set(row.signature, geometry);
  }
}
const file = path.join(root, 'stereo-course/assets/task-scene-viewer.js'), before = fs.readFileSync(file, 'utf8');
const begin = '  // BEGIN REVIEWED SURFACE PROFILES (generated by build_visibility_profiles.cjs)';
const end = '  // END REVIEWED SURFACE PROFILES';
const from = before.indexOf(begin), to = before.indexOf(end);
assert(from >= 0 && to > from && before.indexOf(begin, from + 1) === -1);
const sorted = [...entries].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const block = begin + '\n  const SURFACE_PROFILES = new Map(' + JSON.stringify(sorted) + ');\n';
const after = before.slice(0, from) + block + before.slice(to);
if (process.argv.includes('--check')) assert.equal(before, after, 'Reviewed surface profile bundle needs rebuilding');
else fs.writeFileSync(file, after);
console.log('STEREO_VISIBILITY_PROFILES_OK:', entries.size, 'exact geometry signatures');
