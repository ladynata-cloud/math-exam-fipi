def candidates(title, cy, mode):
    points={'A':(0,0),'B':(4,0),'M':(2,2),'N':(2,-2)}
    edges=[('A','B'),('A','M'),('A','N'),('B','M'),('B','N')]
    if mode!=0:
        points['C']=(1,cy)
        edges.extend([('C','M'),('C','N'),('A','C'),('B','C')])
    return schematic(title,points,edges)


