def medians(title,apex,left,right,initial=False):
    pts={'A':apex,'B':left,'C':right}
    if initial:
        pts['M']=scale(add(left,right),.5)
        return copy_figure(title,pts,'AB AC AM','AB BC CA')
    pts['H']=scale(add(apex,right),.5);pts['K']=scale(add(apex,left),.5)
    return copy_figure(title,pts,'BH CK','AB BC CA')


