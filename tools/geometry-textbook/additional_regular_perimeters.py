def attached_square(label, radius, focus):
    side = radius*sqrt(3)
    h = side*sqrt(3)/2
    pts = {'A':(-side/2,0),'B':(side/2,0),'C':(0,h),'D':(side/2,-side),
           'E':(-side/2,-side),'T':(0,h/3),'K':(0,-side/2),
           'U':(-side/2,-side-1),'W':(1-side/2,-side-1)}
    edges = outline(list('ABC')) + [('B','D'),('D','E'),('E','A'),('U','W'),('T','A'),('K','B')]
    if focus == 'square':
        edges.append(('B','E'))
    return drawing(label,pts,edges,'T' if focus=='triangle' else 'K',
                   radius if focus=='triangle' else side/sqrt(2),
                   [('T','A'),('A','B')] if focus=='triangle' else [('E','B'),('K','B')])


