SUB=str.maketrans('0123456789','₀₁₂₃₄₅₆₇₈₉')


def vertex(i):
    return 'A'+str(i).translate(SUB)


def intersection(p,q,r,s):
    cross=lambda a,b:a[0]*b[1]-a[1]*b[0]
    sub=lambda a,b:(a[0]-b[0],a[1]-b[1])
    u,v=sub(q,p),sub(s,r)
    t=cross(sub(r,p),v)/cross(u,v)
    return (p[0]+t*u[0],p[1]+t*u[1])


def crossing(label,n,R,focus,angle=0):
    other=(6,9) if n==12 else (4,7)
    a,b,c,d=[vertex(k) for k in (1,other[0],2,other[1])]
    labels=[vertex(k) if k in (1,2,*other) else '_vertex'+str(k) for k in range(1,n+1)]
    p=dict(zip(labels,ring(n,R,angle),strict=True))
    p.update(T=(0,0),B=intersection(p[a],p[b],p[c],p[d]),U=(-R,-R-.6),W=(1-R,-R-.6))
    edges=outline(labels)+[(a,b),(c,d),('U','W'),(a,'B'),('B',b),(c,'B'),('B',d)]
    if n==12:
        p['H']=tuple((x+y)/2 for x,y in zip(p[a],p[c]))
        edges.extend([('T','H'),('H',a),('H',c),('T',a),('T',b)])
        highlights={'first':[(a,c),(c,'B'),('B',a)],'second':[(b,d),(d,'B'),('B',b)],
                    'radii':[(a,b),('T','H')]}[focus]
    else:
        edges.extend([('T',a),('T',b),('T',c),('T',d)])
        highlights={'diameter':[(c,'T'),('T',d)],'first':[(a,c),(c,'B'),('B',a)],
                    'second':[('B',b),(b,'T'),('T','B')], 'sum':[(a,'B'),('B',b)]}[focus]
    return drawing(label,p,edges,'T',R,highlights)


def octagon(label,R,focus):
    corners=[(-R,0),(0,R),(R,0),(0,-R)]
    p=dict(zip([vertex(i) for i in range(1,5)],corners,strict=True))
    for i,corner in enumerate(corners):
        for name,j in [('B',i+1),('C',i-1)]:
            other=corners[j%4]
            p[name+str(i+1).translate(SUB)]=tuple(x+(y-x)/sqrt(2) for x,y in zip(corner,other))
    perimeter=['B₁','C₃','B₂','C₄','B₃','C₁','B₄','C₂']
    p.update(T=(0,0),U=(-R,-R-.8),W=(1-R,-R-.8))
    edges=outline([vertex(i) for i in range(1,5)])+outline(perimeter)+[('U','W'),('T','A₁')]
    focus_edges={'marks':[('A₁','B₁'),('A₁','C₁')],'corner':[('B₁','A₂'),('A₂','C₃'),('B₁','C₃'),('C₂','B₁')],
                 'area':outline(perimeter)}[focus]
    return drawing(label,p,edges,'T',R,focus_edges), perimeter


