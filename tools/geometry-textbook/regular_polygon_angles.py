def scene(label,n,mode):
    theta=2*pi/n;r=4
    names=['A','B',*['_poly'+str(i) for i in range(2,n-1)],'V'] if n>3 else ['A','B','V']
    pts={s:(r*cos(i*theta),r*sin(i*theta)) for i,s in enumerate(names)}
    edges=list(zip(names,names[1:]+names[:1],strict=True))
    show_circle=mode in ('circle','sector','unique')
    if show_circle:
        pts['T']=(0,0)
        edges+=[('T','A'),('T','B'),('T','V')]
    if mode in ('circle','unique'):
        for k in names[2:-1]:edges.append(('T',k))
        accented=[('T','A'),('T','B'),('T','V')]
    else:
        if mode=='sector':
            middle=(0,0);start=0;end=theta;radius=1
            accented=[('T','A'),('T','B')]
        elif mode=='exterior':
            middle=pts['A'];start=pi/2-theta/2;end=pi/2+theta/2;radius=.65
            pts['E']=(middle[0]+1.2*cos(start),middle[1]+1.2*sin(start))
            edges.append(('A','E'));accented=[('A','E'),('A','B')]
        else:
            middle=pts['A'];start=pi/2+theta/2;end=3*pi/2-theta/2;radius=.55
            accented=[('A','V'),('A','B')]
        samples=12
        for j in range(samples+1):
            phi=start+(end-start)*j/samples
            pts['_angle'+str(j)]=(middle[0]+radius*cos(phi),middle[1]+radius*sin(phi))
        arc=[('_angle'+str(j),'_angle'+str(j+1)) for j in range(samples)]
        edges+=arc;accented+=arc
    shape=graph(label,pts,edges=edges,circle=('T',r) if show_circle else None)
    # graph can merge the circumcenter with its internal coordinate origin.
    coords=shape[0][1]
    rendered={(round(x,9),round(y,9)):k for k,(x,y) in coords.items()}
    def name(k):return rendered[(round(pts[k][0],9),round(pts[k][1],9))]
    return shape[:3]+([(name(a),name(b)) for a,b in accented],)


