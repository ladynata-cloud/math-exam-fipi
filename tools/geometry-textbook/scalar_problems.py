def compare_directions():
    def sample(label,k):
        if k==3:return figure({'O':(0,0),'P':(6,0)}) (label,'OP')
        f=figure({'O':(0,0),'P':(6,0),'T':(2*k,0)})
        return f(label,'OP OT')
    labels=['a = p/3','−a = −p/3','½a = p/6','−2a = −⅔p','6a = 2p']
    cases=[sample(label,k) for label,k in zip(labels,[1,-1,.5,-2,6],strict=True)]
    compare=build_card(967,
        question='Пусть p=3a и a ненулевой. Для a, −a, ½a, −2a и 6a определи направление относительно p и вырази длину через |p|.',
        answer='С p сонаправлены a, ½a и 6a. Стрелки −a и −2a направлены противоположно p. Длины в том же порядке равны |p|/3, |p|/3, |p|/6, 2|p|/3 и 2|p|. Например, −2a=−(2/3)p.',
        hint='Сначала вырази a через p. Затем для каждого коэффициента отдельно прочитай знак и модуль.',
        steps=[('Возьми p за единицу сравнения','Тройка положительна. Поэтому a=(1/3)p и направлен так же, как p. Для −a коэффициент −1/3 меняет направление, но не длину.', 'Если ненулевой вектор умножен на положительное число, сохраняется его направление.'),
               ('Сравни дробный и отрицательный множители','Для ½a коэффициент относительно p равен 1/6. Для −2a он равен −2/3. В формуле длины минус исчезает: |−2a|=(2/3)|p|.', 'Модуль произведения равен модулю коэффициента, умноженному на длину исходного вектора.'),
               ('Заверши список и проверь масштаб','6a=(6/3)p=2p. Открой пять схем: в каждой O→P изображает один и тот же p, O→T — выбранный результат. Сравни длины с UV.', 'Для ненулевого p знак коэффициента и модуль полностью определяют коллинеарную стрелку.')],
        frames=[sample('Исходный p',3),cases[0],cases[3],cases[4]],cases=cases,
        prompts=[('Если |p|=12, какова длина −2a?', '8','Возьми две трети от 12; модуль неотрицателен.'),
                 ('В новом примере |p|=18. Чему равна длина ½a?', '3','У ½a длина |p|/6.')])
    proofs=[]
    for part,k,name in [('а',1,'1·a=a'),('б',-1,'(−1)·a=−a')]:
        initial=figure({'O':(0,0),'A':(2,1)})('Исходный ненулевой вектор','OA')
        target=figure({'O':(0,0),'A':(2,1),'P':(1,3),'T':(1+2*k,3+k)})('Произведение из P','OA PT')
        zero=frame('Исходный вектор нулевой',{'O':(0,0)})
        direction='совпадает с исходным' if k==1 else 'противоположно исходному'
        result='сам a' if k==1 else 'противоположный вектор −a'
        proofs.append(build_card(968,part=part,question=f'Докажи тождество {name} для любого вектора a, в том числе нулевого.',
            answer=f'У ненулевого a множитель {k} сохраняет длину, а направление произведения {direction}. Поэтому произведение есть {result}. Для a=0 обе части равны нулевому вектору.',
            hint='Для равенства стрелок одной длины недостаточно. Проверь длину, направление и отдельно случай нулевой длины.',
            steps=[('Вычисли длину произведения',f'Модуль числа {k} равен 1, поэтому длина произведения {k}·a равна |a|.','При вычислении длины произведения используют модуль множителя.'),
                   ('Установи направление',f'При a≠0 направление произведения {direction}. Вместе с равенством длин этого достаточно, чтобы получить {result}.','Равные векторы сонаправлены и имеют равные длины; у противоположных длина та же, направление обратное.'),
                   ('Обработай нулевой вектор отдельно','Если a=0, произведение нулевого вектора на любое число есть 0. Противоположный нулевому также нулевой, и равенство сохраняется.', 'О направлении нулевой стрелки рассуждать не требуется.')],
            frames=[initial,initial,target,zero],cases=[target,zero],
            prompts=[('На образце a=(2;1). Найди горизонтальную составляющую произведения.',str(2*k),'Знак множителя определяет, изменить ли знак числа 2.'),
                     ('В другой задаче вертикальная составляющая a равна −3. Какова она у произведения?',str(-3*k),'Умножь −3 на '+str(k)+'.')]))
    return [compare]+proofs


def substitutions():
    m=(3,0);n=(0,6);x=(3,6);y=(3,-6)
    initial=figure({'O':(0,0),'M':m,'N':n,'X':x,'Y':y})('Исходные векторы','OM ON OX OY')
    tasks=[
        ('а','2x−2y',(2,-2),(0,4),'4n','После подстановки 2m+2n−2m+2n остаются четыре n.'),
        ('б','2x+½y',(2,.5),(2.5,1.5),'(5/2)m+(3/2)n','Прибавь половину (m−n) к удвоенному (m+n). Коэффициент m равен 2+½=5/2, коэффициент n равен 2−½=3/2.'),
        ('в','−x−⅓y',(-1,-1/3),(-4/3,-2/3),'−(4/3)m−(2/3)n','Подстановка даёт −m−n−⅓m+⅓n. Собери m и n отдельно: −1−⅓=−4/3, а −1+⅓=−2/3.')]
    out=[]
    for part,expr,coeff,reduced,answer,why in tasks:
        original=scaled_path('Путь через x и y',coeff,(x,y))
        simplified=scaled_path('Тот же результат через m и n',reduced,(m,n))
        note=(' В ответах на печатной с. 397 при n стоит −3/2. Для условия на с. 241 правильный коэффициент −2/3. При m=0, n=(0;6) получаем (0;−4); коэффициент −3/2 дал бы (0;−9).') if part=='в' else ''
        out.append(build_card(969,part=part,question=f'Пусть x=m+n, y=m−n. Вырази {expr} через m и n, не меняя направления исходных стрелок.',
            answer=f'{expr}={answer}. '+why+note,hint='После замены x и y оставь скобки до распределения каждого коэффициента. Следи за слагаемым −n внутри y.',
            steps=[('Поставь вместо x и y их определения',f'У x слагаемые m и n имеют одинаковые знаки; у y перед n минус. У выражения {expr} свой множитель перед каждой целой скобкой.', 'Множитель действует на оба слагаемых скобки.'),
                   ('Собери коэффициенты',why,'Сочетательный и распределительный законы позволяют складывать коэффициенты при одном и том же векторе.'),
                   ('Сверь два построения',f'У образцов m=(3;0), n=(0;6). Пройди первый путь через x, y и второй через m, n. Их последние точки совпали.'+note,'При подстановке любой пары векторов обе записи должны давать одинаковые составляющие.')],
            frames=[initial,initial,original,simplified],cases=[original,simplified]+([scaled_path('Проверка при m=0',coeff,((0,6),(0,-6)))] if part=='в' else []),
            prompts=[('На образце m=(3;0), n=(0;6). Чему равна вертикальная составляющая результата?',str(int(6*reduced[1])),'На вертикаль влияет только n. Умножь 6 на его коэффициент.'),
                     ('В новом примере горизонтальные составляющие m и n равны 6 и 0. Найди горизонтальную составляющую результата.',str(int(6*reduced[0])),'При нулевой горизонтальной составляющей n осталось умножить 6 на коэффициент m.')]))
    return out


def parallelograms():
    p=dict(A=(0,0),B=(4,0),C=(6,4),D=(2,4),E=(1,2),G=(5,2))
    f=figure(p,'AB BC CD DA')
    ec=f('От E через D к C','ED DC EC')
    ag=f('От A через B к G','AB BG AG')
    both=f('Две равные стрелки','EC AG')
    mid=build_card(970,question='E и G — середины сторон AD и BC параллелограмма ABCD. Даны D→C=a и B→C=b. Вырази E→C и A→G через a и b.',
        answer='Оба вектора равны a+½b. Из E идём в D на половину b, затем в C на a. Из A идём в B на a, затем в G на половину b. В печатном ключе на с. 397 напечатан минус. Направление B→C в условии на с. 241 даёт плюс.',
        hint='Сравни острия E→D и B→C. Если направлены одинаково, половина b в первой сумме имеет положительный знак.',
        steps=[('Поставь обозначения на стороны','A→B=D→C=a, A→D=B→C=b. Поскольку E и G — середины соответствующих сторон, E→D и B→G равны ½b.', 'Сонаправленные противоположные стороны параллелограмма задают равные векторы.'),
               ('Пройди по двум маршрутам','По правилу треугольника E→C=E→D+D→C=½b+a. На другом маршруте A→G=A→B+B→G=a+½b. Ответы совпали.', 'Перестановка двух слагаемых не меняет векторную сумму.'),
               ('Проверь знак по высоте','На схеме a=(4;0), b=(2;4). У E→C и A→G вертикальное смещение +2, следовательно a+½b даёт верное направление. При минусе получилось бы −2, противоположно обеим стрелкам.', 'Проверка одной несовпадающей координаты достаточна, чтобы отвергнуть ошибочный знак.')],
        frames=[f('Середины на противоположных сторонах','DC BC'),f('Половины b','ED BG'),ec,both],cases=[ec,ag,both],
        prompts=[('На образце a=(4;0), b=(2;4). Найди вертикальную составляющую E→C.', '2','Движение от E к D поднимает на половину 4; D→C не меняет высоту.'),
                 ('У другой фигуры горизонтальные составляющие a и b равны −3 и 8. Какова горизонтальная составляющая A→G?', '1','Вычисли −3+½×8.')])
    p=dict(A=(0,0),B=(4,0),C=(4,4),D=(0,4),M=(4,3))
    f=figure(p,'AB BC CD DA')
    am=f('Из A через B к M','AB BM AM')
    md=f('Из M через C к D','MC CD MD')
    both=f('Два пути последовательно','AM MD AD')
    ratio=build_card(971,question='На стороне BC параллелограмма ABCD выбрана M. Отношение BM к MC равно 3:1. Вырази A→M и M→D через a=A→D, b=A→B.',
        answer='B→M=(3/4)a и M→C=(1/4)a. Тогда A→M=b+(3/4)a, а M→D=(1/4)a−b.',
        hint='Общее число равных частей на стороне BC равно 3+1. Сначала подпиши обе доли стороны, затем выбери пути через B и C.',
        steps=[('Разметь сторону BC','Длина BM занимает три из четырёх равных частей BC. Обе части пути B→M→C направлены вдоль a. Поэтому B→M=¾a, M→C=¼a.', 'Вектор стороны B→C равен противоположной стороне A→D.'),
               ('Собери первый и второй векторы','A→M=A→B+B→M=b+¾a. M→D=M→C+C→D=¼a−b, поскольку сторона C→D направлена против A→B.', 'У противоположных сторон важно сохранить ориентацию стрелок.'),
               ('Сложи ответы для самопроверки','A→M+M→D должно равняться A→D. Складываем b+¾a и ¼a−b: b сокращается, три четверти и одна четверть составляют a.', 'Промежуточная точка M должна исчезнуть при свёртывании пути.')],
        frames=[f('Три части и одна','AD AB'),f('Направление от B к C','BM MC'),am,md],cases=[am,md,both],
        prompts=[('У a вертикальная составляющая 4, у b — 0. Найди вертикальную составляющую A→M.', '3','Возьми три четверти от 4.'),
                 ('На другой фигуре горизонтальные составляющие a и b равны 8 и 3. Найди горизонтальную составляющую M→D.', '-1','Вычисли четверть от 8 минус 3.')])
    return [mid,ratio]


def build():
    return dict(bookId=BOOK,lessons=compare_directions()+substitutions()+parallelograms())


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text=json.dumps(build(),ensure_ascii=False,separators=(',',':'))+'\n'
    if args.check:assert OUT.read_text()==text
    else:OUT.write_text(text)
