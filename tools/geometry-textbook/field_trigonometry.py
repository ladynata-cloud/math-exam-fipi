def mountain_view(label,h,complete):
    mountain=h/2;run=mountain*sqrt(3)
    pts={'P':(0,0),'C':(0,mountain/10),'B':(0,(mountain+h)/10),'A':(run/10,0)}
    edges=[('P','B'),('A','P'),('A','C')]
    if complete:edges.extend([('A','B'),('B','C')])
    return graph(label,pts,edges=edges,lines=[(pts['C'],pts['B'])])


