def pairs(words):
    result = []
    for word in words.split():
        pair = re.findall(r'[A-Z]₁?', word)
        assert len(pair) == 2 and ''.join(pair) == word
        result.append(tuple(pair))
    return result


def figure(points, outline=''):
    def view(label, arrows=''):
        return frame(label, points, pairs(arrows), pairs(outline))
    return view


