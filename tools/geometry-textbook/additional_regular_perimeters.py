def hexagon(label, diameter, focus):
    r = diameter/2
    pts = dict(zip('ABCDEF',ring(6,r,0),strict=True))
    pts.update(T=(0,0), U=(-r,-r-.35), W=(1-r,-r-.35))
    edges = outline(list('ABCDEF')) + [('A','D'),('A','T'),('U','W')]
    if focus: edges.extend([('T','B'),('T','C'),('T','E'),('T','F')])
    return drawing(label,pts,edges,'T',r,[('A','B'),('A','T')] if focus else [('A','D')])


