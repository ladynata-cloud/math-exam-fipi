def isosceles(label,side,alpha):
    a=radians(alpha);A=(0,0);C=(side,0);B=(side*cos(a),side*sin(a));E=(B[0],0)
    D=((B[0]+C[0])/2,B[1]/2)
    return graph(label,{'A':A,'B':B,'C':C,'D':D,'E':E},edges=[('A','B'),('B','C'),('C','A'),('A','D'),('B','E')])


