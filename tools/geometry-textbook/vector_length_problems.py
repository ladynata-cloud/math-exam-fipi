def circle_distances(n):
    d1,d2=(18,12) if n==983 else (11,16)
    radius=(d1+d2)/2
    x=sqrt(radius**2-(d1-radius)**2)
    p={'O':(0,radius),'T':(0,0),'C':(-x,d1),'D':(x,d2),'C₁':(-x,0),'D₁':(x,0)}
    f=figure(p,'CD C₁D₁ CC₁ DD₁ OT')
    raw=f('Диаметр и касательная')
    h=f('Перпендикулярные расстояния','C₁C D₁D')
    center=f('Высота центра — радиус','TO')
    diameter=f('Сравни сумму высот и диаметр','CD')
    if n==983:
        question='Концы диаметра окружности находятся на расстояниях 18 и 12 см от одной касательной. Каков диаметр окружности?'
        answer='Центр O — середина диаметра. Его расстояние от касательной равно полусумме расстояний концов, (18+12)/2=15 см. Радиус, проведённый в точку касания, перпендикулярен касательной, поэтому радиус 15, а диаметр 30 см.'
        feedback='Если получилось 15, найден радиус. Удвой его, чтобы получить диаметр. Для другой попытки сравни расстояние от центра со средним из 18 и 12.'
        original=('Вычисли расстояние от центра до касательной в сантиметрах.', '15','Возьми полусумму 18 и 12.')
        repeat=('В другой окружности расстояния концов диаметра до одной касательной равны 8 и 14 см. Найди диаметр.', '22','Полусумма даёт радиус 11. Диаметр вдвое больше.')
        final=(30,'Введи диаметр окружности в сантиметрах числом.',feedback)
    else:
        question='Из концов диаметра CD опущены перпендикуляры CC₁ и DD₁ к одной касательной, которая не перпендикулярна CD. Известны CC₁=11 см и CD=27 см. Найди DD₁.'
        answer='Радиус равен 13,5 см, а расстояние центра до касательной является средним расстояний концов диаметра. Поэтому 11+DD₁=2×13,5=27 и DD₁=16 см.'
        original=('Чему равна сумма двух перпендикулярных расстояний от концов при диаметре 27 см?', '27','Сумма расстояний равна удвоенному расстоянию от центра, то есть диаметру.')
        repeat=('У другой окружности диаметр 25 см, а расстояние одного конца равно 8 см. Найди расстояние второго.', '17','Вычти 8 из 25.')
        final=(16,'Введи длину DD₁ в сантиметрах числом.','Если получилось 2,5, это разность между радиусом и первым расстоянием. Чтобы найти второе расстояние, вычти 11 из всего диаметра 27.')
    entry=practice(n,final,question=question,answer=answer,
        hint='Поверни рисунок мысленно так, чтобы касательная стала горизонтальной. Тогда расстояния до неё — вертикальные высоты. Где находится центр между концами диаметра?',
        steps=[('Поставь высоты от одной линии','Вся окружность лежит по одну сторону от касательной. Если взять её за нулевую горизонталь, высоты C и D равны их неотрицательным расстояниям от касательной.', 'Расстояние от точки до прямой измеряется перпендикуляром.'),
               ('Возьми среднее для середины диаметра','O — середина CD. Его высота равна среднему высот C и D. При этом OT до точки касания — радиус, поскольку он перпендикулярен касательной.', 'В параллельной системе отсчёта координата середины — среднее координат концов.'),
               ('Используй удвоение',answer,'Сумма высот концов диаметра равна двум радиусам. Знать наклон самого диаметра не требуется.')],
        frames=[raw,h,center,diameter],cases=[h,center,diameter],prompts=[original,repeat])
    model=entry['visualization']['model']
    for view in model['views'].values():
        suffix='__v'+view['points'][0].split('__v')[-1]
        view['circles']=[{'center':'O'+suffix,'through':'C'+suffix}]
        view['rightAngles']=[dict(vertex='T'+suffix,a='O'+suffix,b='D₁'+suffix,size=2)]
    fit_circles(model)
    entry['visualization']['caption']='T — точка касания. Высоты от C, O и D перпендикулярны одной касательной. UV — единичный отрезок.'
    return entry


