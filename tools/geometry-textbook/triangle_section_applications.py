def interpolate(p,q,wp,wq):
    return tuple((wp*x+wq*y)/(wp+wq) for x,y in zip(p,q))


def bisector_view(title,a,alpha,beta,which):
    gamma=180-alpha-beta
    x=a*sin(radians(alpha))/sin(radians(gamma));y=a*sin(radians(beta))/sin(radians(gamma))
    P={'A':(0,0),'B':(a,0),'C':(y*cos(radians(alpha)),y*sin(radians(alpha)))}
    cross={'A':('D',interpolate(P['B'],P['C'],y,a)),
           'B':('E',interpolate(P['A'],P['C'],x,a)),
           'C':('F',interpolate(P['A'],P['B'],x,y))}
    edges=[('A','B'),('A','C'),('B','C')]
    for k in which:
        nm,position=cross[k];P[nm]=position;edges.append((k,nm))
    return graph(title,P,edges=edges)


