def numeric(e,n,hint,degrees=True):
    forms=[str(n),str(n)+'°',str(n)+' градусов'] if degrees else [str(n),str(n)+',0',str(n)+'.0']
    return grade(e,forms,hint,'Введи число градусов.' if degrees else 'Введи число сторон целым числом.')


