// Build committed browser data. No dependencies or network access.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = name => JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const lessons = ['logic.json','arithmetic.json','percent.json','part2.json','part3.json'].flatMap(read).map(l=>({...l,part:l.part||1})).sort((a,b)=>a.order-b.order);
const source = read('source-map.json');
const exerciseIndex = {};
for(const r of source.exercisePageRanges){
  for(let n=r.firstExercise;n<=r.lastExercise;n++){
    const i=source.topics.findIndex(t=>n>=t.firstExercise&&n<=t.lastExercise);
    const review=source.selfChecks.find(t=>n>=t.firstExercise&&n<=t.lastExercise);
    const lesson=i>=0?'p'+String(i+1).padStart(2,'0'):(n<176?'p07':n<308?'p10':'p14');
    exerciseIndex[n]={page:r.page,lesson,review:!!review};
  }
}
const maps=[source,read('source-map-part2.json'),read('source-map-part3.json')];
const exerciseIndexByPart={1:exerciseIndex};
for(let part=2;part<=3;part++){
  const map=maps[part-1],index={},offset=part===2?14:32;
  for(const r of map.exercisePageRanges){
    for(let n=r.firstExercise;n<=r.lastExercise;n++){
      const i=map.topics.findIndex(t=>n>=t.firstExercise&&n<=t.lastExercise);
      const review=[...(map.selfChecks||[]),...(map.reviews||[])].some(t=>n>=t.firstExercise&&n<=t.lastExercise);
      const preceding=map.topics.reduce((last,t,k)=>n>=t.firstExercise?k:last,0);
      const lesson='p'+String(offset+(i>=0?i:preceding)+1).padStart(2,'0');
      index[n]={page:r.page,lesson,review,part};
    }
  }
  const overrides=map.exerciseOverrides||map.overrides||{};
  for(const [n,override] of (Array.isArray(overrides)?overrides.map(x=>[x.exercise,x]):Object.entries(overrides))){
    const i=map.topics.findIndex(t=>Number(n)>=t.firstExercise&&Number(n)<=t.lastExercise);
    index[n]={lesson:'p'+String(offset+Math.max(i,0)+1).padStart(2,'0'),...(index[n]||{}),...override,part};
  }
  for(const n of map.scope?.missingExerciseNumbers||[])index[n]={...(index[n]||{}),missing:true};
  exerciseIndexByPart[part]=index;
}
const sources=maps.map((map,i)=>({...map.source,part:i+1}));
const data={version:1,source:{...source.source,title:'Математика. 6 класс. Учебник в 3 частях',availableParts:[1,2,3],missingParts:[]},sources,lessons,exerciseIndex,exerciseIndexByPart};
const text='// Generated by build.cjs from authored content and verified source map.\nwindow.PetersonCourse = '+JSON.stringify(data,null,1).replace(/</g,'\\u003c')+';\n';
if(process.argv.includes('--check')){
  if(fs.readFileSync(path.join(root,'data.js'),'utf8')!==text)throw Error('data.js is stale; run node school/peterson6/build.cjs');
}else fs.writeFileSync(path.join(root,'data.js'),text);
console.log('Course bundle: '+lessons.length+' topics, '+lessons.reduce((n,l)=>n+l.tasks.length,0)+' tasks, '+Object.entries(exerciseIndexByPart).map(([part,index])=>'part'+part+':'+Object.values(index).filter(x=>!x.missing).length).join(', ')+' source numbers.');
