def rhomb(label, a, b, focus):
    # The two perpendicular half-diagonals a and b determine the rhombus uniquely.
    side=(a*a+b*b)**.5;r=a*b/side
    p={'A':(-a,0),'B':(0,b),'C':(a,0),'D':(0,-b),'T':(0,0),
       'H':(-a*b*b/(side*side),a*a*b/(side*side)),
       'U':(-a,-b-.6),'W':(1-a,-b-.6)}
    edges=outline('ABCD')+[('A','C'),('B','D'),('T','H'),('H','A'),('U','W')]
    return drawing(label,p,edges,'T',r,[('A','T'),('T','B')] if focus=='diagonals' else [('H','T'),('A','B')])


