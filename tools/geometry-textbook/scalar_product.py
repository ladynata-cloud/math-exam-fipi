def subv(p,q):return tuple(v-u for u,v in zip(p,q))


def source_picture(title,points,first,second,plain,*,rotated=False):
    positions={name:(-1.25*y,1.25*x) for name,(x,y) in points.items()} if rotated else points
    full=list(OUTLINE)
    for a,b in [('A','C'),('B','D')]:
        if (a,b) not in full:full.append((a,b))
    heads=[]
    for segment,ordinary in zip((first,second),plain):
        pair=tuple(segment)
        if ordinary and pair not in full:full.append(pair)
        elif not ordinary and pair not in heads:heads.append(pair)
    return frame(title,positions,heads,full)


