def rendering(d,keys):
    return ', '.join(NAMES[k]+'≈'+fmt(d[k],1 if k.isupper() else 2)+('°' if k.isupper() else '') for k in keys)


def author(n,part,source,given,keys,unit,first,formula,trap,probe,repeat,other,newprobe):
    d,method,second=solve(given);new,_,_=solve(other)
    if second is not None:
        known=next(k for k in 'ABC' if k in given)
        first+=f' Второй кандидат с тем же синусом равен {fmt(second,3)}°. С известным углом {fmt(d[known],2)}° сумма была бы больше 180°, поэтому он невозможен.'
    hints=trap+' Не округляй найденные углы до подстановки в формулы сторон.'
    views=[figure('Исходный треугольник ABC',d,False),figure('Высота CH и основание AB для проверки',d,True),figure('Проверь треугольник с новыми данными',new,True)]
    result=formula+' '+rendering(d,keys)+'.'+(' Все стороны здесь в '+unit+'.' if unit else '')
    e=area(n,part,[292],source+' Найди '+', '.join(NAMES[k] for k in keys)+' в данном порядке.',result,hints,[
       ('Выбери исходное соотношение',first,trap),
       ('Восстанови недостающие элементы',result+' Для проверки сумма трёх углов равна 180°, а большая сторона лежит напротив большего угла.','В законе синусов одна и та же сторона должна соответствовать одному и тому же противоположному углу.'),
       ('Испытай новые исходные данные',repeat+' На новом чертеже '+rendering(new,keys)+'.','У нового треугольника снова выстрой пары сторона–противоположный угол.')],views,[
       (probe[0],probe[1],probe[2]),(newprobe[0],newprobe[1],newprobe[2])],refs=[105,106,107])
    e['visualization']['caption']='Исходный чертёж, тот же треугольник с высотой и новый пример. BC=a, AC=b, AB=c. Длины и углы на каждом рисунке рассчитаны заново.'
    e['visualization']['model']['description']=e['visualization']['caption']
    canonical=';'.join(fmt(d[k],1 if k.isupper() else 2) for k in keys)
    return grade(e,[canonical,*exact_forms(d,keys)],hints,'Введи '+', '.join(NAMES[k] for k in keys)+' через точку с запятой. Углы округляй до десятых градуса, длины до сотых '+unit+'.')


