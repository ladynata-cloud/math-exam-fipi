def fmt(value):
    value = str(value)
    return value.replace('**', '^').replace('*', '·').replace('sqrt(', '√(').replace('pi', 'π').replace('-', '−')


def expr(q, expression, answer, solution):
    return {'q': q, 'a': answer, 'solution': solution, 'points': 2,
            'check': {'kind': 'expression', 'expr': expression,
                      'expected': str(S.simplify(S.sympify(expression)))}}


def eq(q, lhs, rhs, roots, solution, answer=None):
    return {'q': q, 'a': answer or 'x = ' + '; '.join(fmt(x) for x in roots) + '.',
            'solution': solution, 'points': 2,
            'check': {'kind': 'equation', 'lhs': lhs, 'rhs': rhs,
                      'roots': [str(x) for x in roots]}}


def ident(q, lhs, rhs, answer, solution):
    return {'q': q, 'a': answer, 'solution': solution, 'points': 2,
            'check': {'kind': 'identity', 'lhs': lhs, 'rhs': rhs}}


def manual(q, answer, solution, reason):
    return {'q': q, 'a': answer, 'solution': solution, 'points': 2,
            'check': {'kind': 'manual', 'reason': reason}}


