def altitude_scene(title,u,a,b,w,deg=0):
    s=(0,0);A=(u,-a);B=(u,b);C=(u+w,b);D=(u+w,-a)
    h=(u-a*b/u,0);k=(h[0]+w,0)
    def foot(point,ray):
        t=sum(x*y for x,y in zip(point,ray,strict=True))/sum(x*x for x in ray)
        return tuple(t*i for i in ray)
    c=foot(C,A);d=foot(D,B)
    p={'A':A,'B':B,'C':C,'D':D,'S':s,'K':k,'H':h,'C₁':c,'D₁':d}
    r=lambda q:rotated(q,s,deg)
    edges=[('A','B'),('B','C'),('C','D'),('D','A'),('S','C₁'),('S','D₁'),('C','C₁'),('D','D₁'),('B','H'),('A','H')]
    return diagram(title,{n:r(q) for n,q in p.items()},edges,[(r(s),r(k))])


