def v(points=(), segments=(), **kw):
    return dict(label=kw.pop('label', 'Условие'), points=list(points),
                segments=[list(x) for x in segments], **kw)

def tri(a='A', b='B', c='C'): return [[a,b],[b,c],[c,a]]
def ar(o,a,b,marks=0): return dict(vertex=o, **{'from':a,'to':b}, marks=marks, radius=7)
def eq(a,b,marks=1): return dict(a=a,b=b,marks=marks)
def rt(a,o,b): return dict(a=a,vertex=o,b=b)
def ck(kind,**kw): return dict(type=kind,**kw)
def equal(*pairs): return ck('equalLength',segments=[list(p) for p in pairs])
def col(*points): return ck('collinear',points=list(points))
def par(a,b,c,d): return ck('parallel',segments=[[a,b],[c,d]])
def perp(a,b,c,d): return ck('perpendicular',segments=[[a,b],[c,d]])
def angle(a,o,b,d): return ck('angle',points=[a,o,b],degrees=d)
def s(prompt,explanation,reason,refs):
    return dict(prompt=prompt,explanation=explanation,justification=reason,theoryPoints=list(refs))

def piece(title,rows,points,initial,views,checks=(),labels=None,offsets=None,cases=(),label_only=()):
    assert len(rows)==len(views),(title,len(rows),len(views))
    return dict(title=title,rows=rows,points=points,initial=initial,views=views,
                checks=list(checks),labels=labels or {},offsets=offsets or {},
                cases=list(cases),label_only=list(label_only))

def combine(*pieces):
    """Different proof diagrams stay on separate views, never piled together."""
    pts,labels,offsets,checks,scenes,cases,label_only,rows={},{},{},[],[],[],[],[]
    initial=None
    for n,p in enumerate(pieces):
        # Keep helper ids prefixed with underscore: the renderer suppresses
        # their labels, so no invalid empty label strings are necessary.
        names={k:(f'_p{n}{k}' if k.startswith('_') else f'p{n}_{k}') for k in p['points']}
        def rename(x):
            if isinstance(x,str): return names.get(x,x)
            if isinstance(x,list): return [rename(z) for z in x]
            if isinstance(x,tuple): return [rename(z) for z in x]
            if isinstance(x,dict): return {k:rename(z) for k,z in x.items()}
            return x
        for k,xy in p['points'].items():
            pts[names[k]]=[round(float(xy[0]),9),round(float(xy[1]),9),0]
            if not k.startswith('_'):
                labels[names[k]]=p['labels'].get(k,k.replace('1','₁').replace('2','₂'))
            offsets[names[k]]=p['offsets'].get(k,[0,5] if xy[1]>42 else [-4,-5] if xy[0]<50 else [4,-5])
        # Hidden helper coordinates receive no accidental labels: only the
        # authored view.points are rendered and every visible point is named.
        label_only.extend(names[k] for k in p['label_only'])
        checks.extend(rename(p['checks']))
        neutral=rename(p['initial'])
        if initial is None: initial=neutral
        if n:
            # A named case may need the construction already introduced at
            # its unlock step, while the card's neutral scene stays earlier.
            case_initial=rename(p.get('caseInitial',p['initial']))
            cases.append(dict(case_initial,label=p['title'],availableFromStep=len(rows)+1))
        for view in p['views']: scenes.append(rename(view))
        for case in p['cases']:
            data=rename(case)
            data['availableFromStep']=data.get('availableFromStep',0)+len(rows)
            cases.append(data)
        rows.extend(deepcopy(p['rows']))
    vv={'neutral':initial}
    for i,scene in enumerate(scenes,1): vv[f'step-{i}']=dict(scene,label=f'Шаг {i}')
    for i,scene in enumerate(cases,1): vv[f'case-{i}']=scene
    model=dict(points=pts,edges=[],planar=True,bounds=[0,0,100,70],views=vv,
               checks=checks,labels=labels,labelOffsets=offsets,labelOnly=label_only,
               description='Чертёж относится к текущему рассуждению. Дополнительные линии появляются по шагам; другое утверждение показано отдельно.')
    return rows,model

def add(collection,number,title,pages,statement,answer,*pieces):
    rows,model=combine(*pieces)
    did=dict(steps=[{k:z for k,z in row.items() if k!='explanation'} for row in rows])
    record=dict(number=number,title=title,printedPages=pages,pdfPages=[p+1 for p in pages],
                statement=statement,steps=[r['explanation'] for r in rows],answer=answer,
                didactics=did,sourceVerified=True,mathVerified=True,
                notes=['Original explanation; author source check is not independent publication approval.'])
    (THEORY if collection=='theory' else QUESTIONS).append(record)
    MODELS.append(dict(chapter=4,collection=collection,number=number,part='single',
                       model=model,didactics=deepcopy(did)))

