'use strict';

// Keep the cabinet's small static projection in sync with the canonical course map.
// The account server only serves its own reviewed assets; it loads no remote script.
const fs = require('node:fs');
const path = require('node:path');
const { exams } = require('../ege-profil/start/calm-data.js');
const target = path.join(__dirname, '../learning/profile-exam-catalog.js');
const projection = exams.map(({ number, title, entry }) => ({ number, title, entry }));
const source = '// Generated by tools/build-profile-exam-catalog.cjs from ege-profil/start/calm-data.js.\n' +
  '// Do not edit this projection by hand.\n' +
  '(function(root){\n  \'use strict\';\n  const exams=' + JSON.stringify(projection, null, 2) + ';\n' +
  '  const api={exams};\n  root.ProfileExamCatalog=api;\n' +
  '  if(typeof module!==\'undefined\'&&module.exports)module.exports=api;\n' +
  '})(typeof globalThis!==\'undefined\'?globalThis:window);\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) {
    console.error('Profile exam catalogue is stale. Run node tools/build-profile-exam-catalog.cjs');
    process.exitCode = 1;
  } else console.log('PROFILE_EXAM_CATALOG_CURRENT');
} else {
  fs.writeFileSync(target, source);
  console.log('PROFILE_EXAM_CATALOG_WRITTEN');
}
