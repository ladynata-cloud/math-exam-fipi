def circle(title, x, y, r, transform):
    points={'T':(x,y),'A':(x+r,y),'N':(x,y+r),'L':(x-r,y),'S':(x,y-r)}
    return diagram(title,points,[('T',p) for p in 'ANLS'],transform)


