def isosceles(title,a,h,t,whole):
    points={'A':(-a,0),'B':(0,h),'C':(a,0),'D':(a+t,0),'B′':(t,h)}
    edges=[('A','B'),('B','C'),('A','C'),('C','D'),('B','B′'),('B′','D')]
    return schematic(title,points,edges+[('A','D')] if whole else edges)


