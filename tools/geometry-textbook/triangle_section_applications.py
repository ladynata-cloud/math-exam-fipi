def forces(title,r,alpha):
    # Draw the physical vectors in tens of the source force units per grid cell.
    half=radians(alpha/2);x=r*cos(half)/10;y=r*sin(half)/10
    pts={'P':(0,0),'U':(x,y),'V':(x,-y),'R':(2*x,0),'H':(x,0)}
    paths=[(pts['P'],pts[k]) for k in ('U','V','R')]
    arrows=[]
    for start,end in paths:
        dx,dy=end[0]-start[0],end[1]-start[1];norm=sqrt(dx*dx+dy*dy);ux,uy=dx/norm,dy/norm
        for sign in (-1,1):arrows.append(((end[0]-.35*ux-sign*.23*uy,end[1]-.35*uy+sign*.23*ux),end))
    return graph(title,pts,edges=[('U','R'),('V','R'),('U','H'),('V','H')],lines=paths+arrows)


