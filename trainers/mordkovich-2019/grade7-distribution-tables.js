  function figure(v){
    const text=(x,y,label,size=12)=>'<text x="'+x+'" y="'+y+'" font-size="'+size+'">'+label+'</text>';
    let shapes='';
    if(v.kind==='pie'){
      let angle=-Math.PI/2;
      const palette=['#bfdcce','#e9cc95','#c7d9e9','#ddd1e7','#f4c9bd','#c3dbac'];
      v.shares.forEach((share,i)=>{
        const end=angle+share*Math.PI/50,point=(theta,r)=>[85+r*Math.cos(theta),64+r*Math.sin(theta)];
        const from=point(angle,50),to=point(end,50),mid=point((angle+end)/2,35);
        shapes+='<path d="M85 64 L'+from.join(' ')+' A50 50 0 0 1 '+to.join(' ')+' Z" fill="'+palette[i]+'" stroke="#3c5254"/>'+text(mid[0],mid[1]+3,i+1,10);
        const y=18+16*i;
        shapes+='<rect x="158" y="'+(y-10)+'" width="11" height="11" fill="'+palette[i]+'" stroke="#617170"/>'+text(213,y,'№'+(i+1)+' · '+(i===4?'?':share)+' %',11);
        angle=end;
      });
    }else if(v.kind==='tallies'){
      let x=12;
      const mark=(x1,y1,x2,y2)=>'<path d="M'+x1+' '+y1+'L'+x2+' '+y2+'" stroke-width="2.2" stroke="#386156" stroke-linecap="round"/>';
      for(let g=0;g<v.groups;g++){
        for(let j=0;j<4;j++)shapes+=mark(x+7*j,69,x+7*j+5,40);
        shapes+=mark(x-3,54,x+29,49);x+=44;
      }
      for(let j=0;j<v.rest;j++)shapes+=mark(x+7*j,69,x+7*j+5,40);
      shapes+=text(141,101,'Поперечный штрих завершает одну пятёрку');
    }else if(v.kind==='groups'){
      const width=255/v.counts.length,max=Math.max(...v.counts);
      v.counts.forEach((count,i)=>{
        const left=14+i*width,height=56*count/max;
        shapes+='<rect x="'+(left+width*.15)+'" y="'+(81-height)+'" width="'+width*.7+'" height="'+height+'" fill="#c1dfd3" stroke="#426b62"/>'+text(left+width/2,75-height,count)+text(left+width/2,99,v.labels[i],12);
      });
    }else if(v.kind==='scale'){
      shapes+=text(141,19,'Состояние после каждого нажатия');
      for(let i=0;i<5;i++){
        const x=29+i*55;
        shapes+='<rect x="'+(x-25)+'" y="36" width="50" height="30" rx="4" fill="#d7eae1"/>'+text(x,54,Number((v.start/10**i).toFixed(i)).toString().replace('.',','),10)+text(x,86,'шаг '+i,10);
      }
    }else{
      const max=v.kind==='pairs'?v.total-1:Math.floor((v.total-1)/v.factor),steps=[1,2,max];
      const nIsFree=v.kind==='pairs'||v.coord==='n';
      shapes+=text(141,18,'Первая, вторая и последняя допустимые пары');
      steps.forEach((i,j)=>{
        const other=v.total-i*(v.factor||1),n=nIsFree?i:other,k=nIsFree?other:i,x=48+j*92;
        shapes+='<rect x="'+(x-37)+'" y="31" width="74" height="48" rx="5" fill="#daeae4"/>'+text(x,50,'n = '+n)+text(x,68,'k = '+k);
      });
    }
    const labels={pie:'Круговая диаграмма продаж по шести играм',groups:'Столбцы по значениям таблицы',tallies:'Подсчёт штрихов пятёрками',pairs:'Пары положительных слагаемых',weighted:'Решения линейного уравнения в натуральных числах',scale:'Десятикратное уменьшение числа'};
    return '<svg viewBox="0 0 282 124" role="img" aria-label="'+labels[v.kind]+'"><g font-family="sans-serif" text-anchor="middle" fill="#24494b">'+shapes+'</g></svg>';
  }
