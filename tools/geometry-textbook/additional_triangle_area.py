def polygon(label,oa,oc,ob,od,phi):
    th=radians(phi)
    pts={'K':(0,0),'A':(oa,0),'C':(-oc,0),'B':(ob*cos(th),ob*sin(th)),'D':(-od*cos(th),-od*sin(th))}
    return graph(label,pts,edges=[('A','B'),('B','C'),('C','D'),('D','A'),('A','C'),('B','D')])


