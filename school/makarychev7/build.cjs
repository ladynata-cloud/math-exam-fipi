'use strict';
const fs=require('node:fs'),path=require('node:path');
const read=f=>JSON.parse(fs.readFileSync(path.join(__dirname,f),'utf8'));
const sourceMap=read('source-map.json');
const lessons=['ch1.json','ch2-3.json','ch4-5.json','ch6.json'].flatMap(read).sort((a,b)=>a.order-b.order);
for(const l of lessons){
 const ref=sourceMap.sections.find(s=>s.kind==='topic'&&s.id===l.order);
 if(!ref)throw Error('Unknown topic '+l.order);
 l.advanced=ref.advanced;l.page=ref.printedPage;l.sourceRange=ref.exerciseRange.join('–');
 l.chapter=sourceMap.chapters.find(c=>c.id===ref.chapter).title;
}
if(lessons.length!==46||new Set(lessons.map(l=>l.order)).size!==46)throw Error('Expected exactly 46 topics');
const data={edition:'makarychev7-2024',chapters:sourceMap.chapters,sourceMap,lessons};
fs.writeFileSync(path.join(__dirname,'data.js'),'/* Generated by build.cjs; edit chapter JSON sources. */\nwindow.MakarychevCourse='+JSON.stringify(data)+';\n');
console.log(JSON.stringify({topics:lessons.length,theory:lessons.reduce((s,l)=>s+l.theory.length,0),tasks:lessons.reduce((s,l)=>s+l.tasks.length,0),steps:lessons.flatMap(l=>l.tasks).reduce((s,t)=>s+t.steps.length,0),textbookTasks:lessons.flatMap(l=>l.tasks).filter(t=>t.source.type==='textbook').length}));
