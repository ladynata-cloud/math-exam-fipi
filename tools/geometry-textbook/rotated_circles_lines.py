def line_scene(title,offset,length,alpha):
    t=(0,0);h=(0,offset);a=(length,offset)
    rotated_point=lambda p:rotated(p,t,alpha)
    pts={'T':t,'H':h,'H′':rotated_point(h),'A':a,'A′':rotated_point(a)}
    left=(-length*.8,offset);right=(length*1.4,offset)
    lines=[(left,right),(rotated_point(left),rotated_point(right))]
    edges=[('H','A'),('H′','A′')]
    if offset:edges.extend([('T','H'),('T','H′')])
    return diagram(title,pts,edges,[*lines,*turning_arrow(t,h if offset else a,alpha)])


def add_right_angles(c):
    m=c['visualization']['model']
    for v in m['views'].values():
        ids={s:k for k in v['points'] for s in m['labels'][k].split('=')}
        already={a['vertex'] for a in v['rightAngles']}
        for suffix in ('','′'):
            k=ids['H'+suffix]
            if k not in already:v['rightAngles'].append(dict(vertex=k,a=ids['T'],b=ids['A'+suffix],size=1.65))
    return c


