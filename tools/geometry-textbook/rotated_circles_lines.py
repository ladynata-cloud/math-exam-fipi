def diagram(title,points,edges,lines=()):
    coords=[*points.values(),*[p for line in lines for p in line]]
    x=min(x for x,y in coords);y=min(y for x,y in coords)-1.4
    return graph(title,{**points,'U':(x,y),'W':(x+1,y)},edges=[*edges,('U','W')],lines=lines)


def circle_scene(title,d,r):
    t=(0,0); c=(d,0); a=(d+r,0)
    c1=rotated(c,t,60);a1=rotated(a,t,60)
    points={'T':t,'C':c,'C′':c1,'A':a,'A′':a1}
    for i,(x,y) in enumerate((c,c1)):
        for j,(dx,dy) in enumerate(((r,0),(-r,0),(0,r),(0,-r))):
            points[f'bound{i}{j}']=(x+dx,y+dy)
    edges=[('C','A'),('C′','A′')]
    if d:edges.extend([('T','C'),('T','C′')])
    return diagram(title,points,edges,turning_arrow(t,c if d else a,60))


