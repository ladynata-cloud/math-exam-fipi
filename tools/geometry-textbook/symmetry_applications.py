def outside_squares():
    a=(-2,1);b=(-1,-3);c=(0,0)
    d=(a[1],-a[0]);e=(-b[1],b[0])
    h=(a[0]+d[0],a[1]+d[1]);f=(b[0]+e[0],b[1]+e[1])
    points={'C':c,'A':a,'B':b,'D':d,'E':e,'H':h,'F':f}
    edges=[('A','B'),('A','C'),('C','D'),('D','H'),('H','A'),
           ('B','C'),('C','E'),('E','F'),('F','B')]
    return diagram('Два квадрата вне треугольника',points,edges,[(a,e),(d,b)])


