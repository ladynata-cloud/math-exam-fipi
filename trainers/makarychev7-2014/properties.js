(function () {
  'use strict';
  const {add, lessons, example, task, f} = window.MathExamTopicPractice;
  function question(prompt, answer, calculation, error, mistakes) {
    return {...task(prompt, answer, calculation, error), mistakes:mistakes.filter(([value]) => value !== answer)};
  }

  add(95, 4, 18, 'Сложение со знаками', 'Собери удобные пары и вычисли значение всей суммы.',
    'У каждого слагаемого свой знак. Когда меняешь порядок слагаемых, переноси знак вместе с числом.',
    'alg-order', seed => {
      const whole = 7 + seed;
      const positive = 2 + seed / 10;
      const otherPositive = (whole * 10 - (20 + seed)) / 10;
      const negativeTotal = 3 + seed % 4;
      const negative = -(10 + seed) / 10;
      const otherNegative = -(negativeTotal * 10 - (10 + seed)) / 10;
      const values = [positive, negative, otherPositive, otherNegative];
      const data = example('Четыре карточки со знаками', ['Карточка', 'Значение'],
        values.map((v, i) => [i + 1, v]), [
          question('Сколько дадут вместе две положительные карточки?', whole,
            'Объедини карточки 1 и 3. Обе обозначают прибавление.', 'Сложи только положительные числа.',
            [[whole - negativeTotal, 'Ты посчитал всю сумму. В этом вопросе нужны две карточки со знаком плюс.']]),
          question('Какую сумму дают две отрицательные карточки? Сохрани знак.', -negativeTotal,
            'Карточки 2 и 4 обе обозначают уменьшение. Сложи их модули и поставь знак минус.',
            'Два уменьшения складываются.', [[negativeTotal, 'Ты верно посчитал, насколько уменьшилось число. Запиши это изменение со знаком минус.']]),
          question('Найди сумму всех четырёх карточек.', whole - negativeTotal,
            'Положительная пара даёт ' + whole + ', отрицательная пара даёт −' + negativeTotal + '. Теперь сложи результаты.',
            'Сложи результаты двух пар с их знаками.', [[whole + negativeTotal, 'Отрицательные карточки превратились в прибавки. Сохрани их знаки.'], [whole, 'Ты сосчитал положительную пару. Учти ещё обе отрицательные карточки.']])
        ], 'signed-pairs');
      data.values = values;
      return data;
    });
  Object.assign(lessons.get('95-4'), {
    printedPrompt:'Открой №71 на с. 18. Отметь знак каждого слагаемого. В каждом из четырёх подпунктов найди пару, с которой удобнее начать, и выполни вычисление в тетради.',
    printedReference:'Пункт 4 · №71 (а–г)',
    printedGuide:'а) Соедини 3,17 с 0,83, а 10,2 с 9,8. Получишь 4 + 20 = 24. б) 4,11 и 0,89 вместе дают 5, а 15,5 и 4,4 дают 19,9. Всего 24,9. в) Два положительных слагаемых дают 22. Два отрицательных дают −8,6, поэтому результат 13,4. г) Объедини −4,27 и −5,73 в −10, а 3,8 и −3,3 в 0,5. Итого −9,5.'
  });

  add(95, 5, 23, 'Когда равенство верно для всех чисел', 'Сравни разности в двух направлениях, а затем их квадраты.',
    'Один контрпример опровергает тождество. Для доказательства тождества покажи, почему равенство сохраняется при любых допустимых значениях букв.',
    'alg-variable', seed => {
      const distance = 2 + seed % 5, left = seed - 6;
      const x = seed % 2 ? left : left + distance;
      const y = seed % 2 ? left + distance : left;
      const step = x - y;
      const data = example('Две отметки на прямой', ['Точка', 'Координата'], [['x', x], ['y', y]], [
        question('Чему равно x − y? Пройди от y к x.', step,
          'Начни в точке y и закончи в точке x. Влево — отрицательное направление, вправо — положительное.',
          'Вычти координату начала из координаты конца.', [[-step, 'Так получается при движении от x к y. Нужен противоположный переход.'], [0, 'У отметок разные координаты, поэтому перемещение не нулевое.']]),
        question('Найди значение квадрата (y − x)².', step * step,
          'Разность y − x равна ' + f(-step) + '. Умножь её саму на себя.',
          'Квадрат — это произведение двух одинаковых чисел.', [[-step * step, 'При возведении в квадрат произведение двух одинаковых отрицательных чисел положительно.'], [Math.abs(step), 'Ты указал расстояние между отметками. В этом вопросе нужно его возвести в квадрат.']]),
        question('На сколько со знаком отличается первая разность от второй? Вычисли (x − y) − (y − x).', 2 * step,
          'Вторая разность противоположна первой. Вычитая её, ты прибавляешь ещё одно x − y.',
          'Рассматривай вторые скобки как одно вычитаемое.', [[0, 'Нуль вышел бы для двух одинаковых разностей. Начало и конец стрелки поменялись местами.'], [step, 'Это только первая разность. Теперь вычти вторую.']])
      ], 'opposite-steps');
      data.values = [x, y];
      return data;
    });
  Object.assign(lessons.get('95-5'), {
    printedPrompt:'В №86 на с. 23 сравни четыре пары выражений. Для верной при любых числах пары запиши преобразование. Для остальных подбери значения букв, при которых результаты различаются.',
    printedReference:'Пункт 5 · №86 (а–г)',
    printedGuide:'а) В произведении собери числа 2 и 7, затем буквы. Получится 14ab при любых a и b. б) Слагаемые −2a и 2a взаимно уничтожаются. в) Проверь x = 2 и y = 5. Первая разность равна −3, вторая равна 3. Этого примера достаточно, чтобы опровергнуть тождество. г) При замене порядка разность меняет знак. Её квадрат сохраняется, потому что (−u)·(−u) = u² для любого u.'
  });
})();
