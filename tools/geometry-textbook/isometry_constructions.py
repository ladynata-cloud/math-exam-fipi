def mirror(title, points, edges, construction, extend_line=False):
    geom={**points, **{n+'′':(-x,y) for n,(x,y) in points.items()}}
    bottom=min(y for _,y in points.values())-1
    top=max(y for _,y in points.values())+1
    geom.update(K=(0,bottom), L=(0,top))
    segments=[*edges,*[(a+'′',b+'′') for a,b in edges],('K','L')]
    for n, foot in construction.items():
        x,y=points[n]
        if x==0:continue
        geom[foot]=(0,y)
        segments.extend([(n,foot),(foot,n+'′'),(foot,'L')])
    if extend_line:
        ax,ay=points['A'];bx,by=points['B']
        dx,dy=bx-ax,by-ay
        start,end=(ax-.55*dx,ay-.55*dy),(bx+.55*dx,by+.55*dy)
        reflected=lambda p:(-p[0],p[1])
        x=min(v[0] for v in geom.values());y=min(v[1] for v in geom.values())-1.25
        return graph(title,{**geom,'U':(x,y),'W':(x+1,y)},edges=segments,
                     lines=[(start,end),(reflected(start),reflected(end))])
    return schematic(title,geom,segments)


def mark_feet(c, construction):
    model=c['visualization']['model']
    for name,view in model['views'].items():
        n=int(name[-1])-1 if name[-1].isdigit() else 0
        ids={label:k for k in view['points'] for label in model['labels'][k].split('=')}
        marked={mark['vertex'] for mark in view['rightAngles']}
        for point,foot in construction[n].items():
            if foot not in ids or ids[foot] in marked:continue
            marked.add(ids[foot])
            view['rightAngles'].append({'vertex':ids[foot],'a':ids[point],'b':ids['L'],'size':1.2})
    return c


