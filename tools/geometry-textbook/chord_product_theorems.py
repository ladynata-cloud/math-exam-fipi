def locus():
    pts={'A':(0,0),'C':(4,0),'H':(2,0),'P':(4,4),'N':(2,2)}
    return ring_frame('Геометрическое место середин хорд AP',pts,[('A','C'),('A','P'),('C','P'),('H','N')],[('C','A'),('H','A')])


def angle_rings(title,a,b):
    low=a+b-sqrt(2*a*b);hi=a+b+sqrt(2*a*b)
    pts={'T':(0,0),'A':(a,b),'C':(low,low),'D':(hi,hi),'K':(low,0),'L':(0,low),'H':(hi,0),'J':(0,hi)}
    lines=[((0,0),(2*hi+1,0)),((0,0),(0,2*hi+1))]
    return ring_frame(title,pts,[('T','A'),('C','K'),('C','L'),('D','H'),('D','J')],[('C','A'),('D','A')],lines)


