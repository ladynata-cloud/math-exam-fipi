def major_arcs(label,c,focus):
    p={'A':(-c/2,0),'B':(c/2,0),'J':(0,c/2),'K':(0,-c*sqrt(3)/2),
       'U':(-c,-2*c-.4),'W':(1-c,-2*c-.4)}
    edges=[('A','B'),('J','A'),('J','B'),('K','A'),('K','B'),('U','W')]
    upper=arc(p,edges,'A','B',p['J'],c/sqrt(2),225,-270,'upper')
    lower=arc(p,edges,'A','B',p['K'],c,120,300,'lower')
    g=graph(label,p,edges=edges)
    curves=[upper] if focus=='upper' else [lower] if focus=='lower' else [upper,lower]
    return (*g[:3],[pair for names in curves for pair in zip(names,names[1:])])


def trapezoid(label,scale,mode):
    pts={'A':(-7,0),'B':(7,0),'C':(2,12),'D':(-2,12),'H':(-2,0),'T':(0,33/8)}
    pts={k:(scale*x,scale*y) for k,(x,y) in pts.items()}
    pts.update(U=(-8*scale,-4.5*scale),W=(1-8*scale,-4.5*scale))
    edges=outline('ABCD')+[('D','H'),('H','A'),('H','B'),('U','W')]
    high=[('A','H'),('H','D')] if mode=='height' else [('A','D'),('D','B'),('B','A')]
    edges.extend([('D','B'),('A','T'),('T','D')])
    return graph(label,pts,edges=edges,circle=('T',65*scale/8),lines=[(pts[a],pts[b]) for a,b in high])


def similar(label,a,b,focus):
    h=hypot(a,b);x=a*a/h;y=a*b/h
    p={'A':(0,0),'B':(h,0),'C':(x,y),'H':(x,0),'U':(0,-.6),'W':(1,-.6)}
    left=(x+y-a)/2;right=(h-x+y-b)/2
    p.update(I=(x-left,left),J=(x+right,right),F=(x-left,0),G=(x+right,0))
    edges=outline('ABC')+[('C','H'),('A','H'),('H','B'),('I','F'),('J','G'),('U','W')]
    high=[('A','C'),('A','H'),('H','C')] if focus=='left' else [('C','B'),('B','H'),('H','C')] if focus=='right' else [('I','F'),('J','G')]
    return graph(label,p,edges=edges,circle=('I',left),lines=[(p[a],p[b]) for a,b in high])


