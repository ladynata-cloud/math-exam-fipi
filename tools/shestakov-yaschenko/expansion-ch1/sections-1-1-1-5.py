def coord(q):
    return f'({fmt(q[0])}; {fmt(q[1])})'


def v(label, segments=(), points=(), polygon=()):
    result = {'label': label, 'segments': [list(s) for s in segments]}
    if points:
        result['points'] = list(points)
    if polygon:
        result['polygon'] = list(polygon)
    return result


def grid(points, edges, names, width, height, views):
    """Unlabelled exact unit grid; orange source edges remain legible."""
    p = dict(points)
    e = []
    for x in range(width + 1):
        p['_x' + str(x) + 'a'] = (x, 0)
        p['_x' + str(x) + 'b'] = (x, height)
        e.append(['_x' + str(x) + 'a', '_x' + str(x) + 'b'])
    for y in range(height + 1):
        p['_y' + str(y) + 'a'] = (0, y)
        p['_y' + str(y) + 'b'] = (width, y)
        e.append(['_y' + str(y) + 'a', '_y' + str(y) + 'b'])
    allviews = {'neutral': v('Данные исходного рисунка на сетке 1 × 1', edges)}
    for key, view in views.items():
        allviews[key] = {**view, 'segments': [list(s) for s in edges] + view.get('segments', [])}
    return model(p, e + [list(s) for s in edges], names, allviews)


def axes(points, edges, names, views, bounds=None):
    """Coordinate axes are givens; only named source/target points are neutral."""
    p = dict(points)
    if bounds is None:
        xs = [q[0] for q in p.values()] + [0]
        ys = [q[1] for q in p.values()] + [0]
        bounds = (min(xs) - 1, max(xs) + 1, min(ys) - 1, max(ys) + 1)
    xmin, xmax, ymin, ymax = bounds
    p.update({'_x0': (xmin, 0), '_x1': (xmax, 0),
              '_y0': (0, ymin), '_y1': (0, ymax)})
    m = model(p, [['_x0', '_x1'], ['_y0', '_y1']] + [list(s) for s in edges],
              list(names) + ['_x1', '_y1'], views)
    m['labels'] = {'_x1': 'x', '_y1': 'y'}
    return m


def raypoint(degrees, radius=6):
    t = math.radians(degrees)
    return (radius * math.cos(t), radius * math.sin(t))


