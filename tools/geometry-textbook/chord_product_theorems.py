def diameter_scene(title,a,b):
    e=(0,0);r=sqrt(a*b);o=((b-a)/2,0)
    pts={'C':e,'A':(-a,0),'A′':(b,0),'B':(0,r),'B′':(0,-r),'S':o}
    return ring_frame(title,pts,[('A','A′'),('B','B′')],[('S','A')])


