def diagram(name, points, edges, motion):
    images = {p + '′': motion(x, y) for p, (x, y) in points.items()}
    new_edges = [(a + '′', b + '′') for a, b in edges]
    return schematic(name, {**points, **images}, [*edges, *new_edges])


def reflect(x, y):
    return -x - 2, y


def turn(x, y):
    return -y - 3, x


