def angled_scene(title,a,b,t,angle):
    a1,b1=rotated(a,t,angle),rotated(b,t,angle)
    pivot=a if a!=t else b
    pts={'T':t,'A':a,'B':b,'A′':a1,'B′':b1}
    edges=[('A','B'),('A′','B′'),('A','A′'),('T','A'),('T','A′')]
    if a==t:edges.extend([('T','B'),('T','B′')])
    return diagram(title,pts,edges,turning_arrow(t,pivot,angle))


