def octagon(title,selected,diameters):
    names=['A'+str(i) for i in range(1,9)];p=dict(zip(names,ring(8,4,0)));p['T']=(0,0)
    rectangle=['A'+str(i) for i in selected];edges=outline(names)+outline(rectangle)
    if diameters:edges += [(rectangle[0],rectangle[2]),(rectangle[1],rectangle[3])]
    return graph(title,p,edges=edges,circle=('T',4),lines=[(p[a],p[b]) for a,b in outline(rectangle)])


