def sc(points=(), segments=(), **kw):
    return dict(label=kw.pop('label', 'Условие'), points=list(points),
                segments=[list(pair) for pair in segments], **kw)


def arc(o, a, b, marks=0, radius=7):
    return dict(vertex=o, **{'from': a, 'to': b}, marks=marks, radius=radius)


def eq(a, b, marks=1):
    return dict(a=a, b=b, marks=marks)


def right(a, o, b):
    return dict(a=a, vertex=o, b=b)


def ck(kind, **kw):
    return dict(type=kind, **kw)


def equal(*pairs):
    return ck('equalLength', segments=[list(pair) for pair in pairs])


def par(a, b, c, d):
    return ck('parallel', segments=[[a, b], [c, d]])


def perp(a, b, c, d):
    return ck('perpendicular', segments=[[a, b], [c, d]])


def col(*names):
    return ck('collinear', points=list(names))


def ang(a, o, b, degrees):
    return ck('angle', points=[a, o, b], degrees=degrees)


def polar(p, degrees, length):
    theta = math.radians(degrees)
    return [p[0] + length * math.cos(theta), p[1] + length * math.sin(theta)]


def midpoint(a, b):
    return [(a[i] + b[i]) / 2 for i in (0, 1)]


def tri(a='A', b='B', c='C'):
    return [[a, b], [b, c], [c, a]]


def fit(points, width=74, height=48):
    xmin = min(p[0] for p in points.values()); xmax = max(p[0] for p in points.values())
    ymin = min(p[1] for p in points.values()); ymax = max(p[1] for p in points.values())
    scale = min(width / (xmax - xmin or 1), height / (ymax - ymin or 1))
    return {name: [50 + (p[0] - (xmin + xmax) / 2) * scale,
                   35 + (p[1] - (ymin + ymax) / 2) * scale]
            for name, p in points.items()}


def intersection(a, b, c, d):
    u = [b[i] - a[i] for i in (0, 1)]; v = [d[i] - c[i] for i in (0, 1)]
    den = u[0] * v[1] - u[1] * v[0]
    assert abs(den) > 1e-9
    t = ((c[0] - a[0]) * v[1] - (c[1] - a[1]) * v[0]) / den
    return [a[i] + t * u[i] for i in (0, 1)]


def add(number, part, condition, answer, steps, points, neutral, views=None,
        checks=(), cases=(), labels=None, offsets=None, label_only=(),
        bounds=None, givens=(), notes=()):
    page = 66 if number <= 215 else 67 if number <= 217 else 68
    exercise = EX.setdefault(number, dict(number=number, printedPages=[page],
        pdfPages=[page + 1], parts=[], notes=[]))
    exercise['notes'].extend(notes)
    exercise['parts'].append(dict(part=part, conditionSummary=condition, answer=answer,
        steps=[step[1] for step in steps], sourceVerified=True, mathVerified=True,
        visual=dict(initial='Собственный чертёж условия; вычисления находятся рядом.',
                    stepChanges=['Новые построения и выводы появляются на соответствующем шаге.'],
                    cases=[case['label'] for case in cases])))
    views = views or [neutral] * len(steps)
    assert len(views) == len(steps), (number, part, len(views), len(steps))
    all_views = {'neutral': deepcopy(neutral)}
    all_views.update({f'step-{i}': {**deepcopy(view), 'label': f'Шаг {i}'}
                      for i, view in enumerate(views, 1)})
    all_views.update({f'case-{i}': deepcopy(view) for i, view in enumerate(cases, 1)})
    model = dict(points={name: [round(p[0], 9), round(p[1], 9), 0]
                         for name, p in points.items()},
        edges=[], planar=True, bounds=bounds or [0, 0, 100, 70],
        views=all_views, checks=list(checks),
        description=f'Задача {number}' + (f' ({part})' if part != 'single' else '')
                    + ': отдельная модель. Дополнительные элементы раскрываются по шагам.')
    if labels:
        model['labels'] = labels
    if offsets:
        model['labelOffsets'] = offsets
    if label_only:
        model['labelOnly'] = list(label_only)
    item = dict(chapter=3, collection='main', number=number, part=part, model=model,
        didactics=dict(steps=[dict(prompt=s[0], justification=s[2], theoryPoints=s[3])
                             for s in steps]))
    if givens:
        item['statementGivens'] = list(givens)
    MODELS.append(item)


def transversal(alpha):
    dx = 13 / math.tan(math.radians(alpha))
    p = {'P': [50 + dx, 48], 'Q': [50 - dx, 22],
         '_Pl': [6, 48], '_Pr': [94, 48], '_Ql': [6, 22], '_Qr': [94, 22],
         'a': [91, 49], 'b': [91, 23]}
    p['_Pu'] = polar(p['P'], alpha, 13)
    p['_Qd'] = polar(p['Q'], alpha + 180, 13)
    p['c'] = polar(p['P'], alpha, 15)
    v = sc(['P', 'Q', 'a', 'b', 'c'], lines=[['_Pl', '_Pr'], ['_Ql', '_Qr'], ['P', 'Q']])
    checks = [par('_Pl', '_Pr', '_Ql', '_Qr'), col('_Qd', 'Q', 'P', '_Pu'),
              ang('_Pr', 'P', '_Pu', alpha), ang('_Pl', 'P', '_Pu', 180 - alpha)]
    return p, v, checks


