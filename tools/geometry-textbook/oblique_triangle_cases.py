def exterior_height(label,h):
    # A is vertically above D; B lies strictly between D and C.
    u=h*(2-sqrt(3));v=h*sqrt(3)
    pts={'D':(0,0),'A':(0,h),'B':(u,0),'C':(v,0)}
    return graph(label,pts,edges=[('A','B'),('B','C'),('C','A'),('A','D'),('D','B')])


