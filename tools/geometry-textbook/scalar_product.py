def equilateral():
    choices=[
        ('а','AB','AC',60,'a²/2',['a²/2','a^2/2','0,5a²','a²/2'],'У двух сторон, выходящих из A, угол 60°, а обе длины равны a.',8,18,'AB','AC'),
        ('б','AC','CB',120,'−a²/2',['-a²/2','−a²/2','-a^2/2','-0,5a²'],'У CA и CB угол 60°, но AC противоположен CA, поэтому угол выбранных векторов 120°.',-8,-18,'AC','CB'),
        ('в','AC','BD',90,'0',['0','0,0','0.0'],'BD — высота к AC, поэтому оба ненулевых вектора взаимно перпендикулярны.',0,-27,'AB','BD'),
        ('г','AC','AC',0,'a²',['a²','a^2','a*a'],'Это скалярный квадрат стороны. У вектора с самим собой угол 0°.',16,36,'AC','AC')]
    rows=[]
    def model(label,a,u,v):
        pts={'A':(0,0),'C':(a,0),'B':(a/2,a*sqrt(3)/2),'D':(a/2,0)}
        arrows=[tuple(u)]
        if v!=u:arrows.append(tuple(v))
        return frame(label,pts,arrows,[('A','B'),('B','C'),('C','A'),('B','D')])
    original={'A':(0,0),'C':(4,0),'B':(2,2*sqrt(3)),'D':(2,0)}
    for part,u,v,phi,result,forms,why,x,y,nu,nv in choices:
        raw1=subv(original[u[0]],original[u[1]]);raw2=subv(original[v[0]],original[v[1]])
        views=[model('Равносторонний ABC и высота BD',4,u,v),common_view('Те же два вектора у общего начала',raw1,raw2),model('Треугольник со стороной 6',6,nu,nv)]
        hint='Порядок букв указывает направление. Сохрани его при переносе. Высота BD перпендикулярна AC, а угол между сторонами может стать 120° после разворота одной стрелки.'
        proof=why+f' Для векторов {u} и {v} угол {phi}°, скалярное произведение равно {result}.'
        transfer=(f'При стороне 6 и том же выборе стрелок результат {y}.' if nu==u and nv==v else 'При стороне 6 теперь сравни AB и BD. Длина BD=3√3, угол между AB и BD равен 150°, поэтому произведение 6·3√3·(−√3/2)=−27.')
        c=card(1131,part,[288],f'В равностороннем ABC со стороной a проведена высота BD. Найди скалярное произведение векторов {u[0]}→{u[1]} и {v[0]}→{v[1]}.',proof,hint,
              [('Прочитай обе стрелки',why,'Сопоставь их направления с исходными вершинами треугольника.'),('Вычисли произведение',proof+f' В модели со стороной 4 получается {x}.','Косинус берётся от угла между векторами, а не обязательно от угла внутри треугольника.'),
               ('Замени данные',transfer,'Смена длины влияет на ненулевое скалярное произведение двух векторов.')],views,
              [('Чему равно произведение в числовом рисунке со стороной 4?',str(x),'Подставь a=4 в найденное выражение.'),('Чему равно новое произведение на чертеже со стороной 6?',str(y),'Сверь обозначения выбранных стрелок и их направления.')],[109,110])
        rows.append(grade(c,list(dict.fromkeys(forms)),hint,'Введи точное значение через a или число 0. Для квадрата можно написать a² или a^2.'))
    return rows


def force_frame(title,angle,p=8,q=15):
    theta=radians(angle);u=(p,0);v=(q*cos(theta),q*sin(theta));r=(u[0]+v[0],u[1]+v[1])
    pts={'O':(0,0),'P':u,'Q':v,'R':r}
    return frame(title,pts,[('O','P'),('O','Q'),('O','R')],[('P','R'),('Q','R')])


