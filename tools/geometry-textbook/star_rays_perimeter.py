def ray(title,a,b,theta,turn,r):
    u=polar(theta,r);v=polar(theta+turn,r)
    add=lambda q,w:(q[0]+w[0],q[1]+w[1])
    pts={'A':a,'B':b,'P':add(a,u),'Q':add(b,v)}
    lines=[]
    for q,t in [(a,theta),(b,theta+turn)]:
        tip=add(q,polar(t,r+1.1))
        lines.append((q,tip))
        for k in [-1,1]:lines.append((tip,add(tip,polar(t+180+k*24,.32))))
    return diagram(title,pts,[('A','B')],lines)


