def tint(m,view,index):
    ring,=view['circles'];p=m['points'];t=p[ring['center']];b=p[ring['through']];r=hypot(t[0]-b[0],t[1]-b[1])
    ids=[]
    for j in range(72):
        k=f'_disk{j}__v{index}';theta=2*pi*j/72
        p[k]=[t[0]+r*cos(theta),t[1]+r*sin(theta),t[2]];ids.append(k)
    view['polygons']=[ids]


