def regular_shape(title,n,r,phase,degrees):
    names='ABC' if n==3 else 'ABCD'
    center='D' if n==3 else 'T'
    points={center:(0,0)}
    for i,label in enumerate(names):
        angle=radians(phase)+2*pi*i/n
        points[label]=(round(r*cos(angle),9),round(r*sin(angle),9))
    edges=[(k,names[(i+1)%n]) for i,k in enumerate(names)]
    edges.extend((center,label) for label in names)
    return picture(title,points,edges,center,'A',degrees)


