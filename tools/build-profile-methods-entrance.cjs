#!/usr/bin/env node
'use strict';

// Project the existing public catalog into its initial HTML. The application
// replaces this content when it loads; no progress or exercise data is invented.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'ege-profil/azbuka-metodov/index.html');
const context = vm.createContext({ URL, URLSearchParams });
for (const file of ['ege-profil/exam-map.js', 'ege-profil/azbuka-metodov/catalog.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
}
const catalog = context.ProfileAlphabetCatalog;
const escape = value => String(value).replace(/[&<>"']/g,
  letter => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[letter]);
const start = '<!-- profile-methods-catalog:start -->';
const end = '<!-- profile-methods-catalog:end -->';
const content = [
  start,
  '      <!-- Generated by tools/build-profile-methods-entrance.cjs. -->',
  '      <p class="az-kicker">ЕГЭ профиль · 2027</p>',
  '      <h1>Основы и методы</h1>',
  '      <p class="az-lead">Разбери один приём, проверь себя на другом примере и переходи к задачам ЕГЭ.</p>',
  '      <noscript><p class="az-panel">Ниже — темы курса. Для упражнений и самопроверки включите JavaScript. Можно также прочитать <a href="/topics/lineynye-uravneniya/">разбор линейных уравнений</a> или <a href="/topics/oge-geometriya/">разбор геометрической задачи</a>.</p></noscript>',
  '      <div class="az-catalog">',
  ...catalog.list.map(item => '        <a class="az-panel az-card" href="' + escape(catalog.href(item.id)) + '">' +
    '<span class="az-kicker">' + escape(item.numbers.map(catalog.displayLabel).join(' · ')) + '</span>' +
    '<h2>' + escape(item.title) + '</h2><p>' + escape(item.description) + '</p>' +
    '<span class="az-count">Навыков в теме: ' + Object.keys(item.skills).length + '</span></a>'),
  '      </div>',
  '      ' + end,
].join('\n');
const original = fs.readFileSync(target, 'utf8');
const pattern = /<!-- profile-methods-catalog:start -->[\s\S]*?<!-- profile-methods-catalog:end -->/;
if (original.split(start).length !== 2 || original.split(end).length !== 2) {
  throw new Error('Expected exactly one static methods catalog block');
}
const updated = original.replace(pattern, content);
if (process.argv.includes('--check')) {
  if (updated !== original) {
    console.error('Static methods catalog is stale. Run node tools/build-profile-methods-entrance.cjs');
    process.exitCode = 1;
  } else console.log('PROFILE_METHODS_ENTRANCE_CURRENT: ' + catalog.list.length + ' topics');
} else {
  fs.writeFileSync(target, updated);
  console.log('PROFILE_METHODS_ENTRANCE_WRITTEN: ' + catalog.list.length + ' topics');
}
