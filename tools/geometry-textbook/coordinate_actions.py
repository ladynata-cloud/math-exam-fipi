O=(0,0)


def plus(a,b):return tuple(x+y for x,y in zip(a,b,strict=True))


def times(k,a):return tuple(k*x for x in a)


def show(p):
    def unit(v):return (str(int(v)) if v==int(v) else str(v).replace('.',',')).replace('-','−')
    return '('+unit(p[0])+';'+unit(p[1])+')'


def source(n,*,part=None,**fields):
    entry=cartesian(n,part=part,**fields)
    entry['review']['reviewer']='Сверено с печатной с. 252 издания Атанасяна 2023 года. Входные координаты, все подпункты, знаки и нулевые случаи проверены по вычислениям и измерениям авторских чертежей.'
    entry['help'][1].update(theoryIds=['atanasyan-7-9-theory-94-part-1'],text='Сравни действия с двумя координатами и направления на рисунке. Умножение на число действует на обе компоненты.')
    return entry


def pair_answer(entry,point,feedback):
    x,y=point
    entry['answer']={'mode':'exact','accepted':[f'{x};{y}',f'{x}; {y}',f'({x};{y})',f'({x}; {y})'],'prompt':'Введи координаты по порядку x;y, через точку с запятой.','feedback':feedback}
    return entry


def sums_and_differences():
    cases={
        1009:[((3,2),(2,5),(-2,3)),((3,-4),(1,5),(-3,4)),((-4,-2),(5,3),(2,-5)),((2,7),(-3,-7),(6,-2))],
        1010:[((5,3),(2,1),(-3,4)),((3,2),(-3,2),(-2,3)),((3,6),(4,-3),(2,-4)),((-5,-6),(2,-4),(-3,-5))]}
    rows=[]
    for n,dataset in cases.items():
        adding=n==1009; symbol='+' if adding else '−'
        for part,(a,b,transfer) in zip('абвг',dataset,strict=True):
            last=b if adding else times(-1,b)
            result=plus(a,last)
            initial=grid('Две заданные стрелки',[('A',O,a),('B',O,b)])
            action=grid('Присоедини второй шаг',[('A',O,a),('B',a,result)])
            final=grid('Суммарный путь и его результат',[('A',O,a),('B',a,result),('C',O,result)])
            second='перенеси b без изменения направления' if adding else 'разверни b, получив −b, и перенеси из конца a'
            x,y=result
            source_text=(f'Для a={show(a)} и b={show(b)} найди координаты a{symbol}b. Проверь итог по движению от начала до конца ломаной.')
            explain=f'Получаем a{symbol}b={show(result)}. По горизонтали действуем с {a[0]} и {b[0]}, по вертикали с {a[1]} и {b[1]}. Второй шаг после переноса имеет координаты {show(last)}.'
            ea,eb=transfer
            tx=ea+eb if adding else ea-eb
            e=source(n,part=part,question=source_text,answer=explain,
               hint='Сначала запиши два отдельных вычисления. В каждом используй компоненты одной и той же оси.',
               steps=[('Укажи первое и второе перемещение',f'Сначала пройди a={show(a)}. Затем {second}. На рисунке основания соседних шагов совпадают с концами предыдущих.','Сложение заменяет два последовательных движения одним; вычитание складывает с противоположным вектором.'),
                      ('Вычисли обе координаты',f'По x получаем {a[0]} {symbol} ({b[0]}) = {x}. По y — {a[1]} {symbol} ({b[1]}) = {y}. Запиши в неизменном порядке: {show(result)}.','Знак каждой исходной компоненты сохраняй в скобках до выполнения действия.'),
                      ('Сверь по чертежу',f'Результирующая стрелка c идёт из O в {show(result)}. Если какая-либо компонента равна нулю, по этой оси движения двух шагов взаимно компенсировались.','Проверь результат по каждой оси, не меняя местами абсциссу и ординату.')],
               initial=initial,frames=[initial,action,final],cases=[initial,action,final],
               prompts=[(f'Какова вертикальная составляющая a{symbol}b для исходных данных?',str(y),f'Вычисли {a[1]} {symbol} ({b[1]}).'),
                        (f'В новом примере горизонтальные составляющие равны {ea} и {eb}. Какова горизонталь a{symbol}b?',str(tx),f'Вычисли {ea} {symbol} ({eb}).')])
            feedback='Сложи абсциссы только с абсциссами, ординаты только с ординатами. Сохрани порядок x;y.' if adding else 'Вычти координаты второго вектора из соответствующих координат первого; вычитание отрицательной координаты меняет её знак.'
            contrary=plus(a,times(-1,b)) if adding else plus(a,b)
            feedback+=f' Если получилось {show(contrary)}, выполнено противоположное действие.'
            if y==0:feedback+=' Вертикальные части здесь взаимно компенсируются, поэтому вторая координата нулевая.'
            rows.append(pair_answer(e,result,feedback))
    return rows


