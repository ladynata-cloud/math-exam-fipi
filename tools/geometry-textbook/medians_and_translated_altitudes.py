def mid(a,b):
    return tuple((x+y)/2 for x,y in zip(a,b,strict=True))


def medians(title,a,b,c):
    m=tuple((v+w+z)/3 for v,w,z in zip(a,b,c,strict=True))
    names='ABC'
    pts={'A':a,'B':b,'C':c,'M':m,'A₁':mid(b,c),'B₁':mid(c,a),'C₁':mid(a,b)}
    pts.update({s+'₂':mid(pts[s],m) for s in names})
    edges=[('A','B'),('B','C'),('C','A'),('A','A₁'),('B','B₁'),('C','C₁')]
    tri=[(pts[names[i]+suffix],pts[names[(i+1)%3]+suffix]) for i in range(3) for suffix in ('₁','₂')]
    return diagram(title,pts,edges,tri)


