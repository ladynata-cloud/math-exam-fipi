def pattern(title,paths,named):
    points={};edges=[]
    for i,path in enumerate(paths):
        ids=[]
        for j,pt in enumerate(path):
            label=f'm{i}p{j}'
            points[label]=tuple(round(x,9) for x in pt);ids.append(label)
        edges.extend(zip(ids,ids[1:]))
    # Named landmarks come first, so coincident motif corners do not need another visible label.
    return schematic(title,{**named,**points},edges)


def border():
    template=[(0,0),(.85,.35),(.3,1.4),(0,0)]
    motifs=[[(x+2*i,y) for x,y in template] for i in range(4)]
    return pattern('Бордюр с шагом 2',motifs,{'A':(0,0),'A′':(2,0)})


def rosette(n):
    def vertex(r,a):return r*cos(a),r*sin(a)
    step=2*pi/n
    motifs=[]
    for i in range(n):
        t=step*i
        motifs.append([vertex(.4,t),vertex(2.7,t+step*.22),vertex(2.0,t+step*.5),vertex(.4,t)])
    return pattern(f'Розетка из {n} одинаковых мотивов',motifs,{'T':(0,0),'A':vertex(2.7,step*.22)})


def mosaic():
    frame=[[(0,j),(6,j)] for j in (0,1,2,3)]
    frame.extend([[(i,0),(i,3)] for i in (0,2,4,6)])
    return pattern('Фрагмент прямоугольного паркета',frame,{'T':(2,1)})


def clear_pattern_names(card):
    model=card['visualization']['model']
    for view in model['views'].values():
        visible=[]
        for k in view['points']:
            retained=[n for n in model['labels'][k].split('=') if not n.startswith('m')]
            if retained:
                model['labels'][k]='='.join(retained);visible.append(k)
        view['points']=visible
    return card


