def shape(title,a,b,c):
    x=(b*b+c*c-a*a)/(2*c);y=sqrt(b*b-x*x)
    pts={'A':(0,0),'B':(c,0),'C':(x,y),'H':(x,0)}
    return graph(title,pts,edges=[('A','B'),('B','C'),('C','A'),('C','H')])


