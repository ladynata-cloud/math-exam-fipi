def parallel_scene(title,y,z,x0,focus):
    # Rotate both possible directions on the entire line y = const about A.
    a=(x0,0);pts={'A':a};ymin=min(y,z,0);ymax=max(y,z,0)
    lines=[];edges=[]
    for i,sign in enumerate((1,-1)):
        deg=60*sign;si,co=sin(radians(deg)),cos(radians(deg))
        xb=(z-co*y)/si
        b=(x0+xb,y);c=rotated(b,a,deg)
        k='′' if i else ''
        pts['B'+k]=b;pts['C'+k]=c
        edges.extend([('A','B'+k),('B'+k,'C'+k),('C'+k,'A')])
        if focus in (i,2):
            d=(co,si);lines.append((at(c,d,(ymin-.5-z)/si),at(c,d,(ymax+.5-z)/si)))
    xs=[p[0] for p in pts.values()]
    lines.extend([((min(xs)-.65,h),(max(xs)+.65,h)) for h in (y,z)])
    return diagram(title,pts,edges,lines)


