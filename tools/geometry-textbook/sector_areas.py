def arc(points, edges, first, last, center, radius, start, sweep, prefix):
    count = ceil(abs(sweep) / 5)
    names = [first]
    for i in range(1, count):
        theta = radians(start + sweep * i / count)
        key = f'_{prefix}{i}'
        points[key] = (center[0] + radius * cos(theta), center[1] + radius * sin(theta))
        names.append(key)
    names.append(last)
    edges.extend(zip(names, names[1:]))
    return names


def disk(label, r, degrees, region='sector'):
    theta = radians(degrees)
    points = {'T': (0, 0), 'A': (r, 0), 'B': (r*cos(theta), r*sin(theta)),
              'U': (-r, -r-.8), 'W': (1-r, -r-.8)}
    edges = [('T', 'A'), ('T', 'B'), ('U', 'W')]
    if region == 'remainder':
        names = arc(points, edges, 'B', 'A', (0, 0), r, degrees, 360-degrees, 'rest')
    else:
        names = arc(points, edges, 'A', 'B', (0, 0), r, 0, degrees, 'arc')
    if region == 'segment':
        edges.append(('A', 'B'))
        fill = names
    else:
        fill = ['T', *names]
    return graph(label, points, edges=edges, circle=('T', r)), [fill]


def corners(label, side, region):
    r = side/2
    points = dict(zip('ABCDEFGH', [(-r,-r),(r,-r),(r,r),(-r,r),
                                   (0,-r),(r,0),(0,r),(-r,0)], strict=True))
    points.update(U=(-r,-r-.8), W=(1-r,-r-.8))
    edges = list(zip('ABCD', 'BCDA', strict=True)) + [('U','W')]
    quarters = []
    for i, (vertex, first, last) in enumerate(zip('ABCD','EFGH','HEFG',strict=True)):
        curve = arc(points, edges, first, last, points[vertex], r, i*90, 90, f'q{i}_')
        quarters.append([vertex, *curve])
    if region == 'white':
        # Trace midpoints E→H→G→F→E in boundary order.
        fills = [[name for i in (0, 3, 2, 1) for name in quarters[i][1:-1]]]
    elif region == 'one':
        fills = quarters[:1]
    else:
        fills = quarters
    return graph(label, points, edges=edges), fills


def lesson(n, pages, question, proof, hint, steps, scenes, probes, caption, forms=None, title=None):
    c = area(n, None, pages, question, proof, hint, steps, [x for x, _ in scenes],
             probes, refs=[120] if title else [121], title=title)
    c['source']['chapter'] = 'XIII'
    c['review']['reviewer'] = ('Атанасян и др., Геометрия 7–9, 2023. Пункт 121 на с. 306–307, '
        '№1217 на с. 309, №1218–1220 и рис. 354 на с. 310, ключ на с. 402. '
        'Розовые углы рис. 354 сопоставлены с незакрашенной центральной областью.')
    if not title:
        c['help'][1]['text'] = hint
    m = c['visualization']['model']
    m['description'] = c['visualization']['caption'] = caption
    for i, (view, (scene, polygons)) in enumerate(zip(
            m['views'].values(), [scenes[0], *scenes[:3], *scenes], strict=True)):
        ids = {name: k for k in view['points'] for name in m['labels'][k].split('=')}
        view['polygons'] = [[ids.get(k, k + '__v' + str(i)) for k in poly] for poly in polygons]
        if 'T' in ids and not (n == 1220 and i in (3,6)):
            a, b = scene[0][1]['A'], scene[0][1]['B']
            if abs(a[0]*b[0]+a[1]*b[1]) < 1e-8:
                view['rightAngles'] = [dict(vertex=ids['T'], a=ids['A'], b=ids['B'], size=1.3)]
        if n == 1219:
            view['rightAngles'] = [dict(vertex=ids['A'], a=ids['B'], b=ids['D'], size=1.3)]
    if forms:
        return grade(c, forms, hint, 'Введи точное выражение. Для π можно набрать pi, для корня — sqrt(...).')
    if not title:
        c['answer']['prompt'] = 'Объясни переход от доли полного оборота к формуле площади. Сверь доказательство по шагам.'
    return c


