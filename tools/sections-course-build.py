#!/usr/bin/env python3
"""Rebuild the browser data and self-contained download from canonical sources.

The course JSON is the complete, preserved Sections_From_Zero lesson bundle.
Both the website and offline edition use exactly the same data, CSS and runtime.
The shared-board adapter is loaded only by its dedicated trainer wrapper.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "stereo-course" / "sections"


def outputs() -> dict[Path, str]:
    data = json.loads((COURSE / "data" / "course.json").read_text(encoding="utf-8"))
    lessons = data["lessons"]
    if (len(lessons) != 186 or len({lesson["id"] for lesson in lessons}) != 186
            or sum(len(lesson["steps"]) for lesson in lessons) != 967
            or sum(len(lesson.get("calculationSteps", [])) for lesson in lessons) != 81):
        raise ValueError("The reviewed course inventory must remain 186 / 967 / 81")
    # Escape the HTML closing-tag boundary, including future quoted examples.
    course_js = "/* Generated by tools/sections-course-build.py; edit data/course.json. */\nwindow.COURSE=" + json.dumps(
        data, ensure_ascii=False, separators=(",", ":")
    ).replace("</", "<\\/") + ";\n"
    html = (COURSE / "index.html").read_text(encoding="utf-8")
    css = (COURSE / "assets" / "style.css").read_text(encoding="utf-8")
    app = (COURSE / "assets" / "app.js").read_text(encoding="utf-8")
    replacements = {
        '<link rel="stylesheet" href="/stereo-course/sections/assets/style.css">': "<style>\n" + css + "</style>",
        '<script src="/stereo-course/sections/assets/course-data.js"></script>': "<script>\n" + course_js + "</script>",
        '<script src="/stereo-course/sections/assets/app.js"></script>': "<script>\n" + app + "</script>",
    }
    for before, after in replacements.items():
        if html.count(before) != 1:
            raise ValueError("Missing or duplicate canonical asset: " + before)
        html = html.replace(before, after)
    if "<script src=" in html or '<link rel="stylesheet"' in html:
        raise ValueError("The offline course must not require network assets")
    return {
        COURSE / "assets" / "course-data.js": course_js,
        COURSE / "download" / "Sections_From_Zero.html": html,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on generated-file drift without modifying files")
    args = parser.parse_args()
    changed = []
    for path, content in outputs().items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if args.check and changed:
        print("Generated course files need rebuilding: " + ", ".join(changed))
        return 1
    print("Sections course: generated files are current" if not changed else "Rebuilt: " + ", ".join(changed))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
