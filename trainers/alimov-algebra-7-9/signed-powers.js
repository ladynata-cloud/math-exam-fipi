(function(){
  'use strict';
  const course=window.MathExamTopicEdition,{lesson,q,sample}=course;
  const forms=[
    ['5-1','Подстановка в a³b²c²','Подставь a = −1, b = −3, c = 2 в a³b²c².','Нечётная степень a³ равна −1. Квадраты b² и c² равны 9 и 4. Все три множителя дают −36.',[-1,-1,1],[3,2,2],false],
    ['5-2','Подстановка в ab³c²','Подставь a = −2, b = −1, c = −3 в ab³c².','Числа a и b³ отрицательны и дают положительный множитель 2. Квадрат c² равен 9. Получаем 18.',[-1,-1,-1],[1,3,2],false],
    ['5-3','Отрицательный куб в знаменателе','Найди a³b²/c³ при a = −2, b = −3, c = −1.','Числитель равен (−8) · 9 = −72, знаменатель — (−1)³ = −1. Частное двух отрицательных чисел равно 72. Деление допустимо, поскольку c ≠ 0.',[-1,-1,-1],[3,2,3],true],
    ['5-4','Куб в числителе и квадрат в знаменателе','Найди ab³/c² при a = 8, b = −1 и c = −2.','Числитель 8 · (−1)³ = −8. В знаменателе (−2)² = 4. Ответ −2.',[1,-1,-1],[1,3,2],true]
  ];
  for(const [key,title,prompt,guide,sign,exp,divide] of forms){
    lesson(key,title,prompt,guide,'Подставляй отрицательное основание вместе со скобками, затем возводи в степень; только после этого перемножай или дели.',s=>{
      const a=sign[0]*(s+1),b=sign[1]*(1+s%3),c=sign[2]*(2+s%3),A=a**exp[0],B=b**exp[1],C=c**exp[2],numer=A*B,x=divide?numer/C:numer*C;
      const equation='a^'+exp[0]+' · b^'+exp[1]+(divide?' / ':' · ')+'c^'+exp[2];
      return sample('Вычисляй степени отдельно. При чётном показателе ненулевой результат положителен, при нечётном знак основания сохраняется.',
        [['Выражение',equation],['a',a],['b',b],['c',c]],[
          q('Каково значение первой степени a^'+exp[0]+'?',A,'Возведи '+a+' в степень '+exp[0]+'.',-A,'Знак основания и чётность его показателя нужно рассматривать вместе.'),
          q('Каков результат произведения первых двух степеней?',numer,'Умножь '+A+' на ('+b+')^'+exp[1]+'.',-numer,'Подстановка отрицательного b должна происходить в скобках; проверь чётность степени b.'),
          q('Каково окончательное значение выражения?',x,'К полученному результату примени '+(divide?'деление на ':'умножение на ')+C+'.',divide?numer*C:numer/C,'Последняя степень расположена '+(divide?'в знаменателе. Вместо умножения требуется деление.':'в числителе. Вместо деления требуется умножение.'))
        ],'signed-powers',{a,b,c,exp,divide});
    },7,undefined,81);
  }
  const statements=[
    ['6-1','Отрицательное десятичное число относительно нуля','Запиши знак сравнения для утверждения, что −11,7 является отрицательным числом.','Отрицательные числа расположены слева от нуля. Поэтому запись имеет вид −11,7 < 0.',-1,'x'],
    ['6-2','Положительное десятичное число относительно нуля','Запиши неравенство, показывающее положительность 98,3.','Положительное 98,3 расположено справа от нуля, значит, 98,3 > 0.',1,'x'],
    ['6-3','Как записать условие «x отрицательно»','Запиши с помощью знака сравнения условие, что x отрицательно.','x < 0. Точка x расположена строго слева от начала; равенство нулю не допускается.',-1,'x'],
    ['6-4','Как записать условие «y положительно»','Запиши с помощью знака сравнения условие, что y положительно.','y > 0. При положительном y его точка расположена строго справа от начала координат.',1,'y']
  ];
  for(const [key,title,prompt,guide,sign,name] of statements){
    lesson(key,title,prompt,guide,'Знак неравенства указывает положение по отношению к нулю. Расстояние до нуля является модулем числа.',s=>{
      const magnitude=s%2?(2*s+3)/10:2*s+1,step=magnitude/(s+1),value=sign*magnitude;
      return sample('В '+(name==='x'?'точке x':'точке y')+' находится отметка на расстоянии '+magnitude.toLocaleString('ru-RU')+' единицы от нуля. Выбери её сторону по данному условию.',
        [['Условие',name+(sign<0?' отрицательно':' положительно')],['Модуль',magnitude],['Единичных делений до нуля',s+1]],[
          q('Какова координата '+name+'?',value,'Возьми модуль и поставь знак из условия.',-value,'Модуль правильный, но указанная сторона нуля противоположна условию.'),
          q('Какая запись верная? Введи −1 для «'+name+' < 0» или 1 для «'+name+' > 0».',sign,'Сопоставь левую полуось с <, правую — с >.',-sign,'Знак неравенства выбрал противоположное направление.'),
          q('Какова цена одного из равных делений между точкой и нулём?',step,'Раздели расстояние '+magnitude.toLocaleString('ru-RU')+' на '+(s+1)+'.',magnitude,'Здесь посчитано всё расстояние, а требуется длина одного равного деления.')
        ],'signed-zero',{magnitude,step,sign,s,name});
    },7,undefined,81);
  }
  const prev=course.figure;
  course.figure=d=>{
    const t=(x,y,v)=>'<text x="'+x+'" y="'+y+'">'+v+'</text>';
    let body,title;
    if(d.chart==='signed-powers'){
      title='Знаки трёх степеней при подстановке';
      body=t(6,18,'Основание в скобках и показатель');
      for(const [i,x] of [d.a,d.b,d.c].entries()){
        const X=8+i*86;body+=t(X,49,'('+x+')^'+d.exp[i])+t(X,81,(x**d.exp[i])>0?'выше 0':'ниже 0');
        if(i<2)body+=t(X+62,49,i===1&&d.divide?'÷':'×');
      }
    }else if(d.chart==='signed-zero'){
      title='Заданная точка и её расстояние до нуля';const x=135+d.sign*105;
      body=t(7,18,d.name+(d.sign<0?' ниже нуля':' выше нуля'))+'<path d="M17 61 H255 M135 52 V72" fill="none" stroke="#5c806c"/>';
      for(let i=1;i<=d.s+1;i++){const u=135+d.sign*105*i/(d.s+1);body+='<path d="M'+u+' 58 v6" stroke="#547964"/>';}
      body+='<circle cx="'+x+'" cy="61" r="5" fill="#a35576"/>'+t(x-7,92,d.name)+t(131,92,'0');
    }else return prev(d);
    return '<svg viewBox="0 0 280 120" role="img" aria-label="'+title+'"><g font-family="sans-serif" font-size="12" fill="#244c3e">'+body+'</g></svg>';
  };
})();
