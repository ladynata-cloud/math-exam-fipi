def bisect_scene(title,x,y,angle):
    t=(x,y);a=(2*x,0);b=(0,2*y);o=(0,0)
    r=lambda q:rotated(q,o,angle)
    pts={'V':o,'T':t,'A':a,'B':b}
    lines=[((-1,0),(2*x+1,0)),((0,-1),(0,2*y+1)),((-1,2*y),(2*x+1,2*y))]
    return diagram(title,{k:r(v) for k,v in pts.items()},[('A','B')],[(r(p),r(q)) for p,q in lines])


