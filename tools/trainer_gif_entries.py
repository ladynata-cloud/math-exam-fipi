def grid(card, stage, *, area=False):
    for x in range(62, 264, 28):
        card.line(((x, 89), (x, 257)), 'grid', 1)
    for y in range(89, 258, 28):
        card.line(((62, y), (258, y)), 'grid', 1)
    a, b, c = (90, 229), (202 if area else 174, 229), (202 if area else 174, 117)
    if area:
        card.polygon((a, b, c), 'soft', 'blue', 2)
    else:
        card.line((a, c), 'blue', 4)
    if stage >= 1:
        card.line((a, b, c), 'accent', 3)
        card.text((a[0] + b[0]) / 2, 237, '4' if area else '3', 16, 'accent', True)
        card.text(c[0] + 10, 165, '4', 16, 'accent', True)


def cone(card, stage, *, scale=False):
    cx, base, width, top = 155, 223, 79, 103
    if scale:
        width = 100 if stage >= 1 else 50
    a, b, c = (cx - width, base), (cx + width, base), (cx, top)
    card.polygon((a, b, c), 'soft', 'blue', 2)
    lower = [(cx + width * cos(i * pi / 20), base + 17 * sin(i * pi / 20))
             for i in range(21)]
    card.line(lower, 'blue', 2)
    upper = [(cx + width * cos(i * pi / 20), base - 17 * sin(i * pi / 20))
             for i in range(21)]
    card.line(upper, 'muted', 2, dashed=True)
    if stage >= 1:
        card.line((c, (cx, base)), 'accent', 3, dashed=True)
        card.text(cx + 8, (top + base) // 2, 'h' if scale else '4', 17, 'accent', True)
        card.line(((cx, base), b), 'accent', 3)
        card.text(cx + width // 2, base - 20, ('2r' if stage >= 1 else 'r') if scale else '3',
                  17, 'accent', True)


def asa_triangles(card, stage):
    for offset, names in ((0, 'ABC'), (118, 'DEF')):
        a, b, c = (45 + offset, 223), (141 + offset, 223), (78 + offset, 128)
        card.polygon((a, b, c), 'soft', 'blue', 2)
        card.line((a, b), 'accent', 3)
        center = (a[0] + b[0]) / 2
        card.line(((center, 217), (center, 229)), 'accent', 2)
        for (x, y), name in zip((a, b, c), names):
            card.text(x, y + (8 if name in 'ABDE' else -21), name, 16, bold=True, anchor='mt')
        if stage >= 1:
            card.circle(a[0] + 12, a[1] - 8, 4, 'amber')
        if stage >= 2:
            card.circle(b[0] - 15, b[1] - 8, 4, 'blue')


def line_graph(card, stage):
    x0, y0, unit = 133, 195, 23
    for x in range(x0 - 3 * unit, x0 + 6 * unit, unit):
        card.line(((x, 97), (x, 251)), 'grid', 1)
    for y in range(y0 - 4 * unit, y0 + 3 * unit, unit):
        card.line(((64, y), (253, y)), 'grid', 1)
    card.arrow((61, y0), (264, y0), 'muted', 2)
    card.arrow((x0, 253), (x0, 90), 'muted', 2)
    card.text(270, y0 - 9, 'x', 17, 'muted')
    card.text(x0 - 17, 90, 'y', 17, 'muted')
    if stage == 3:
        card.line(((x0 - 12, y0 + 47), (x0 + 58, y0 - 93)), 'accent', 3)
    if stage >= 1:
        card.circle(x0, y0 + unit, 5, 'blue')
        card.text(x0 + 8, y0 + unit + 2, 'A', 17, 'blue', True)
    if stage >= 2:
        card.circle(x0 + 2 * unit, y0 - 3 * unit, 5, 'blue')
        card.text(x0 + 2 * unit + 9, y0 - 3 * unit + 2, 'B', 17, 'blue', True)


