def parallel_scene(title,a,b,a1):
    center=tuple((u+w)/2 for u,w in zip(a,a1))
    b1=rotated(b,center,180)
    return diagram(title,{'A':a,'B':b,'A′':a1,'B′':b1,'T':center},
        [('A','B'),('A′','B′'),('A','A′'),('B','B′')],turning_arrow(center,a,180))


