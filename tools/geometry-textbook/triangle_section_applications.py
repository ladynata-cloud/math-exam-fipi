def diagonal_frame(title,a,b,alpha,show):
    x=b*cos(radians(alpha));y=b*sin(radians(alpha))
    pts={'A':(0,0),'B':(a,0),'C':(a+x,y),'D':(x,y),'K':((a+x)/2,y/2)}
    edges=[('A','B'),('B','C'),('C','D'),('D','A'),('A','C')]
    if show:edges.append(('B','D'))
    return graph(title,pts,edges=edges)


