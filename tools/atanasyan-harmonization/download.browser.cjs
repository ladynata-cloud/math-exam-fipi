'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
const {folder, textbook, first} = require('./download.test.cjs');
const out = path.resolve(process.env.HARMONIZATION_DOWNLOAD_ARTIFACTS || 'artifacts/atanasyan-harmonization/download');
fs.mkdirSync(out, {recursive: true});
const evidence = {completed: false, widths: [], networkRequests: [], errors: []};
let browser;
(async () => {
  browser = await chromium.launch({headless: true, ...(process.env.CHROMIUM_EXECUTABLE_PATH ? {executablePath: process.env.CHROMIUM_EXECUTABLE_PATH} : {})});
  for (const width of [320, 1280]) {
    const context = await browser.newContext({viewport: {width, height: 900}, offline: true});
    await context.route(/^https?:/, route => { evidence.networkRequests.push(route.request().url()); return route.abort(); });
    context.on('page', opened => opened.on('pageerror', error => evidence.errors.push(error.message)));
    const page = await context.newPage();
    const open = async (file, id = '') => page.goto(pathToFileURL(path.join(folder, file)).href + (id ? '#' + id : ''));
    await open('index.html');
    assert.equal(await page.locator('a[href^="atlas/"]').evaluateAll(links => new Set(links.map(link => link.getAttribute('href'))).size), 63);
    await page.locator('a[href="atlas/segments.html"]').first().click();
    await page.locator('.topic-investigation svg').waitFor();
    await page.locator('.research-predict select').selectOption('unsure');
    await page.locator('.research-predict button').click();
    const slider = page.locator('.research-controls input[type=range]').first();
    await slider.focus();
    await slider.press('ArrowRight');
    await page.locator('#observation').fill('В автономной копии две разные точки задают одну прямую.');
    // A real reload exercises the exported page and its normal store.
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('mathExamGeometry.v1'))?.units.segments.research?.observation?.includes('автономной'));
    await page.reload();
    assert.match(await page.locator('#observation').inputValue(), /автономной/);
    const savedBeforeGuide = await page.evaluate(() => localStorage.getItem('mathExamGeometry.v1'));
    await page.locator('.manual-research summary').first().click();
    const guide = page.locator('[data-geometry-guide-surface="manual"]');
    const picture = guide.locator('.geg-preview img');
    await picture.evaluate(img => img.decode());
    assert((await picture.getAttribute('src')).startsWith('../_shared/geometry-experiment-gifs/'), 'offline poster uses the packaged exact media');
    await guide.getByRole('button', {name: 'Смотреть GIF', exact: true}).click();
    await picture.evaluate(img => img.decode());
    assert.equal(await guide.locator('.geometry-experiment-guide').getAttribute('data-playing'), 'true');
    await guide.getByRole('button', {name: 'Остановить GIF', exact: true}).click();
    await guide.getByRole('button', {name: 'Следующий шаг инструкции', exact: true}).click();
    await picture.evaluate(img => img.decode());
    await page.waitForTimeout(250);
    assert.equal(await page.evaluate(() => localStorage.getItem('mathExamGeometry.v1')), savedBeforeGuide, 'offline playback preserves exact saved work');
    await page.screenshot({path: path.join(out, width + '-offline-segments.png')});
    const lesson = textbook.lessons.find(item => item.kind === 'exercise');
    await open('index.html');
    await page.locator('a[href="textbook/index.html"]').click();
    await page.locator('#catalog-search').fill(lesson.source.exercise);
    await page.locator('[data-lesson="' + lesson.id + '"]').click();
    await page.locator('[data-main-model] svg').waitFor();
    await page.locator('#final-answer').fill('Запись из автономного задачника');
    await page.reload();
    await page.locator('#final-answer').waitFor();
    assert.equal(await page.locator('#final-answer').inputValue(), 'Запись из автономного задачника');
    await page.screenshot({path: path.join(out, width + '-offline-textbook.png')});
    const initial = first.lessons.find(item => item.kind === 'exercise');
    await open('index.html');
    await page.locator('a[href="first-steps/index.html"]').click();
    await page.locator('[data-companion-course]').waitFor();
    await page.evaluate(id => { location.hash = id; }, initial.id);
    await page.locator('[data-course-model] svg').waitFor();
    await page.locator('#afs-answer').fill('Мой первый шаг без подключения к сети.');
    await page.locator('[data-save-work]').click();
    assert.match(await page.locator('[data-save-status]').innerText(), /учител/);
    await page.reload();
    await page.locator('#afs-answer').waitFor();
    assert.equal(await page.locator('#afs-answer').inputValue(), 'Мой первый шаг без подключения к сети.');
    assert.equal(await page.locator('.afs-original-link').getAttribute('href'), '../textbook/index.html#' + initial.id);
    await page.screenshot({path: path.join(out, width + '-offline-first-steps.png')});
    const [linked] = await Promise.all([context.waitForEvent('page'), page.locator('.afs-original-link').click()]);
    await linked.locator('[data-main-model] svg').waitFor();
    assert(linked.url().endsWith('/textbook/index.html#' + initial.id));
    await linked.close();
    await open('first-steps/index.html');
    assert.equal(await page.locator('[data-companion-course]').getAttribute('href'), 'https://mathexam.space/geometry-course/ichenskaya-7-works/');
    evidence.widths.push({width, atlasSaved: true, textbookSaved: true, firstStepsSaved: true, localGifPlayback: true});
    await context.close();
  }
  assert.deepEqual(evidence.networkRequests, [], 'all learning resources are local');
  assert.deepEqual(evidence.errors, []);
  evidence.completed = true;
  console.log('ATANASYAN_HARMONIZATION_DOWNLOAD_BROWSER_OK: file://, network disabled, atlas/textbook/first-steps, both widths and restored work');
})().catch(error => { evidence.failure = error.stack; console.error(error); process.exitCode = 1; }).finally(async () => {
  fs.writeFileSync(path.join(out, 'evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
  await browser?.close();
  fs.rmSync(folder, {recursive: true, force: true});
});
