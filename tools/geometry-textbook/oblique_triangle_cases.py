def parallelogram(label,ad,bd,ang,sgn,construction=False):
    theta=radians(ang);dx=ad*cos(theta);dy=ad*sin(theta);shift=sqrt(max(0,bd*bd-dy*dy))
    bx=dx+sgn*shift
    pts={'A':(0,0),'D':(dx,dy),'B':(bx,0),'C':(bx+dx,dy)}
    return graph(label,pts,edges=[('A','B'),('B','C'),('C','D'),('D','A'),('B','D')],circle=('D',bd) if construction else None)


def two_parallelograms():
    ad=22/3;bd=4.4;t=22.5
    views=[parallelogram('Длинное основание AB: острый угол DBA',ad,bd,t,1),
           parallelogram('Короткое основание AB: тупой угол DBA',ad,bd,t,-1),
           parallelogram('Граничная конфигурация: касание прямой AB',5,2.5,30,1,True),
           parallelogram('Пересечения с окружностью радиуса BD',ad,bd,t,1,True)]
    angle=degrees(asin(ad*sin(radians(t))/bd))
    assert 39.62<angle<39.64 and 17.12<angle-t<17.14
    hint='Задан синус угла DBA. Проверь и угол β, и 180°−β: обе суммы с 22°30′ меньше 180°. Параллельность сторон переносит эти углы к диагонали BD.'
    c=area(1117,None,[282],'В параллелограмме ABCD даны AD=7⅓ м, BD=4,4 м и ∠A=22°30′. Найди все возможные пары (∠BDC; ∠DBC), округлив углы до десятых градуса.',
           'В ABD имеем sin ∠DBA=(AD/BD)sin 22,5°=(5/3)sin 22,5°. Получаются ∠DBA≈39,628° или 140,372°. Соседние стороны параллельны, поэтому ∠BDC=∠DBA, ∠DBC=∠BDA. Пары до десятых: (39,6°;117,9°) и (140,4°;17,1°).',hint,
           [('Восстанови синус','В треугольнике ABD напротив угла A лежит BD, а напротив угла при B лежит AD. Поэтому sin B=(22/3)/(22/5)·sin 22,5°=(5/3)sin 22,5°. Острая ветвь B≈39,628° даёт D≈117,872°.','Не перепутай противолежащие стороны.'),
            ('Построй второй параллелограмм','У того же синуса есть B≈140,372°. Этот угол вместе с 22,5° занимает меньше 180°: D≈17,128°. Ширина основания AB меняется. Поскольку DC∥AB и BC∥AD, B и D дают требуемые углы BDC и DBC соответственно.','Проверь два разных пересечения прямой основания с окружностью радиуса BD.'),
            ('Проверь граничный случай','Пусть AD=5, ∠A=30° и BD=2,5. Высота D над AB равна BD, так что окружность касается прямой в B. Остаётся одна пара: ∠BDC=90°, ∠DBC=60°.','Два решения сливаются в одно, когда sin DBA=1.')],views,
           [('Сколько разных исходных параллелограммов удовлетворяют условию?','2','Проверь оба угла с одним и тем же синусом.'),('Сколько решений в новом примере с касанием?','1','Окружность касается прямой только в одной точке.')],refs=[100,105,107])
    groups=[('39,6;117,9','140,4;17,1'),('39.6;117.9','140.4;17.1')]
    forms=[v for a,b in groups for pair in [(a,b),(b,a)] for v in (';'.join(pair),'; '.join(pair))]
