def scene(label,outer,inner=0,show_width=True):
    p={'T':(0,0),'A':(outer,0),'B':(-outer,0),'U':(-outer,-outer-.6),'W':(1-outer,-outer-.6)}
    edges=[('A','T'),('T','B'),('U','W')]
    if inner:
        p['H']=(inner,0)
        if show_width:edges.append(('H','A'))
    return graph(label,p,edges=edges,circle=('T',outer)),inner/outer


def shade(c,views):
    m=c['visualization']['model']
    for i,(v,(_,ratio)) in enumerate(zip(m['views'].values(),[views[0],*views,*views],strict=True)):
        pos=m['points'];ids={name:k for k in v['points'] for name in m['labels'][k].split('=')}
        t=pos[ids['T']];a=pos[ids['A']];r=hypot(a[0]-t[0],a[1]-t[1]);boundary=[];inside=[]
        for j in range(72):
            theta=2*pi*j/72
            for prefix,scale,append_to in ([('_outer',1,boundary),('_inner',ratio,inside)] if ratio else [('_outer',1,boundary)]):
                k=f'{prefix}{j}__v{i}';pos[k]=[t[0]+scale*r*cos(theta),t[1]+scale*r*sin(theta),t[2]];append_to.append(k)
        if ratio:
            v['circles'].append({'center':ids['T'],'through':ids['H']})
            # Separate quadrilateral pieces paint just the ring. The central disk remains clear.
            v['polygons']=[[boundary[j],boundary[(j+1)%72],inside[(j+1)%72],inside[j]] for j in range(72)]
            v['highlightSegments']=[[ids['H'],ids['A']]]
            m.setdefault('labelOffsets',{}).update({ids['H']:[-2,4],ids['A']:[3,-4]})
        else:
            v['polygons']=[boundary];v['highlightSegments']=[[ids['T'],ids['A']]]
    return c


def make(n,task,reason,hint,steps,vs,checks,note,answers,request):
    c=area(n,None,[309],task,reason,hint,steps,[v for v,_ in vs],checks,refs=[118,120])
    c['source']['chapter']='XIII';c['help'][1]['text']=hint
    c['review']['reviewer']='Атанасян, издание 2023: точные исходные величины с единицами сверены на с. 309; ответы №1209–1213 — на с. 402. Диаметры, одинаковые центры, толщина кольцевого слоя и расход на квадратный метр проверены отдельно.'
    c['visualization']['caption']=note;c['visualization']['model']['description']=note
    return grade(shade(c,vs),answers,hint,request)


