def cut(p,indices,title=None):
    q=deepcopy(p)
    q['rows']=[deepcopy(p['rows'][i]) for i in indices]
    q['views']=[deepcopy(p['views'][i]) for i in indices]
    q['cases']=[]
    if title:q['title']=title
    return q

