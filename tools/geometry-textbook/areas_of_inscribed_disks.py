def trapezoid(label,a,t):
    # t=tan(alpha/2), so b=a*t² and 2r=a*t give a true tangential isosceles trapezium.
    r=a*t/2;b=a*t*t
    p={'A':(-a/2,0),'B':(a/2,0),'C':(b/2,2*r),'D':(-b/2,2*r),'T':(0,r),'H':(0,0),'K':(0,2*r)}
    for name,u,v in [('L','B','C'),('M','A','D')]:
        x,y=p[u];dx,dy=p[v][0]-x,p[v][1]-y
        q=(-x*dx+(r-y)*dy)/(dx*dx+dy*dy);p[name]=(x+q*dx,y+q*dy)
    p['U']=(-a/2,-.7);p['W']=(1-a/2,-.7)
    edges=outline('ABCD')+[('A','T'),('T','H'),('T','K'),('T','L'),('T','M'),('A','H'),('U','W')]
    return drawing(label,p,edges,'T',r,[('A','T'),('A','H'),('T','H')])


