        def draw(card, stage):
            left = 302 if diagram else 100
            if diagram:
                diagram(card, stage)
            for index, formula in enumerate(formulas[:stage + 1]):
                y = 85 + 45 * index
                active = index == stage
                card.rect((left, y, 615 if diagram else 540, y + 39),
                          'soft' if active else 'white', 'edge', radius=6)
                size = 22 if diagram else 25
                while card.draw.textlength(formula, font=card.font(size, active)) > (289 if diagram else 408):
                    size -= 1
                card.text(left + 13, y + 9, formula, size, 'accent' if active else 'muted', active)
        build(slug, title, steps, draw)

