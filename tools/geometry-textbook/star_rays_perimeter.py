def meet(a,b,d):
    # Point a+t(b-a) on the ray lambda*d. Use the directed area determinant.
    ux,uy=b[0]-a[0],b[1]-a[1]
    det=lambda x,y:x[0]*y[1]-x[1]*y[0]
    t=-det(a,d)/det((ux,uy),d)
    return (a[0]+t*ux,a[1]+t*uy)


def folded(title,alpha,theta,r):
    b=(0,0);d=polar(theta,r);p=polar(-theta,r);q=polar(2*alpha-theta,r)
    e=meet(p,q,direction(0));f=meet(p,q,direction(alpha))
    a=polar(0,r+1);c=polar(alpha,r+1)
    pts={'A':a,'B':b,'C':c,'D':d,'E':e,'F':f,'P':p,'Q':q}
    edges=[('B','A'),('B','C'),('D','E'),('E','F'),('F','D')]
    return diagram(title,pts,edges,[(p,q)])


