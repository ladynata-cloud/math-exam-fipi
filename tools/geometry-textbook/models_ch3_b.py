def four_points(first, second, opposite=False, suffix=''):
    b, c = [25, 25], [65, 25]
    direction = 180 - second if not opposite else 180 + second
    dlen = 30 if not opposite else 18
    return {name + suffix: point for name, point in
            {'B': b, 'C': c, 'A': polar(b, first, 31), 'D': polar(c, direction, dlen)}.items()}


def four_view(suffix='', **kw):
    a, b, c, d = [name + suffix for name in 'ABCD']
    return sc([a, b, c, d], [[a, b], [b, c], [c, d]],
              angleArcs=[arc(b, a, c), arc(c, b, d)], **kw)


