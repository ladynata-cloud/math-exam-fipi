def path_points(p,prefix,r,start,length,count,offset=(0,0),first='A',last='B'):
    names=[first,*[prefix+str(j) for j in range(1,count)],last]
    for j,name in enumerate(names):
        a=start+length*j/count;p[name]=(round(offset[0]+r*cos(a),10),round(offset[1]+r*sin(a),10))
    return names


def pairs(names):return list(zip(names,names[1:]))


def wheel(title,r,deg):
    p={'T':(0,0),'U':(-r,-r-1),'W':(1-r,-r-1)}
    phi=deg*pi/180;start=-phi/2;end=phi/2
    arc=path_points(p,'_open',r,start,phi,32)
    outer=path_points(p,'_guard',r+.38,end,2*pi-phi,48,first='D',last='E')
    inner=path_points(p,'_back',r,start,-(2*pi-phi),48,first='A',last='B')
    edges=[('T','A'),('T','B'),('U','W'),('B','D'),('A','E')]+pairs(arc)+pairs(outer)+pairs(inner)
    g=graph(title,p,edges=edges,circle=('T',r))
    return (*g[:3],pairs(arc)),outer+inner


def pendulum(title,r,deg):
    p={'T':(0,0),'U':(-r*.7,-r-.55),'W':(-r*.7+1,-r-.55),'M':(0,-r)}
    phi=deg*pi/180
    path=path_points(p,'_swing',r,-pi/2-phi/2,phi,32)
    # The low point of the pendulum already has the visible name M.
    path[16]='M';p.pop('_swing16')
    g=graph(title,p,edges=[('T','A'),('T','B'),('T','M'),('U','W')]+pairs(path))
    return (*g[:3],pairs(path))


def track(title,r,phi,close=False):
    if close:
        # The curve is shown in true metres/100. Its center lies outside the close-up.
        p={'U':(0,-.75),'W':(1,-.75)}
        route=path_points(p,'_rail',r,-pi/2,phi,28,offset=(0,r))
        edges=[('U','W')]+pairs(route)
        # The source starting point coincides with the internal plotting origin.
        g=graph(title,p,edges=edges);mapping=g[1]
        route=['O' if k=='A' and 'A' in mapping.get('O','').split('=') else k for k in route]
    else:
        p={'T':(0,0),'U':(-.5,-.7),'W':(.5,-.7)}
        route=path_points(p,'_rail',r,pi/3,phi,28)
        g=graph(title,p,edges=[('T','A'),('T','B'),('U','W')]+pairs(route))
    return (*g[:3],pairs(route))


