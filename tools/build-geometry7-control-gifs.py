#!/usr/bin/env python3
"""Compose the control-work GIFs and still previews from recorded trainer steps."""

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TRAINER = ROOT / 'trainers/geometry-7'
FONTS = Path('/usr/share/fonts/truetype/dejavu')
SIZE = (640, 428)


def wrap(draw, text, font, width):
    lines = ['']
    for word in text.split():
        candidate = (lines[-1] + ' ' + word).strip()
        if lines[-1] and draw.textlength(candidate, font=font) > width:
            lines.append(word)
        else:
            lines[-1] = candidate
    return lines


def make_frame(title, step, number, count, source_dir):
    frame = Image.new('RGB', SIZE, '#f8f9ff')
    draw = ImageDraw.Draw(frame)
    heading = ImageFont.truetype(str(FONTS / 'DejaVuSans-Bold.ttf'), 19)
    body = ImageFont.truetype(str(FONTS / 'DejaVuSans.ttf'), 20)
    counter = ImageFont.truetype(str(FONTS / 'DejaVuSans-Bold.ttf'), 15)
    draw.rectangle((0, 0, 640, 54), fill='#211c4e')
    draw.text((21, 15), title, font=heading, fill='#fff')
    draw.rounded_rectangle((548, 12, 620, 41), radius=8, fill='#e4f6aa')
    draw.text((584, 27), f'{number}/{count}', anchor='mm', font=counter, fill='#24224c')

    content_top = 64
    if tool_filename := step.get('toolFilename'):
        with Image.open(source_dir / tool_filename) as button:
            tool = button.convert('RGB')
        frame.paste(tool, ((640 - tool.width) // 2, content_top))
        content_top += tool.height + 8

    with Image.open(source_dir / step['filename']) as source:
        image = source.convert('RGB')
        image.thumbnail((590, 342 - content_top), Image.Resampling.LANCZOS)
    left = (640 - image.width) // 2
    top = content_top + (342 - content_top - image.height) // 2
    draw.rounded_rectangle((left - 3, top - 3, left + image.width + 3, top + image.height + 3),
                           radius=8, fill='#e1e5f1')
    frame.paste(image, (left, top))
    if point := step.get('point'):
        x, y = (left + point[0] * image.width, top + point[1] * image.height)
        draw.ellipse((x - 10, y - 10, x + 10, y + 10), outline='#b82b62', width=3)

    draw.rounded_rectangle((16, 354, 624, 414), radius=10, fill='#efedff')
    caption = step['caption']
    lines = wrap(draw, caption, body, 572)
    if len(lines) > 2:
        body = ImageFont.truetype(str(FONTS / 'DejaVuSans.ttf'), 18)
        lines = wrap(draw, caption, body, 572)
    if len(lines) > 2:
        raise ValueError(f'Caption needs a shorter line: {caption}')
    start = 354 + (60 - len(lines) * 23) // 2
    for index, line in enumerate(lines):
        draw.text((33, start + index * 23), line, font=body, fill='#24224c')
    return frame


def build(source):
    clips = json.loads((source / 'frames.json').read_text(encoding='utf-8'))
    output = TRAINER / 'control-work-gifs'
    output.mkdir(exist_ok=True)
    metadata = {}
    for clip in clips:
        identifier = clip['id']
        frames = clip['frames']
        images = [
            make_frame(clip['title'], frame, index + 1, len(frames), source)
            for index, frame in enumerate(frames)
        ]
        still = images[min(1, len(images) - 1)]
        still.save(output / f'{identifier}.webp', quality=84, method=6)
        palette = [image.quantize(colors=112, method=Image.Quantize.MEDIANCUT) for image in images]
        palette[0].save(output / f'{identifier}.gif', save_all=True, append_images=palette[1:],
                        duration=[2300] * (len(images) - 1) + [3300], loop=0, optimize=True, disposal=2)
        metadata[identifier] = {'title': clip['title'], 'steps': [frame['caption'] for frame in frames]}
    assert len(metadata) == 16
    data = json.dumps(metadata, ensure_ascii=False, indent=2)
    (TRAINER / 'control-work-demo-data.js').write_text(
        '// Generated by tools/build-geometry7-control-gifs.py\nwindow.GeometryControlDemoData = ' + data + ';\n',
        encoding='utf-8',
    )
    print(f'{len(metadata)} GIFs and previews · {sum(file.stat().st_size for file in output.iterdir()):,} bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('frames', type=Path)
    build(parser.parse_args().frames)
