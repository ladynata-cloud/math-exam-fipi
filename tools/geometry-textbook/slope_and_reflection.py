def incline(label,k,d):
    pts={'P':(0,d),'Q':(2,d+2*k),'H':(2,d)}
    return straight(label,pts,[(k,-1,d)],edges=[('P','H'),('H','Q')])


def slopes():
    cases=[
        ('а','x+1',1,1,'1',45,1,135,'Когда x увеличивается на 2, y также увеличивается на 2.'),
        ('б','−x+2',-1,2,'−1',135,-1,45,'При движении на 2 вправо ордината уменьшается на 2.'),
        ('в','(√3/3)x+4',sqrt(3)/3,4,'√3/3',30,1,150,'На отрезке длины 2 по горизонтали приращение ординаты равно 2√3/3.'),
        ('г','−(√3/3)x+5',-sqrt(3)/3,5,'−√3/3',150,-1,30,'При увеличении абсциссы на 2 изменение ординаты составляет −2√3/3.'),
        ('д','−√3x−2',-sqrt(3),-2,'−√3',120,-1,60,'Приращению абсциссы 2 соответствует приращение ординаты −2√3.')]
    cards=[]
    for part,expr,k,d,exact,angle,sign,other,measure in cases:
        hint='Угловой коэффициент равен тангенсу угла. Знак k указывает, лежит угол до или после 90°. Свободный член сдвигает прямую по вертикали.'
        reason=f'У прямой y={expr} коэффициент при x равен {exact}. Поэтому tg α={exact}, откуда α={angle}° в диапазоне 0°≤α<180°.'
        frames=[incline('Исходная прямая',k,d),incline('Параллельный сдвиг на две единицы вверх',k,d+2),incline('Отражение наклона при сохранении пересечения с Oy',-k,d)]
        c=author(1107,part,[276],f'Какой угол образует прямая y={expr} с положительной полуосью Ox? Выбери угол наклона от 0° до 180°.',reason,hint,
                 [('Измерь подписанный наклон',measure+f' Отношение Δy/Δx={exact}.','Читай изменение слева направо. При убывании графика оно отрицательно.'),
                  ('Свяжи наклон с углом',reason+' На втором чертеже та же прямая сдвинута на две единицы вверх, её угол сохранился.','Добавление постоянной к обеим ординатам не меняет их разность.'),
                  ('Измени знак наклона',f'Теперь коэффициент при x равен числу, противоположному исходному. Угол стал 180°−{angle}°={other}°.','Сравни две прямые по разные стороны от вертикали через точку P.')],frames,
                 [('Какой знак имеет исходный коэффициент k? Введи 1 или −1.',str(sign),'Смотри на коэффициент при x вместе со знаком.'),('Какой угол (в градусах) у отражённого наклона?',str(other),'Найди угол, смежный с исходным.')],[100,103],caption=GRID+' Отрезки PH и HQ показывают приращения координат.')
        cards.append(grade(c,[str(angle),f'{angle}°',f'{angle} градусов'],hint,'Введи угол в градусах.'))
    return cards


def light_view(label,mx,my,screen,show):
    hit=mx-my
    pts={'M':(mx,my),'K':(hit,0)}
    paths=[(pts['M'],pts['K'])]
    if show:
        height=hit-screen
        pts.update({'B':(screen,0),'P':(screen,height)})
        # Only the path of light up to the screen is colored. There is no continuation on the other side of K.
        paths.append((pts['K'],pts['P']))
        paths.append(((screen,-.5),(screen,height+1)))
    return graph(label,pts,lines=paths)


def reflection():
    figures=[light_view('Падение из M до точки K',8,3,-10,False),light_view('Отражение к вертикальному экрану',8,3,-10,True),light_view('Другие положения источника и экрана',4,2,-3,True)]
    hint='От M луч движется вниз и влево. При отражении от Ox горизонтальное направление сохраняется, вертикальное меняется. Найди пересечение с вертикалью экрана.'
    task='Из точки M=(8;3) свет падает на ось Ox и отражается от неё. Прямая падения образует с положительной полуосью Ox угол 45°. Найди уравнения прямых, содержащих падающий и отражённый лучи, и точку встречи с экраном, стоящим перпендикулярно Ox через B=(−10;0).'
    reason='Прямая падения y=x−5 проходит через M и пересекает Ox в K=(5;0). Вектор падающего света можно взять (−1;−1), отражённого (−1;1). Прямая отражения y=−x+5, а свет идёт вдоль неё только при x≤5. Экран задан x=−10, поэтому встреча происходит в P=(−10;15).'
    c=author(1108,None,[276],task,reason,hint,[('Найди точку падения','Коэффициент прямой падения tg 45°=1. Подставь M: 3=8+d, значит d=−5. Встреча с осью требует 0=x−5, откуда K=(5;0).','От источника до K уменьшаются обе координаты.'),
        ('Отрази направление','При отражении от горизонтального зеркала компонента вдоль него сохраняется. Вместо (−1;−1) получаем (−1;1). Через K проходит y=−x+5. При x=−10 получаем y=15. Точка лежит по нужную сторону от K.','Наклон прямой сам по себе не определяет, в какую сторону движется свет.'),
        ('Перенеси источник и экран','Возьми M=(4;2), экран x=−3, угол падения тот же. Тогда y=x−2, K=(2;0). Луч отражения идёт по y=−x+2 при x≤2, встречает экран в (−3;5).','Проверь уравнение в точке падения и в полученной точке экрана.')],figures,
        [('Чему равна абсцисса исходной точки падения K?','5','Положи y=0 в уравнении падающей прямой.'),('Чему равна высота встречи с новым экраном x=−3?','5','Подставь −3 в y=−x+2.')],[102,103],caption=GRID+' Луч идёт от M к K и далее вверх и влево к экрану BP.')
    formats=['1;-5;-1;5;-10;15','1; -5; -1; 5; -10; 15','y=x-5; y=-x+5; (-10;15)','y=x−5; y=−x+5; (−10;15)']
    return grade(c,formats,hint,'Запиши шесть чисел через точку с запятой: k и d для прямой падения y=kx+d, затем k и d для отражения, затем x и y точки на экране.')


def build():
    return {'bookId':BOOK,'lessons':slopes()+[reflection()]}


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    text=json.dumps(build(),ensure_ascii=False,separators=(',',':'))+'\n'
    if parser.parse_args().check:assert OUT.read_text()==text
    else:OUT.write_text(text)
