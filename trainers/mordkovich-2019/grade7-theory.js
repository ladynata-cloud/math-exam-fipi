  function figure(data) {
    const v=data.visual;
    if(v.kind==='branches') {
      return '<svg viewBox="0 0 280 96" role="img" aria-label="'+v.caption+'"><g font-family="sans-serif" text-anchor="middle" fill="#244139" font-size="12">'+
        v.values.map(([name,value,detail],i)=>{const x=70+140*i;return '<rect x="'+(x-64)+'" y="4" width="128" height="76" rx="6" fill="#e4f1ed" stroke="#35695a"/><text x="'+x+'" y="24">'+name+'</text><text x="'+x+'" y="46" font-weight="bold">'+value+'</text><text x="'+x+'" y="68">'+detail+'</text>';}).join('')+'</g></svg>';
    }
    if(v.kind==='area') {
      const width=225,split=v.plus?width*v.w/(v.w+v.k):width*(v.w-v.k)/v.w;
      return '<svg viewBox="0 0 280 103" role="img" aria-label="Прямоугольник. Последняя полоса '+(v.plus?'добавлена':'вычтена')+'"><rect x="35" y="18" width="'+split+'" height="47" fill="#a9d9be" stroke="#38715e"/><rect x="'+(35+split)+'" y="18" width="'+(width-split)+'" height="47" fill="'+(v.plus?'#bed4eb':'#f6d7bb')+'" stroke="#586556" stroke-dasharray="'+(v.plus?'0':'4 2')+'"/><g fill="#263d37" text-anchor="middle" font-family="sans-serif" font-size="12"><text x="17" y="45">'+v.h+'</text><text x="'+(35+split+(width-split)/2)+'" y="46">'+v.k+'</text><text x="145" y="88">полная ширина '+(v.plus?(v.w+v.k):v.w)+'</text></g></svg>';
    }
    const x=h=>32+9*h, y=t=>97-74*t/(Math.max(...v.temp)-Math.min(...v.temp))-(-Math.min(...v.temp))*74/(Math.max(...v.temp)-Math.min(...v.temp));
    const points=v.hours.map((h,i)=>x(h)+','+y(v.temp[i])).join(' ');
    return '<svg viewBox="0 0 280 126" role="img" aria-label="Температура по часам. Точки — измерения, отрезки соединяют соседние наблюдения"><g fill="#244139" font-size="10" font-family="sans-serif"><path d="M32 9v91m0 -'+(100-y(0))+'h225" fill="none" stroke="#667b79"/><polyline points="'+points+'" fill="none" stroke="#437566" stroke-width="2"/>'+
      v.hours.map((h,i)=>'<circle cx="'+x(h)+'" cy="'+y(v.temp[i])+'" r="3.5" fill="#8b4226"/><text x="'+x(h)+'" y="113" text-anchor="middle">'+h+'</text>').join('')+
      '<text x="1" y="18">°C</text><text x="247" y="124">час</text><text x="2" y="'+(y(0)+3)+'">0</text><text x="2" y="'+(y(Math.max(...v.temp))+3)+'">'+Math.max(...v.temp)+'</text><text x="2" y="99">'+Math.min(...v.temp)+'</text></g></svg>';
  }
