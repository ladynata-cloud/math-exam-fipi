    pairs={'A':(3,7),'B':(-2,1),'C':(6,14),'D':(2,-1),'E':(2,4)}
    # A larger square represents two source units in this particular problem.
    vis=lambda label,keys:grid(label,[(key,O,times(.5,pairs[key])) for key in keys])
