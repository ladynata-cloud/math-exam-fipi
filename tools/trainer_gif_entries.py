def number_line(labels, highlighted, position=None):
    def draw(card, stage):
        left, right, top = 50, 270, 177
        card.arrow((left - 7, top), (right + 9, top), 'muted', 2)
        spacing = (right - left) / (len(labels) - 1)
        for index, label in enumerate(labels):
            x = left + spacing * index
            active = index in highlighted[stage]
            card.line(((x, top - 6), (x, top + 6)), 'muted', 2)
            if active:
                card.circle(x, top, 5, 'accent', 'white', 1)
            card.text(x, top + 18, label, 16, 'accent' if active else 'muted',
                      bold=active, anchor='mt')
        if position is not None:
            fraction, label = position
            x = left + (right - left) * fraction
            card.circle(x, top, 5, 'amber')
            card.text(x, top - 28, label, 16, 'amber', bold=True, anchor='mt')
    return draw


def fraction_strip(total, counts):
    def draw(card, stage):
        left, top, width = 46, 158, 224
        for index in range(total):
            box = (left + index * width / total, top,
                   left + (index + 1) * width / total, top + 34)
            card.rect(box, 'accent' if index < counts[stage] else 'white', 'edge')
    return draw


def triangle(card, stage, *, exterior=False, area=False):
    a, b = (55, 235), (244, 235)
    if area:
        c = (55, 101)
    else:
        rise = (b[0] - a[0]) / (1 / tan(pi / 4) + 1 / tan(pi / 3))
        c = (a[0] + rise, a[1] - rise)
    card.polygon((a, b, c), 'soft', 'blue', 2)
    card.text(43, 242, 'A', 16, bold=True)
    card.text(238, 242, 'B', 16, bold=True)
    card.text(c[0] - 2, c[1] - 19, 'C', 16, bold=True)
    if area:
        card.line(((a[0] + 13, a[1]), (a[0] + 13, a[1] - 13),
                   (a[0], a[1] - 13)), 'muted', 2)
        card.text(140, 214, '8', 19, 'accent', True)
        card.text(39, 159, '6', 19, 'accent', True)
    else:
        card.text(92, 212, '45°', 16, 'accent', True)
        card.text(204, 210, '60°' if not exterior or stage >= 1 else '?', 16, 'accent', True)
        card.text(c[0] + 3, c[1] + 31, '75°' if stage >= 2 or exterior else '?',
                  16, 'accent', True)
        if exterior:
            card.arrow((b[0], b[1]), (279, b[1]), 'amber', 2)
            card.text(242, 202, '120°', 15, 'amber', True)


