def practice(n,result=None,**kwargs):
    entry=build_card(n,pages=[243],**kwargs)
    entry['help'][1]['theoryIds']=['atanasyan-7-9-theory-92-part-1']
    entry['review']['reviewer']='Печатные с. 243 и 397 издания Атанасяна 2023 года, глава X. Исходные данные, единицы, расстояния и геометрические зависимости проверены независимо.'
