def compass_draw(title,method,stage,R):
    n={'hex':6,'tri':6,'square':4,'oct':8}[method]
    names=['A','B','C','D','E','F','G','J'][:n]
    p=dict(zip(names,ring(n,R,0),strict=True));p['T']=(0,0)
    edges=[];marks=[];aux=None
    if method=='hex':
        if stage==0:
            keep=['A','B','T'];p={k:p[k] for k in keep}
            edges=[('T','A'),('T','B'),('A','B')];aux=('A','T')
        elif stage==1:
            keep=['A','B','C','T'];p={k:p[k] for k in keep}
            edges=[('A','B'),('B','C'),('B','T'),('T','C')];aux=('B','T')
        else:edges=outline(names)
        marks=edges
    elif method=='tri':
        edges=outline(names)
        if stage==0:marks=[('A','B'),('B','C')];aux=('A','T')
        elif stage==1:
            edges.append(('A','C'));marks=[('A','C'),('T','A'),('T','C')];edges.extend(marks[1:])
        else:
            triangle=['A','C','E'];edges.extend(outline(triangle));marks=outline(triangle)
    elif method=='square':
        if stage==0:
            p={k:p[k] for k in ['A','C','T']};edges=[('A','C')];marks=edges
        else:
            edges=[('A','C'),('B','D')]
            if stage==1:marks=edges
            else:edges.extend(outline(names));marks=outline(names)
    else:
        old=['A','C','E','G']
        edges=outline(old)
        if stage==0:
            p={k:p[k] for k in old+['T']};marks=edges
        elif stage==1:
            p={k:p[k] for k in old+['B','T']};p['H']=tuple((a+b)/2 for a,b in zip(p['A'],p['C']))
            edges.extend([('T','B'),('A','H'),('C','H'),('A','B'),('B','C')]);marks=[('T','B'),('A','B'),('B','C')]
        else:edges.extend(outline(names));marks=outline(names)
    return graph(title,p,edges=edges,circle=('T',R),lines=[(p[a],p[b]) for a,b in marks]),aux


