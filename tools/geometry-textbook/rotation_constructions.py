def rotated(p,center,degrees):
    x,y=p[0]-center[0],p[1]-center[1]
    co,si=cos(radians(degrees)),sin(radians(degrees))
    return round(center[0]+co*x-si*y,9),round(center[1]+si*x+co*y,9)


def turning_arrow(center,anchor,degrees):
    cx,cy=center
    dx,dy=anchor[0]-cx,anchor[1]-cy
    radius=min(1.4,.58*hypot(dx,dy))
    start=atan2(dy,dx)
    end=start+radians(degrees)
    direction=1 if degrees>0 else -1
    positions=[(cx+radius*cos(start+i*(end-start)/18),cy+radius*sin(start+i*(end-start)/18)) for i in range(19)]
    tip=positions[-1];tx=-direction*sin(end);ty=direction*cos(end)
    side=min(.16,radius*.16);length=side*1.8
    return [*zip(positions,positions[1:]),*[(tip,(tip[0]-length*tx-k*side*ty,tip[1]-length*ty+k*side*tx)) for k in (-1,1)]]


def picture(title,points,edges,center,origin,degrees):
    arc=turning_arrow(points[center],points[origin],degrees)
    left=min(x for x,y in points.values()); low=min(y for x,y in points.values())-1.45
    return graph(title,{**points,'U':(left,low),'W':(left+1,low)},edges=[*edges,('U','W')],lines=arc)


def rotate_figure(title,points,edges,center,pivot,degrees):
    middle=points[center]
    moving=[label for label in points if label!=center or label=='A']
    image={label+'′':rotated(points[label],middle,degrees) for label in moving}
    rays=[(center,label) for label in [pivot,pivot+'′']]
    if 'B' in points and pivot!='B':
        rays.extend([(center,'B'),(center,'B′')])
    return picture(title,{**points,**image},[*edges,*[(a+'′',b+'′') for a,b in edges],*rays],center,pivot,degrees)


