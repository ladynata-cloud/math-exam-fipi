def add(a,b):
    return a[0]+b[0],a[1]+b[1]

def neg(a):
    return -a[0],-a[1]

def scale(a,k):
    return k*a[0],k*a[1]

def copy_figure(label,pts,arrows,lines):
    return frame(label,pts,[tuple(s) for s in arrows.split()],[tuple(s) for s in lines.split()])


def visual_card(n,pages,question,answer,hint,steps,views,checks,refs,note):
    entry=card(n,None,pages,question,answer,hint,steps,views,checks,refs,caption=note)
    model=entry['visualization']['model']
    for i,(view,source) in enumerate(zip(model['views'].values(),[views[0],*views,*views],strict=True)):
        arrows=source[2];suffix='__v'+str(i)
        shafts=[[a+suffix,b+suffix] for a,b in arrows]
        heads=[segment for segment in view['segments'] if segment[1].startswith('head_')]
        view['highlightSegments']=shafts+heads
    entry['help'][1]['text']='Раскрой произведение по распределительному закону. Соотнеси каждое слагаемое с длиной или углом на чертеже.'
    entry['answer']['prompt']='Запиши обоснование и проверь его на новом чертеже.'
    return entry


