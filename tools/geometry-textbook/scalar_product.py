def common_view(label,first,second,*,plain=(False,False),projections=False):
    pts={'P':(0,0),'X':first,'Y':second}
    # If the exact translated ends coincide, one visible point represents both vectors.
    equal=all(abs(a-b)<1e-8 for a,b in zip(first,second))
    if equal or second==(0,0):del pts['Y']
    if first==(0,0):del pts['X']
    pairs=[('P','X'),('P','X' if equal else 'Y')]
    arrows=[];lines=[]
    for pair,line in zip(pairs,plain):
        dest=lines if line else arrows
        if pair not in dest and pair[1] in pts:dest.append(pair)
    if projections:
        for endpoint,foot in [('X','H'),('Y','K')]:
            if endpoint not in pts:continue
            x,y=pts[endpoint]
            if x and y:
                pts[foot]=(x,0)
                lines.extend([('P',foot),(foot,endpoint)])
    return frame(label,pts,arrows,lines)


def data_pair(label,degrees,a=2,b=3):
    th=radians(degrees)
    return common_view(label,(a,0),(round(b*cos(th),12),round(b*sin(th),12)))


