def angles(label,side,B,C):
    # The scale is fixed within each task; the larger field survey uses kilometres on paper.
    A=180-B-C;c=side*sin(radians(C))/sin(radians(A))
    h=(c*cos(radians(B)),c*sin(radians(B)))
    return graph(label,{'A':h,'B':(0,0),'C':(side,0),'H':(h[0],0)},edges=[('A','B'),('A','C'),('B','C'),('A','H'),('C','H')])


