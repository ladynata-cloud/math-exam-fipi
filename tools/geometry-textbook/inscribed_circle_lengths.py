def length(a,b):
    return hypot(a[0]-b[0],a[1]-b[1])


def triangle_view(title,vertices,outside,focus):
    a,b,c=vertices;lab='ABC'
    x0,y0=a;x1,y1=b;x2,y2=c
    if outside:
        bx,by=x1-x0,y1-y0;cx,cy=x2-x0,y2-y0
        db,dc=bx*bx+by*by,cx*cx+cy*cy
        den=2*(bx*cy-by*cx)
        t=(x0+(cy*db-by*dc)/den,y0+(bx*dc-cx*db)/den)
        rad=length(t,a)
    else:
        weights=[length(b,c),length(c,a),length(a,b)]
        t=tuple(sum(w*p[j] for w,p in zip(weights,vertices,strict=True))/sum(weights) for j in (0,1))
        rad=abs((x1-x0)*(t[1]-y0)-(y1-y0)*(t[0]-x0))/length(a,b)
    pts=dict(zip(lab,vertices,strict=True));pts['T']=t
    edges=outline(lab);selected=[]
    if outside:
        edges.extend(('T',k) for k in lab)
        selected=[('T','C')] if focus else [('A','B')]
        if len(set(round(v,6) for v in (length(a,c),length(b,c))))==1:
            pts['H']=((x0+x1)/2,(y0+y1)/2);edges.append(('C','H'))
    else:
        for k,(start,end) in zip('HKL',outline(lab),strict=True):
            p,q=pts[start],pts[end];u=(q[0]-p[0],q[1]-p[1]);v=(t[0]-p[0],t[1]-p[1])
            projection=(v[0]*u[0]+v[1]*u[1])/(u[0]*u[0]+u[1]*u[1])
            pts[k]=(p[0]+projection*u[0],p[1]+projection*u[1]);edges.extend([('T',k),(start,k),(end,k)])
        edges.append(('A','T'));selected=[('T','H'),('T','K'),('T','L')] if focus else [('A','B'),('A','T')]
    pts['U']=(min(x for x,y in vertices),min(y for x,y in vertices)-.9)
    pts['W']=(pts['U'][0]+1,pts['U'][1]);edges.append(('U','W'))
    return drawing(title,pts,edges,'T',rad,selected)


def polygon_view(title,kind,sizes,focus):
    if kind=='rectangle':
        w,h=sizes
        p={'A':(-w/2,-h/2),'B':(w/2,-h/2),'C':(w/2,h/2),'D':(-w/2,h/2),'T':(0,0)}
        r=hypot(w,h)/2;edges=outline('ABCD')+[('A','C'),('B','D'),('T','C')];selected=[('A','C'),('T','A'),('T','D')] if focus else [('B','C')]
    elif kind=='hexagon':
        r=sizes[0];names='ABCDEF';p=dict(zip(names,ring(6,r,0),strict=True));p['T']=(0,0)
        edges=outline(names)+[('T',k) for k in names];selected=[('T','A'),('A','B'),('B','T')]
    else:
        r=sizes[0]/2
        p={'A':(-r,-r),'B':(r,-r),'C':(r,r),'D':(-r,r),'T':(0,0),'H':(0,-r),'K':(r,0)}
        edges=outline('ABCD')+[('T','H'),('T','K'),('A','H'),('B','K')];selected=[('T','H'),('A','B')] if focus else [('A','B')]
    low=min(y for x,y in p.values());left=min(x for x,y in p.values())
    p['U']=(left,low-.9);p['W']=(left+1,low-.9);edges.append(('U','W'))
    return drawing(title,p,edges,'T',r,selected)


def scenes(kind,values,outside):
    result=[]
    for idx,configuration in enumerate([values[0],values[0],values[1]]):
        label=('Прочитай данные фигуры','Выдели искомый радиус','Проверь на новой фигуре')[idx]
        if kind=='eq':
            side=configuration[0];points=[(0,0),(side,0),(side/2,side*sqrt(3)/2)]
        elif kind=='right':
            a,b=configuration;points=[(0,0),(a,0),(0,b)]
        elif kind=='isosceles':
            a,h=configuration;points=[(0,0),(a,0),(a/2,h)]
        else:
            result.append(polygon_view(label,kind,configuration,idx>0));continue
        result.append(triangle_view(label,points,outside,idx>0))
    return result


